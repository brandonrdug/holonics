"""Generate a terrain of interacting digits for the tower: sums, differences and products of two
operands drawn from 0..N-1, so every place carries uniform digits and the carry is exercised (the
GSM8K passage's own sums carry out of 21% of places, uniform digits out of 45-50%). One expression a
line, written `a+b=c`, `a-b=c` (a >= b) and `a*b=c`. The truth is generated by exact integer
arithmetic: a terrain may generate its truth, and only its text reaches the machine.

Held out: an operand pair is held out of training when the keyed SHA-256 of its operation and its
operands falls below HELD_PER_MILLE thousandths. For + and * the key reads the unordered pair, so a
commuted pair is held out with it and never seen; for - the pair is already ordered.

Writes to OUT_DIR (which must not exist):
- train.txt: every expression not held out, each once, in the keyed order;
- dev.txt: every held-out expression and an equal count of training expressions, alternating;
- dev.roles: one region byte per dev.txt byte. 0: a content digit of an unseen result; 1: a content
  digit of a seen result; 2: a result's scale (its trailing zeros; the result 0 is content);
  3: everything else (operands, signs, the line's end).

usage: python3 -I arithmetic_terrain.py N HELD_PER_MILLE KEY OUT_DIR
"""
import hashlib
import os
import sys

OPERATIONS = "+-*"


def keyed(key, text):
    return hashlib.sha256(f"{key}:{text}".encode()).digest()


def expressions(n):
    for op in OPERATIONS:
        for a in range(n):
            for b in range(n):
                if op == "-" and a < b:
                    continue
                c = a + b if op == "+" else a - b if op == "-" else a * b
                yield op, a, b, c


def held(key, op, a, b, per_mille):
    pair = f"{min(a, b)},{max(a, b)}" if op in "+*" else f"{a},{b}"
    return int.from_bytes(keyed(key, f"held:{op}:{pair}")[:4], "big") % 1000 < per_mille


def line(op, a, b, c):
    return f"{a}{op}{b}={c}\n"


def roles(op, a, b, c, unseen):
    head = f"{a}{op}{b}="
    result = str(c)
    content = len(result.rstrip("0")) if c else 1
    regions = [3] * len(head)
    regions += [0 if unseen else 1] * content + [2] * (len(result) - content)
    return regions + [3]


def main():
    n, per_mille, key, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3], sys.argv[4]
    os.mkdir(out)
    kept, out_of = [], []
    for e in expressions(n):
        (out_of if held(key, *e[:3], per_mille) else kept).append(e)
    order = lambda e: keyed(key, f"order:{e[0]}:{e[1]},{e[2]}")
    kept.sort(key=order)
    out_of.sort(key=order)
    seen = sorted(kept, key=lambda e: keyed(key, f"seen:{e[0]}:{e[1]},{e[2]}"))[: len(out_of)]
    with open(os.path.join(out, "train.txt"), "x") as f:
        f.write("".join(line(*e) for e in kept))
    text, regions = [], []
    for unseen, seen_one in zip(out_of, seen):
        for e, is_unseen in ((unseen, True), (seen_one, False)):
            text.append(line(*e))
            regions += roles(*e, is_unseen)
    dev = "".join(text)
    assert len(dev) == len(regions)
    with open(os.path.join(out, "dev.txt"), "x") as f:
        f.write(dev)
    with open(os.path.join(out, "dev.roles"), "xb") as f:
        f.write(bytes(regions))
    counts = [regions.count(r) for r in range(4)]
    print(f"TERRAIN n={n} kept={len(kept)} held={len(out_of)} train_bytes={sum(len(line(*e)) for e in kept)} "
          f"dev_bytes={len(dev)} unseen_digits={counts[0]} seen_digits={counts[1]} scale_zeros={counts[2]} rest={counts[3]}")


if __name__ == "__main__":
    main()
