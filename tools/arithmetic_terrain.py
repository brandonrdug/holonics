"""Generate a terrain of interacting digits for the tower: sums, differences and products of two
operands drawn from 0..N-1, so every place carries uniform digits and the carry is exercised (the
GSM8K passage's own sums carry out of 21% of places, uniform digits out of 45-50%). One expression a
line, written `a+b=c`, `a-b=c` (a >= b) and `a*b=c`. The truth is generated by exact integer
arithmetic: a terrain may generate its truth, and only its text reaches the machine.

Held out: an operand pair is held out of training when the keyed SHA-256 of its operation and its
operands falls below HELD_PER_MILLE thousandths. For + and * the key reads the unordered pair, so a
commuted pair is held out with it and never seen; for - the pair is already ordered.

Writes to OUT_DIR (which must not exist):
- train.txt: every expression not held out, each once, in the keyed order;
- dev.txt: every held-out expression and an equal count of training expressions, alternating;
- dev.roles: one region byte per dev.txt byte. 0: a content digit of an unseen result; 1: a content
  digit of a seen result; 2: a result's scale (its trailing zeros; the result 0 is content);
  3: everything else (operands, signs, the line's end).

usage: python3 -I arithmetic_terrain.py N HELD_PER_MILLE KEY OUT_DIR

The drawn terrain, for a passage's own markup:
  python3 -I arithmetic_terrain.py drawn LENGTH COUNT KEY EXCLUDE_TEXT OUT_DIR
draws COUNT expressions of each of +, -, * and / with each operand's length uniform in 1..LENGTH and
its digits uniform (a leading digit nonzero); a quotient is exact, a = q*b with q and b drawn so. It
writes OUT_DIR/terrain.txt, one `<<a op b=c>>c` a line (the calculation markup of the prepared
GSM8K text), and leaves out every operand pair that EXCLUDE_TEXT calculates (unordered for + and *),
so a held-out problem's calculation is never met in the terrain.

  python3 -I arithmetic_terrain.py interleave PASSAGE TERRAIN OUT
spreads the terrain's lines evenly through a passage of problems separated by a blank line: after
problem i the lines from floor(i T / P) to floor((i + 1) T / P), as one paragraph of their own.
"""
import hashlib
import os
import re
import sys

OPERATIONS = "+-*"


def keyed(key, text):
    return hashlib.sha256(f"{key}:{text}".encode()).digest()


def expressions(n):
    for op in OPERATIONS:
        for a in range(n):
            for b in range(n):
                if op == "-" and a < b:
                    continue
                c = a + b if op == "+" else a - b if op == "-" else a * b
                yield op, a, b, c


def held(key, op, a, b, per_mille):
    pair = f"{min(a, b)},{max(a, b)}" if op in "+*" else f"{a},{b}"
    return int.from_bytes(keyed(key, f"held:{op}:{pair}")[:4], "big") % 1000 < per_mille


def line(op, a, b, c):
    return f"{a}{op}{b}={c}\n"


def roles(op, a, b, c, unseen):
    head = f"{a}{op}{b}="
    result = str(c)
    content = len(result.rstrip("0")) if c else 1
    regions = [3] * len(head)
    regions += [0 if unseen else 1] * content + [2] * (len(result) - content)
    return regions + [3]


def main():
    n, per_mille, key, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3], sys.argv[4]
    os.mkdir(out)
    kept, out_of = [], []
    for e in expressions(n):
        (out_of if held(key, *e[:3], per_mille) else kept).append(e)
    order = lambda e: keyed(key, f"order:{e[0]}:{e[1]},{e[2]}")
    kept.sort(key=order)
    out_of.sort(key=order)
    seen = sorted(kept, key=lambda e: keyed(key, f"seen:{e[0]}:{e[1]},{e[2]}"))[: len(out_of)]
    with open(os.path.join(out, "train.txt"), "x") as f:
        f.write("".join(line(*e) for e in kept))
    text, regions = [], []
    for unseen, seen_one in zip(out_of, seen):
        for e, is_unseen in ((unseen, True), (seen_one, False)):
            text.append(line(*e))
            regions += roles(*e, is_unseen)
    dev = "".join(text)
    assert len(dev) == len(regions)
    with open(os.path.join(out, "dev.txt"), "x") as f:
        f.write(dev)
    with open(os.path.join(out, "dev.roles"), "xb") as f:
        f.write(bytes(regions))
    counts = [regions.count(r) for r in range(4)]
    print(f"TERRAIN n={n} kept={len(kept)} held={len(out_of)} train_bytes={sum(len(line(*e)) for e in kept)} "
          f"dev_bytes={len(dev)} unseen_digits={counts[0]} seen_digits={counts[1]} scale_zeros={counts[2]} rest={counts[3]}")


def number(key, label, length):
    """A number of `length` digits, each uniform, its leading digit nonzero unless it is one digit."""
    raw = int.from_bytes(keyed(key, label)[:8], "big")
    low = 0 if length == 1 else 10 ** (length - 1)
    return low + raw % (10**length - low)


def calculations(text):
    pairs = set()
    for a, op, b in re.findall(rb"<<(\d+)([-+*/])(\d+)=", text):
        a, b, op = int(a), int(b), op.decode()
        pairs.add((op, min(a, b), max(a, b)) if op in "+*" else (op, a, b))
    return pairs


def drawn(length, count, key, exclude, out):
    os.mkdir(out)
    excluded = calculations(open(exclude, "rb").read())
    lines, left_out = [], 0
    for op in "+-*/":
        k, kept = 0, 0
        while kept < count:
            label = f"drawn:{op}:{k}"
            k += 1
            la = 1 + keyed(key, label + ":la")[0] % length
            lb = 1 + keyed(key, label + ":lb")[0] % length
            a, b = number(key, label + ":a", la), number(key, label + ":b", lb)
            if op == "-" and a < b:
                a, b = b, a
            if op == "/":
                if b == 0:
                    continue
                a, b = a * b, b
            pair = (op, min(a, b), max(a, b)) if op in "+*" else (op, a, b)
            if pair in excluded:
                left_out += 1
                continue
            c = a + b if op == "+" else a - b if op == "-" else a * b if op == "*" else a // b
            lines.append((op, f"<<{a}{op}{b}={c}>>{c}\n"))
            kept += 1
    lines.sort(key=lambda l: keyed(key, "order:" + l[1]))
    text = "".join(l[1] for l in lines)
    with open(os.path.join(out, "terrain.txt"), "x") as f:
        f.write(text)
    print(f"TERRAIN_DRAWN length={length} count={count} lines={len(lines)} bytes={len(text)} left_out={left_out}")


def interleave(passage, terrain, out):
    problems = open(passage, "rb").read().split(b"\n\n")
    if problems[-1] == b"":
        problems.pop()
    lines = open(terrain, "rb").read().splitlines(keepends=True)
    p, t = len(problems), len(lines)
    parts = []
    for i, problem in enumerate(problems):
        parts.append(problem + b"\n\n")
        block = lines[i * t // p:(i + 1) * t // p]
        if block:
            parts.append(b"".join(block) + b"\n")
    with open(out, "xb") as f:
        f.write(b"".join(parts))
    print(f"INTERLEAVED problems={p} terrain_lines={t} bytes={sum(len(x) for x in parts)}")


if __name__ == "__main__":
    if sys.argv[1] == "drawn":
        drawn(int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], sys.argv[5], sys.argv[6])
    elif sys.argv[1] == "interleave":
        interleave(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        main()
