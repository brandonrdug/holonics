"""P59 item 2 (G138's premise read before anything is built): the contact's copies, one mechanism a copy, generated from the entries' own source.

Each copy is the entry's text from crates/holonics-cuda/kernels/field.cu with the named substitutions and nothing else (each substitution's
count is asserted), renamed `field_copy_<mechanism>_<entry>`, written to crates/holonics-cuda/kernels/field_copies.cuh, which field.cu includes
only under RULER_COPIES (the ruler build `ruler-copies`). A copy is launched immediately before its entry on the entry's words, with every
array the entry writes moved to a scratch array of the same layout that starts as the entry's (field.rs), so the state's bytes are the law's.

The mechanisms:
  n  the entry as it stands (the instrument's own control: a copy run before its entry on the same words).
  r  source rows resident, an upper bound: every load of another site's row reads the warp's own site's row (same instructions, same words):
     a source's qf and qf32 rows in the exposure, its vf rows in the forward contact's numerators, its vf and qf rows in the rows and in the
     skin's return; a receiver's dyh and pq rows in the columns.
  w  a pair's words in walk order: e, sb, ds and dpb read and written at the row's entry index (the lane's k wrapped under the region's
     sites) in place of the source's place j: the exposure, the forward contact, the rows, the skin's return.
  a  the reductions as plain stores: every atomic sum a plain store at the lane's own address in scratch (`plain`): cv, cw, gcov and dsshare
     in the rows; gsig in the skin's return.
  c  the columns from a record in column order: ds, e, the skin's words and the receiver's place read in order along a source's receivers
     from scratch arrays laid in that order (field_copy_c_columns_record copies the entry's own words there, at the source's row of the
     region's dense block), with no walk of the class lists (receiver_at) and no support_entry.

usage: python3 tools/contact_copies.py [--check]   (--check: refuse when the header on disk differs from what the source gives)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELD = ROOT / "crates/holonics-cuda/kernels/field.cu"
OUT = ROOT / "crates/holonics-cuda/kernels/field_copies.cuh"


def function(src, signature):
    """The text of the function whose definition starts with `signature` (a template line before it included), through its closing brace."""
    at = src.index(signature)
    start = src.rfind("\n", 0, at) + 1
    if src[start:at].strip() == "" and src[max(0, start - 30):start].rstrip().endswith("template <int L>"):
        start = src.rfind("\n", 0, start - 1) + 1
    depth, i = 0, src.index("{", at)
    while True:
        ch = src[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
        i += 1


def sub(text, rules, label):
    for old, new, count, regex in rules:
        found = len(re.findall(old, text)) if regex else text.count(old)
        if found != count:
            raise SystemExit(f"{label}: {old!r} occurs {found} times, {count} expected")
        text = re.sub(old, new, text) if regex else text.replace(old, new)
    return text


def main():
    src = FIELD.read_text()
    exposure = function(src, "extern \"C\" __global__ void __launch_bounds__(CONTACT_ROWS * 32, 8) field_exposure(")
    contact = function(src, "__device__ void contact_body(const FieldWords &w, uint32_t store)")
    rows = function(src, "extern \"C\" __global__ void __launch_bounds__(REV_ROWS * 32, 4) field_contact_rows(")
    columns = function(src, "extern \"C\" __global__ void __launch_bounds__(CONTACT_ROWS * 32) field_contact_columns(")
    skin = function(src, "extern \"C\" __global__ void __launch_bounds__(CONTACT_ROWS * 32) field_pace_skin_back(")
    assert contact.startswith("template <int L>"), contact[:40]
    plain = (r"add_wide\(([^;]*?), ([^;]*)\);", r"plain[(uint64_t)blockIdx.x * blockDim.x + threadIdx.x] = (\2);")
    out = [
        "// Generated by tools/contact_copies.py from field.cu's entries (P59 item 2): the contact's copies, one mechanism a copy. Do not edit;",
        "// run the tool. Compiled only in the ruler build (RULER_COPIES); no learner's build includes it.",
        "",
        "// The ruler's count of checked products that took their long path (`RULER_LONG`), raised only while a copy runs.",
        "extern \"C\" __global__ void field_ruler_counting(int on, int reset) {",
        "    if (threadIdx.x == 0 && blockIdx.x == 0) {",
        "        ruler_counting = on;",
        "        if (reset) {",
        "            ruler_long = 0;",
        "        }",
        "    }",
        "}",
        "",
        "extern \"C\" __global__ void field_ruler_long_read(unsigned long long *out) {",
        "    if (threadIdx.x == 0 && blockIdx.x == 0) {",
        "        out[0] = ruler_long;",
        "    }",
        "}",
        "",
        "// The check of a copy that must give its entry's words (the null copy, the columns from their record): the 64-bit words of two arrays",
        "// that differ, counted.",
        "extern \"C\" __global__ void field_ruler_diff(const uint64_t *a, const uint64_t *b, uint64_t words, unsigned long long *count) {",
        "    unsigned long long local = 0;",
        "    for (uint64_t c = (uint64_t)blockIdx.x * blockDim.x + threadIdx.x; c < words; c += (uint64_t)gridDim.x * blockDim.x) {",
        "        local += a[c] != b[c] ? 1ull : 0ull;",
        "    }",
        "    if (local) {",
        "        atomicAdd(count, local);",
        "    }",
        "}",
        "",
        "// (w)'s inputs laid in walk order: each row's pair words moved from the source's place j to the row's entry index (the lane's k wrapped under",
        "// the region's sites), the row's support walked as the entries walk it (`row_prepare`, `support_at`), so a (w) copy reads the words its entry",
        "// reads at the addresses (w) gives them. Heads `h_first` to `h_first + h_count`, `head_stride` words apart (zero: an array with no head).",
        "extern \"C\" __global__ void __launch_bounds__(CONTACT_ROWS * 32) field_copy_w_walk(FieldWords w, uint32_t h_first, uint32_t h_count, const uint64_t *src, uint64_t *dst, uint64_t head_stride) {",
        "    __shared__ RowCls rcs[CONTACT_ROWS];",
        "    const uint32_t warp = threadIdx.x >> 5, lane = threadIdx.x & 31;",
        "    const uint32_t classes = w.nclasses;",
        "    const uint64_t rows = (uint64_t)h_count * w.T;",
        "    for (uint64_t x = ((uint64_t)blockIdx.x * blockDim.x + threadIdx.x) >> 5; x < rows; x += (uint64_t)gridDim.x * (blockDim.x >> 5)) {",
        "        const uint32_t h = h_first + (uint32_t)(x / w.T);",
        "        const uint64_t g = x % w.T;",
        "        const uint64_t hg = (uint64_t)h * w.T + g;",
        "        if (skipped_row(w, g)) {",
        "            continue;",
        "        }",
        "        const uint32_t r = w.site_region[g];",
        "        const uint64_t first = w.region_off[r];",
        "        const uint32_t sites = w.region_off[r + 1] - (uint32_t)first, i = w.site_pos[g];",
        "        const uint32_t *members = w.members + (uint64_t)h * w.T + first;",
        "        const uint32_t *off = w.class_off + ((uint64_t)h * w.R + r) * (2 * classes + 1);",
        "        const uint32_t K = row_prepare(w, hg, off, rcs[warp], lane);",
        "        const uint64_t base = (uint64_t)h * head_stride + w.region_eoff[r] + (uint64_t)i * sites;",
        "        for (uint32_t k = lane; k < K; k += 32) {",
        "            const uint32_t j = support_at(members, off, rcs[warp], i, sites, k);",
        "            if (j != UINT32_MAX) {",
        "                dst[base + k % sites] = src[base + j];",
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ]

    def kernel(text, old_name, new_name, rules, label, extra_param=None):
        t = sub(text, [(old_name, new_name, 1, False)] + rules, label)
        if extra_param:
            sig_end = t.index(") {")
            t = t[:sig_end] + extra_param + t[sig_end:]
        out.extend([f"// {label}", t, ""])

    # The exposure.
    for mech, rules in {
        "n": [],
        "r": [("rows32 + (uint64_t)j * 4", "rows32 + (uint64_t)i * 4", 1, False), ("words + (uint64_t)j * S", "words + (uint64_t)i * S", 1, False)],
        "w": [("erow[j] = (uint64_t)z;", "erow[k % sites] = (uint64_t)z;", 1, False), ("sbrow[j] = base;", "sbrow[k % sites] = base;", 1, False)],
    }.items():
        kernel(exposure, "field_exposure(", f"field_copy_{mech}_exposure(", rules, f"field_exposure, mechanism {mech}")
    # The forward contact: the body a copy a mechanism, and its entries at five and six limbs.
    for mech, rules in {
        "n": [],
        "r": [("values[(uint64_t)j * S + entry]", "values[(uint64_t)i * S + entry]", 2, False)],
        "w": [(r"\berow\[j\]", "erow[k % sites]", 3, True)],
    }.items():
        body = sub(contact, [("contact_body(", f"contact_body_copy_{mech}(", 1, False)] + rules, f"contact_body, mechanism {mech}")
        out.extend([f"// contact_body, mechanism {mech}", body, ""])
        for limbs in (5, 6):
            out.append(f"extern \"C\" __global__ void __launch_bounds__(CONTACT_ROWS * 32, CONTACT_MIN_BLOCKS) field_copy_{mech}_contact_l{limbs}(FieldWords w, uint32_t store) {{ contact_body_copy_{mech}<{limbs}>(w, store); }}")
        out.append("")
    # The rows.
    for mech, rules in {
        "n": [],
        "r": [("values + (uint64_t)j * S", "values + (uint64_t)i * S", 2, False), ("words[(uint64_t)jx * S + entry]", "words[(uint64_t)i * S + entry]", 1, False)],
        "w": [(r"\be\[j\]", "e[k % sites]", 2, True), (r"\bdpr\[j\]", "dpr[k % sites]", 2, True), (r"\bsbr\[j\]", "sbr[k % sites]", 1, True), ("dsr[j] = dsv;", "dsr[k % sites] = dsv;", 1, False)],
        "a": [(plain[0], plain[1], 7, True)],
    }.items():
        kernel(rows, "field_contact_rows(", f"field_copy_{mech}_contact_rows(", rules, f"field_contact_rows, mechanism {mech}", ", wide *plain" if mech == "a" else None)
    # The columns.
    for mech, rules in {
        "n": [],
        "r": [("w.pq[((uint64_t)h * w.T + first + i) * S + entry]", "w.pq[((uint64_t)h * w.T + first + j) * S + entry]", 1, False), ("dyr[(uint64_t)i * S + entry]", "dyr[(uint64_t)j * S + entry]", 1, False)],
    }.items():
        kernel(columns, "field_contact_columns(", f"field_copy_{mech}_contact_columns(", rules, f"field_contact_columns, mechanism {mech}")
    # (c): the record in column order, then the columns read from it.
    walk = """                const uint32_t i = receiver_at(members, off, pmem, poff, olist, c, j, sites, k);
                if (i == UINT32_MAX || skipped_row(w, first + i)) {
                    continue;
                }
                const uint64_t at = (uint64_t)i * sites;
                const uint32_t gap = j > i ? j - i : i - j;
                // The pair's support entry in receiver `i`'s row (`support_entry`), where the clock's skins stand: read only on a paced head
                // whose pace is not plain there, the one row that reads the store.
                const uint64_t sentry = paced_c && paced_at(w, h, first + i) ? support_row(w, r, i) + support_entry(w, h, r, first, members, off, i, j) : 0;
                const wide dec = skin_raw_at(w, h, m, first + i, sentry, gap);
                // The key's bracket released by the skin's bits once (the probe's grain), then by the covector,
                // against the receiver's probe (§16.19).
                const int64_t probe_i = w.pq[((uint64_t)h * w.T + first + i) * S + entry];
                sk += (wide)dsc[at] * rel(((dec * (wide)probe_i) << g0) - dec * dec * (wide)words[(uint64_t)j * S + entry], g0);
                sv += (wide)e[at] * carried_ij_at(w, h, m, first + i, sentry, gap, dyr[(uint64_t)i * S + entry]);"""
    read = """                const uint64_t rk = rbase + k;
                const uint32_t i = rec_i[rk];
                if (i == UINT32_MAX) {
                    continue;
                }
                const wide dec = (wide)rec_dec[rk * n + m];
                const int64_t probe_i = w.pq[((uint64_t)h * w.T + first + i) * S + entry];
                sk += (wide)rec_ds[rk] * rel(((dec * (wide)probe_i) << g0) - dec * dec * (wide)words[(uint64_t)j * S + entry], g0);
                const int64_t vy = dyr[(uint64_t)i * S + entry];
                sv += (wide)rec_e[rk] * (still ? (wide)vy : rel(dec * (wide)vy, MOVE_BITS));"""
    record_body = """                const uint32_t i = receiver_at(members, off, pmem, poff, olist, c, j, sites, k);
                const uint64_t rk = rbase + k;
                if (i == UINT32_MAX || skipped_row(w, first + i)) {
                    rec_i[rk] = UINT32_MAX;
                    continue;
                }
                const uint64_t at = (uint64_t)i * sites;
                const uint32_t gap = j > i ? j - i : i - j;
                const uint64_t sentry = paced_c && paced_at(w, h, first + i) ? support_row(w, r, i) + support_entry(w, h, r, first, members, off, i, j) : 0;
                rec_i[rk] = i;
                rec_ds[rk] = dsc[at];
                rec_e[rk] = e[at];
                for (uint32_t l = 0; l < n; l++) {
                    rec_dec[rk * n + l] = (uint32_t)skin_raw_at(w, h, l, first + i, sentry, gap);
                }"""
    base = """        const int64_t *dyr = dyh + ((uint64_t)h * w.T + first) * S;"""
    rbase = base + """
        // The source's record from its offset (P59 (c)): its receivers in column order, `K` of them (a receiver heard twice stands twice).
        const uint64_t rbase = rec_off[g];"""
    params_c = ", const uint64_t *rec_off, const uint32_t *rec_i, const int64_t *rec_ds, const uint64_t *rec_e, const uint32_t *rec_dec"
    copy_c = sub(columns, [("field_contact_columns(", "field_copy_c_contact_columns(", 1, False), (walk, read, 1, False), (base, rbase, 1, False)], "field_contact_columns, mechanism c")
    copy_c = copy_c[:copy_c.index(") {")] + params_c + copy_c[copy_c.index(") {"):]
    # The record: the walk alone, every lane a receiver (k from the lane, a step of 32), the sums and their outputs left out.
    rec = sub(columns, [("field_contact_columns(", "field_copy_c_columns_record(", 1, False), (walk, record_body, 1, False), (base, rbase, 1, False),
                        ("for (uint32_t k = part; k < K; k += parts) {", "for (uint32_t k = lane; k < K; k += 32) {", 1, False)], "the columns' record")
    head, tail = rec.index("        sk = parts_sum("), rec.index("    }\n}")
    rec = rec[:head] + rec[tail:]
    rec = rec.replace("if (part < parts) {", "{", 1)
    rec = rec[:rec.index(") {")] + ", const uint64_t *rec_off, uint32_t *rec_i, int64_t *rec_ds, uint64_t *rec_e, uint32_t *rec_dec" + rec[rec.index(") {"):]
    # The count of each source's receivers, the record's offsets read from it on the host.
    count = sub(columns, [("field_contact_columns(", "field_copy_c_columns_count(", 1, False)], "the columns' count")
    cut = count.index("        const uint64_t *e = w.e + (uint64_t)h * w.E + w.region_eoff[r] + j;")
    count = count[:cut] + "        if (lane == 0) {\n            kout[g] = K;\n        }\n    }\n}"
    count = count[:count.index(") {")] + ", uint32_t *kout" + count[count.index(") {"):]
    out.extend(["// field_contact_columns, mechanism c: each source's count of receivers", count, "", "// field_contact_columns, mechanism c: the record in column order", rec, "",
                "// field_contact_columns, mechanism c", copy_c, ""])
    # The skin's return.
    for mech, rules in {
        "n": [],
        "r": [("values[(uint64_t)j * S + l]", "values[(uint64_t)i * S + l]", 1, False), ("values[(uint64_t)j * S + n + l]", "values[(uint64_t)i * S + n + l]", 1, False),
              ("words[(uint64_t)j * S + l]", "words[(uint64_t)i * S + l]", 1, False), ("words[(uint64_t)j * S + n + l]", "words[(uint64_t)i * S + n + l]", 1, False)],
        "w": [(r"\be\[j\]", "e[k % sites]", 1, True), (r"\bdsr\[j\]", "dsr[k % sites]", 1, True)],
        "a": [(plain[0], plain[1], 3, True)],
    }.items():
        kernel(skin, "field_pace_skin_back(", f"field_copy_{mech}_pace_skin_back(", rules, f"field_pace_skin_back, mechanism {mech}", ", wide *plain" if mech == "a" else None)
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            raise SystemExit("field_copies.cuh is not what field.cu's entries give: run tools/contact_copies.py")
        print("field_copies.cuh matches its source")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10))} lines, {text.count('__global__')} entries")


if __name__ == "__main__":
    main()
