/// **The probe**: a bounded dry run of one mode's engine, its milliseconds a refinement and a
/// deposit and its resident set, from which the pinned run is projected.
fn probe(mode: &str, cut: Option<&str>) {
    let clock = Instant::now();
    let (declared, pairs) = match mode {
        "copy" => (terrain_declared(), copy_pairs(&terrain_declared(), 1, 32)),
        "order2" => (order_declared(false), order_pairs(&order_declared(false), 1, 32)),
        "order2-pinned" => (order_declared(true), order_pairs(&order_declared(true), 1, 32)),
        "moire" => {
            let moire = Moire::draw(&MOIRE_FAMILY, MoireClass::Sheets, &mut Draw::new(MOIRE_SEED))
                .expect("the moiré");
            (terrain_declared(), moire_pairs(&moire, &terrain_declared(), 1, 32))
        }
        "text" => {
            let declared = text_declared();
            let passage = text_passage(cut.expect("a passage cut"), &declared, 32, false);
            (declared, passage.train)
        }
        other => panic!("probe copy | moire | text, not {other}"),
    };
    let mut engine = Engine::new(declared);
    let built = clock.elapsed().as_millis();
    let start = Instant::now();
    for batch in pairs.chunks(declared.batch) {
        engine.learn(batch);
    }
    let learned = start.elapsed().as_millis();
    let start = Instant::now();
    let _ = engine.generate(&pairs[0].0);
    let generated = start.elapsed().as_millis();
    engine.report("probe");
    println!(
        "hnn_prediction probe {mode}: setup {built} ms; {} refinements in {} deposits {learned} ms ({} ms a refinement with its deposit share); one generation {generated} ms; resident {}",
        engine.tally.refinements,
        engine.tally.deposits,
        learned / u128::from(engine.tally.refinements.max(1)),
        resident()
    );
}

fn main() {
    let arguments = exterior::admit_reserve_flag(std::env::args().collect());
    match arguments.get(1).map(String::as_str) {
        Some("probe") => probe(
            arguments.get(2).map(String::as_str).expect("a mode"),
            arguments.get(3).map(String::as_str),
        ),
        // Development reads before the pins: the terrain at development seeds (never the pinned
        // training or evaluation seeds) and counts given on the command line.
        Some("develop") => {
            let mut declared = terrain_declared();
            if let Some(batch) = arguments.get(5).and_then(|value| value.parse().ok()) {
                declared.batch = batch;
            }
            if let Some(period) = arguments.get(6).and_then(|value| value.parse().ok()) {
                declared.period = period;
            }
            if let Some(words) = arguments.get(7).and_then(|value| value.parse().ok()) {
                declared.words = words;
            }
            let count = |at: usize| -> usize {
                arguments
                    .get(at)
                    .and_then(|value| value.parse().ok())
                    .expect("a count")
            };
            match arguments.get(2).map(String::as_str) {
                Some("order2") => {
                    let pinned = arguments.get(8).is_some_and(|value| value == "pinned");
                    let mut declared = order_declared(pinned);
                    if let Some(batch) = arguments.get(5).and_then(|value| value.parse().ok()) {
                        declared.batch = batch;
                    }
                    if let Some(period) = arguments.get(6).and_then(|value| value.parse().ok()) {
                        declared.period = period;
                    }
                    if let Some(words) = arguments.get(7).and_then(|value| value.parse().ok()) {
                        declared.words = words;
                    }
                    if let Some(request) = arguments.get(9).and_then(|value| value.parse().ok()) {
                        declared.request = request;
                    }
                    terrain(
                        "develop order2",
                        declared,
                        order_pairs(&declared, 21, count(3)),
                        order_pairs(&declared, 22, count(4)),
                        None,
                    );
                }
                // The bank's development reads (before the bank pin): the order repair's training
                // at the development seeds, then the bank's generation at `p = num/den` and the
                // relative grain `2^(−g)`: `develop bank <train> <evaluate> <num> <den> <g>`.
                Some("bank") => {
                    let declared = order_declared(false);
                    let strength = rat(count(5) as i64, count(6) as i64);
                    terrain(
                        "develop order2 bank",
                        declared,
                        order_pairs(&declared, 21, count(3)),
                        order_pairs(&declared, 22, count(4)),
                        Some(BankRun {
                            strength,
                            grain: count(7) as u32,
                            learning: false,
                            probe: Vec::new(),
                        }),
                    );
                }
                // The bank's learning path's development reads (before the learning pin): the
                // training with the bank's face beside the readout at the development seeds, the
                // flips' probe at development seed 23, then the bank's generation:
                // `develop learn <train> <evaluate> <probe>`.
                Some("learn") => {
                    let declared = order_declared(false);
                    terrain(
                        "develop order2 learn",
                        declared,
                        order_pairs(&declared, 21, count(3)),
                        order_pairs(&declared, 22, count(4)),
                        Some(BankRun {
                            strength: bank_strength(),
                            grain: BANK_GRAIN,
                            learning: true,
                            probe: order_pairs(&declared, 23, count(5)),
                        }),
                    );
                }
                Some("copy") => terrain(
                    "develop copy",
                    declared,
                    copy_pairs(&declared, 11, count(3)),
                    copy_pairs(&declared, 12, count(4)),
                    None,
                ),
                Some("moire") => {
                    let moire =
                        Moire::draw(&MOIRE_FAMILY, MoireClass::Sheets, &mut Draw::new(13))
                            .expect("the moiré");
                    terrain(
                        "develop moire",
                        declared,
                        moire_pairs(&moire, &declared, 14, count(3)),
                        moire_windows(&moire, &declared),
                        None,
                    );
                }
                // The pumped receiving ring at a strength `p = a/b` given as `a b`, at development
                // seeds: `develop pumped <train> <evaluate> <a> <b>`.
                Some("pumped") => {
                    let strength = (
                        arguments.get(5).and_then(|v| v.parse().ok()).expect("a"),
                        arguments.get(6).and_then(|v| v.parse().ok()).expect("b"),
                    );
                    let declared = pumped_declared(strength);
                    terrain(
                        "develop pumped",
                        declared,
                        copy_pairs(&declared, 11, count(3)),
                        copy_pairs(&declared, 12, count(4)),
                        None,
                    );
                }
                // The bank on text (before the bank pin): one pass over the first `<train>` choosing
                // pairs, then the bank's sections for the first two choosing requests (already read),
                // their bytes written to the owner-only file and only their counts and times printed:
                // `develop bank-text <cut> <train> <out>`.
                // `develop learn-text <cut> <train> <out>`: the same with the bank's face beside
                // the readout in training (the learning pin's development read).
                Some(mode @ ("bank-text" | "learn-text")) => {
                    let declared = text_declared();
                    let passage = text_passage(
                        arguments.get(3).map(String::as_str).expect("the passage cut"),
                        &declared,
                        count(4),
                        false,
                    );
                    let clock = Instant::now();
                    let mut engine = Engine::new(declared);
                    if mode == "learn-text" {
                        engine.learning = Some(bank_of(declared.period, &bank_strength()));
                    }
                    for batch in passage.train.chunks(declared.batch) {
                        engine.learn(batch);
                    }
                    println!("  develop {mode}: training {} ms", clock.elapsed().as_millis());
                    engine.report("develop");
                    engine.report_learning();
                    engine.bank = Some((bank_of(declared.period, &bank_strength()), BANK_GRAIN));
                    let start = Instant::now();
                    let requests: Vec<&[usize]> =
                        passage.train.iter().take(2).map(|(request, _)| request.as_slice()).collect();
                    let sections = engine.generate_banks(&requests);
                    let mut written = String::new();
                    for (order, (classes, released)) in sections.iter().enumerate() {
                        let bytes: Vec<u8> = classes
                            .iter()
                            .take_while(|&&class| class != declared.alphabet - 1)
                            .map(|&class| u8::try_from(class).expect("a byte class"))
                            .collect();
                        println!(
                            "  development section {order} (request {} bytes): {}, {} bytes",
                            requests[order].len(),
                            if *released { "released" } else { "held" },
                            bytes.len()
                        );
                        written.push_str(&format!(
                            "section {order}: {}\n{}\n\n",
                            if *released { "released" } else { "held" },
                            String::from_utf8_lossy(&bytes)
                        ));
                    }
                    #[allow(clippy::disallowed_methods)]
                    std::fs::write(
                        arguments.get(5).expect("the owner-only file"),
                        written,
                    )
                    .expect("write the development sections");
                    engine.report_bank();
                    println!(
                        "  two sections {} ms; resident {}",
                        start.elapsed().as_millis(),
                        resident()
                    );
                }
                // Text: the choosing role's pairs only; the validation role is never read here.
                Some("text") => {
                    let declared = text_declared();
                    let passage = text_passage(
                        arguments.get(3).map(String::as_str).expect("the passage cut"),
                        &declared,
                        count(4),
                        false,
                    );
                    let clock = Instant::now();
                    let mut engine = Engine::new(declared);
                    for batch in passage.train.chunks(declared.batch) {
                        if !guarded(&clock) {
                            break;
                        }
                        engine.learn(batch);
                    }
                    engine.report("develop text");
                    println!("  {} ms; resident {}", clock.elapsed().as_millis(), resident());
                    // A development generation on choosing requests already read (never the
                    // validation role), written to the owner-only file given as `develop text
                    // <cut> <train> <out>`: its counts are printed, its bytes only written.
                    if let Some(out) = arguments.get(5) {
                        let start = Instant::now();
                        let mut written = String::new();
                        for (order, (request, _)) in passage.train.iter().take(RELEASES).enumerate() {
                            let (classes, released) = engine.generate(request);
                            let bytes: Vec<u8> = classes
                                .iter()
                                .take_while(|&&class| class != declared.alphabet - 1)
                                .map(|&class| u8::try_from(class).expect("a byte class"))
                                .collect();
                            println!(
                                "  development section {order}: {}, {} bytes, UTF-8 {}",
                                if released { "released" } else { "held" },
                                bytes.len(),
                                std::str::from_utf8(&bytes).is_ok()
                            );
                            written.push_str(&format!(
                                "section {order}: {}\n{}\n\n",
                                if released { "released" } else { "held" },
                                String::from_utf8_lossy(&bytes)
                            ));
                        }
                        #[allow(clippy::disallowed_methods)]
                        std::fs::write(out, written).expect("write the development sections");
                        println!(
                            "  development generation: {} refinements, {} ms",
                            engine.generation_refinements,
                            start.elapsed().as_millis()
                        );
                    }
                }
                _ => panic!("develop copy | moire <train> <evaluate> | text <cut> <train>"),
            }
        }
        Some("order2") => {
            let pinned = arguments.get(2).is_some_and(|value| value == "pinned");
            // `order2 bank`: the order repair's training and generation, then the receiving bank's
            // generation on the same constitution and requests (the bank pin).
            let bank = arguments.get(2).is_some_and(|value| value == "bank");
            // `order2 learn`: the bank's learning path (the learning pin): the training compares
            // every request by the bank's face beside the readout, the flips read on the held-out
            // probe; then the order repair's and the bank's generations and the opening's
            // diagnostic, as `order2 bank`.
            let learn = arguments.get(2).is_some_and(|value| value == "learn");
            let declared = order_declared(pinned);
            terrain(
                if pinned {
                    "order2 pinned"
                } else if bank {
                    "order2 bank"
                } else if learn {
                    "order2 learn"
                } else {
                    "order2"
                },
                declared,
                order_pairs(&declared, TRAIN_SEED, ORDER_TRAIN),
                order_pairs(&declared, EVALUATE_SEED, EVALUATE),
                (bank || learn).then(|| BankRun {
                    strength: bank_strength(),
                    grain: BANK_GRAIN,
                    learning: learn,
                    probe: if learn {
                        order_pairs(&declared, PROBE_SEED, PROBE)
                    } else {
                        Vec::new()
                    },
                }),
            );
        }
        // `pumped below | past`: the pinned pumped runs (module header, "The pumped receiving ring").
        Some("pumped") => {
            let strength = match arguments.get(2).map(String::as_str) {
                Some("below") => PUMP_BELOW,
                Some("past") => PUMP_PAST,
                _ => panic!("pumped below | past"),
            };
            let declared = pumped_declared(strength);
            terrain(
                "pumped",
                declared,
                copy_pairs(&declared, TRAIN_SEED, PUMPED_TRAIN),
                copy_pairs(&declared, EVALUATE_SEED, PUMPED_EVALUATE),
                None,
            );
        }
        Some("copy") => {
            let declared = terrain_declared();
            terrain(
                "copy",
                declared,
                copy_pairs(&declared, TRAIN_SEED, COPY_TRAIN),
                copy_pairs(&declared, EVALUATE_SEED, EVALUATE),
                None,
            );
        }
        Some("moire") => {
            // `moire [K]`: the pinned moiré at `K` words (the pins of September 29 took `K = 2`;
            // the certified step's pins read `K = 4` and `K = 8`).
            let mut declared = terrain_declared();
            if let Some(words) = arguments.get(2).and_then(|value| value.parse().ok()) {
                declared.words = words;
            }
            let moire = Moire::draw(&MOIRE_FAMILY, MoireClass::Sheets, &mut Draw::new(MOIRE_SEED))
                .expect("the moiré");
            let truth = moire.truth(&MOIRE_FAMILY).expect("the moiré's truth");
            println!(
                "  the moiré: {} gratings, joint period {}, least period {}, determining depth {}",
                moire.gratings().len(),
                truth.joint_period,
                truth.least_period,
                truth.depth
            );
            terrain(
                "moire",
                declared,
                moire_pairs(&moire, &declared, TRAIN_SEED, MOIRE_TRAIN),
                moire_windows(&moire, &declared),
                None,
            );
        }
        // The development configuration where `K = 4` diverged under the declared step `γ_U = 1`
        // (the native generation pins' development table: `d = 16`, `K = 4`, `s = 1`, batch 8, 128
        // windows at the development seeds; `E`'s entries grew 1, 6, 26, 316), read again under the
        // certified step: development seeds only, never the pinned ones.
        Some("divergence") => {
            let mut declared = terrain_declared();
            declared.period = 16;
            declared.words = 4;
            declared.batch = 8;
            let moire = Moire::draw(&MOIRE_FAMILY, MoireClass::Sheets, &mut Draw::new(13))
                .expect("the moiré");
            terrain(
                "divergence",
                declared,
                moire_pairs(&moire, &declared, 14, 128),
                moire_windows(&moire, &declared),
                None,
            );
        }
        Some("text") => {
            let (mut bound, mut passes) = (TEXT_TRAIN, TEXT_PASSES);
            // `text <cut> <out> … bank`: the sections generated by the receiving bank (the bank pin);
            // `… learn`: the training compares every request by the bank's face beside the readout
            // (the learning pin), then the bank's sections.
            let learn = arguments.last().is_some_and(|value| value == "learn");
            let bank = learn || arguments.last().is_some_and(|value| value == "bank");
            let options = &arguments[4..arguments.len() - usize::from(bank)];
            for pair in options.chunks(2) {
                match pair {
                    [key, value] if key == "train" => bound = value.parse().expect("pairs"),
                    [key, value] if key == "passes" => passes = value.parse().expect("passes"),
                    _ => panic!("text <cut> <out> [train <pairs>] [passes <n>] [bank]"),
                }
            }
            text(
                arguments.get(2).map(String::as_str).expect("the passage cut"),
                arguments.get(3).map(String::as_str).expect("the sections' owner-only file"),
                bound,
                passes,
                bank,
                learn,
            )
        }
        _ => panic!(
            "hnn_prediction probe <mode> [cut] | copy | moire | text <cut> <out> [train <pairs>] [passes <n>]"
        ),
    }
}
