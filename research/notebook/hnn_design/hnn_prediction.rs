/// [definition; agent-inferred, the bank pin] **The receiving bank**: the parametron record's
/// receiving node (`C = I`, `K = I`, no dissipation but its port `Y = 16`, `h = 1`), its members at
/// the axis `1` and the pump steps `i^j` whose order divides the receiving ring's period `d` (so the
/// turn is a cycle of every member's clock), each at the declared strength `p`.
fn bank_of(period: u64, strength: &Rat) -> ReceivingBank {
    let identity = ExactRatMatrix::identity(2).expect("identity");
    let material = ResonatorMaterial::new(
        identity.clone(),
        identity,
        ExactRatMatrix::zero(2, 2).expect("zero"),
        None,
    )
    .expect("the receiving node");
    let axis = Carrier::new(Rat::from_integer(1.into()), Rat::zero()).expect("the axis 1");
    let pumps = [
        PumpStep::Stand,
        PumpStep::Quarter,
        PumpStep::Half,
        PumpStep::ThreeQuarters,
    ]
    .into_iter()
    .filter(|step| period.is_multiple_of(step.order() as u64))
    .map(|step| PumpDeclaration::new(strength.clone(), axis.clone(), step).expect("a member"))
    .collect();
    ReceivingBank::new(
        material,
        pumps,
        Rat::from_integer(16.into()),
        Rat::from_integer(1.into()),
        BANK_DECISION_GRAIN,
    )
    .expect("the bank")
}

/// The grain of a bank member's own `Floquet::decide` (the parametron record's `2^(−6)`); the turn's
/// readings take the declared grain of the run.
const BANK_DECISION_GRAIN: u32 = 6;

impl Engine {
    fn new(declared: Declared) -> Self {
        let field = declare(&declared);
        let refinement = Refinement::declare(
            &field,
            0,
            declared.words,
            declared.span,
            declared.stations,
            declared.alphabet - 1,
        )
        .expect("the declared refinement");
        let mut theta =
            Constitution::initial(&field, CAMPAIGN_ONE_BUDGET).expect("the initial constitution");
        if let Some((numerator, denominator)) = declared.pump {
            theta = theta
                .with_ring_resonator(&field, 0, pumped_resonator(&field, rat(numerator, denominator)))
                .expect("the receiving ring's pumped resonator");
        }
        Self {
            field,
            refinement,
            theta,
            charts: Charts::new(),
            tally: Tally::default(),
            order: declared.order,
            partitions: Draw::new(MASK_SEED),
            generation_refinements: 0,
            generation_balances: 0,
            bank: None,
            bank_tally: BankTally::default(),
            learning: None,
            learning_tally: LearningTally::default(),
            probe: Vec::new(),
        }
    }

    /// **Sections generated by the receiving bank** (`prediction::generate_by_bank`), one per request,
    /// each released at width zero or held. The requests' generations are co-present regions (the
    /// shared constitution read at its cut, one section each), run on the host's cores and tallied in
    /// request order.
    fn generate_banks(&mut self, requests: &[&[usize]]) -> Vec<(Vec<usize>, bool)> {
        use rayon::prelude::*;
        let (bank, grain) = self.bank.as_ref().expect("a declared bank");
        let start = Instant::now();
        let (field, theta, refinement) = (&self.field, &self.theta, &self.refinement);
        let generated: Vec<_> = requests
            .par_iter()
            .map(|request| {
                let (current, moment) = ingest(field, request);
                generate_by_bank(field, theta, &current, &moment, refinement, bank, *grain)
                    .expect("a section generated by the bank")
            })
            .collect();
        let t = &mut self.bank_tally;
        t.ms += start.elapsed().as_millis();
        generated
            .into_iter()
            .map(|generated| {
                t.refinements += generated.refinements as u64;
                t.readings += generated.readings as u64;
                t.certified += generated.certified as u64;
                t.members += generated.members as u64;
                t.ticks_closed += generated.ticks_closed as u64;
                t.ticks += generated.ticks as u64;
                for (_, _, growth, runner) in &generated.decisions {
                    t.locks += 1;
                    let range = t
                        .growth
                        .get_or_insert((growth.lower.clone(), growth.upper.clone()));
                    if growth.lower < range.0 {
                        range.0 = growth.lower.clone();
                    }
                    if growth.upper > range.1 {
                        range.1 = growth.upper.clone();
                    }
                    let margin = &growth.lower - &runner.upper;
                    if t.margin.as_ref().is_none_or(|least| &margin < least) {
                        t.margin = Some(margin);
                    }
                }
                let release = generated.release;
                if release.released() {
                    (release.classes, true)
                } else {
                    (Vec::new(), false)
                }
            })
            .collect()
    }

    fn report_learning(&self) {
        let t = &self.learning_tally;
        if self.learning.is_none() {
            return;
        }
        println!(
            "  the bank's learning path: {} comparisons staged ({} skipped: a target read with no power), the face's top the target at {}; {} ms (the images and the comparisons); the training's staging {} ms and deposits {} ms in all",
            t.comparisons, t.skipped, t.top_right, t.ms, self.tally.stage_ms, self.tally.deposit_ms
        );
        if let Some(code) = &t.code {
            println!("  the bank face's training code, sum of -log2 theta_t: {}", reading_of(code, 16));
        }
        for (member, (lowered, raised, zero)) in t.pumps.iter().enumerate() {
            println!(
                "  member {member}'s pump covector over a deposit (held: the bank's pumps are declared): the descent raises p^2 at {lowered}, lowers it at {raised}, zero at {zero}"
            );
        }
        if let (Some((least, largest)), Some((low, high))) = (&t.curvature, &t.steps) {
            println!(
                "  the source port's bank curvature from {least} to {largest}; its certified steps 2^k for k from {low} to {high}"
            );
        }
        for (label, (a, curvature, bank, covector, k)) in
            ["first", "last"].iter().zip(&t.certificates)
        {
            // Which bound sets the step: `ηC ≤ a` (the curvature) or `ηc ≤ 1` (the covector scale).
            let binding = if covector.is_zero() || (!curvature.is_zero() && a / curvature <= Rat::from_integer(1.into()) / covector) {
                "the curvature"
            } else {
                "the covector scale"
            };
            println!(
                "  the source port's certificate at the {label} deposit: a = {}, C = {} (the bank's {}), c = {}; step 2^{k}, set by {binding}",
                holonics::holon::deposition::significant(a, 16, false),
                holonics::holon::deposition::significant(curvature, 16, true),
                holonics::holon::deposition::significant(bank, 16, true),
                holonics::holon::deposition::significant(covector, 16, true),
            );
        }
        if !self.probe.is_empty() {
            let (better, worse, open) = t.flips_taken;
            let (r_better, r_worse, r_open) = t.flips_refused;
            println!(
                "  the flips read on the held-out probe ({} requests): of the proposals taken, the probe's code at the turned sheets strictly lower at {better}, strictly higher at {worse}, undecided at {open}; of the proposals refused, strictly lower at {r_better}, strictly higher at {r_worse}, undecided at {r_open}; {} ms",
                self.probe.len(),
                t.probe_ms
            );
        }
    }

    fn report_bank(&self) {
        let t = &self.bank_tally;
        println!(
            "  the bank's generation: {} refinements, {} turn readings; {} locks, their members certified {} of {}, the executed turns' ticks closed {} of {}; {} ms",
            t.refinements, t.readings, t.locks, t.certified, t.members, t.ticks_closed, t.ticks, t.ms
        );
        if let Some((least, largest)) = &t.growth {
            println!(
                "  the locked readings' growth from {least} to {largest}; the least margin over the runner-up {}",
                t.margin
                    .as_ref()
                    .map_or_else(|| "none".to_string(), ToString::to_string)
            );
        }
    }

    /// **One deposit over a batch**: every request staged with its checks, the batch deposited at
    /// one commit, the unreached loci and every refinement's commit balance checked.
    fn learn(&mut self, batch: &[(Vec<usize>, Vec<usize>)]) {
        let staging = Instant::now();
        let mut composed = Vec::with_capacity(batch.len());
        let mut balances = Vec::with_capacity(batch.len());
        let mut windows = Vec::with_capacity(batch.len());
        // The bank's images at the cut (the learning pin): every class's column of `E` at every
        // rotation, read once per deposit.
        let learning_clock = Instant::now();
        let images = self.learning.as_ref().map(|bank| {
            BankImages::of(&self.field, &self.theta, &self.refinement, bank)
                .expect("the bank's images")
        });
        self.learning_tally.ms += learning_clock.elapsed().as_millis();
        let mut bank_staged = Vec::new();
        for (request, target) in batch {
            let (current, moment) = ingest(&self.field, request);
            let locked = if self.order {
                mask(&mut self.partitions, self.refinement.stations())
            } else {
                vec![false; self.refinement.stations()]
            };
            let staged = stage(
                &self.field,
                &self.theta,
                &current,
                &moment,
                &self.refinement,
                target,
                &locked,
                &mut self.charts,
                true,
            )
            .expect("a staged refinement");
            self.tally.refinements += 1;
            self.tally.balances += u64::from(staged.balance.closes());
            if let Some(pairing) = &staged.pairing {
                self.tally.pairings += 1;
                self.tally.pairings_held += u64::from(pairing.holds());
            }
            if staged.release.released() {
                self.tally.released += 1;
            } else {
                self.tally.held += 1;
            }
            self.tally.peak_bits = self.tally.peak_bits.max(staged.peak_bits);
            self.tally
                .add_code(&staged.ratio.code_length().expect("the section's code"));
            if let Some(images) = &images {
                let comparing = Instant::now();
                let bank = stage_bank(
                    &self.field,
                    &current,
                    &moment,
                    &self.refinement,
                    images,
                    target,
                    &locked,
                )
                .expect("the bank's comparison");
                let t = &mut self.learning_tally;
                t.comparisons += bank.stations.len() as u64;
                t.skipped += bank.skipped as u64;
                t.top_right += bank.stations.iter().filter(|r| r.top == r.target).count() as u64;
                t.code = Some(match &t.code {
                    Some(total) => interval_sum(total, &bank.code).expect("enclosures add"),
                    None => bank.code.clone(),
                });
                t.ms += comparing.elapsed().as_millis();
                bank_staged.push(bank);
            }
            balances.push((current.clone(), staged.end, staged.balance));
            composed.push(staged.composed);
            windows.push((current, moment, target.clone(), locked));
        }
        self.tally.stage_ms += staging.elapsed().as_millis();
        let depositing = Instant::now();
        let deposit = match &images {
            Some(images) => {
                // Each member's pump covector over the batch: its sign, reported; the pumps are
                // the bank's declared constitution and are held (the learning pin).
                let members = images.chart().members();
                let t = &mut self.learning_tally;
                t.pumps.resize(members, (0, 0, 0));
                for member in 0..members {
                    let covector: Rat = bank_staged.iter().map(|b| b.pumps[member].clone()).sum();
                    let entry = &mut t.pumps[member];
                    if covector.is_negative() {
                        entry.0 += 1;
                    } else if covector.is_positive() {
                        entry.1 += 1;
                    } else {
                        entry.2 += 1;
                    }
                }
                deposit_with_bank(
                    &self.theta,
                    &self.refinement,
                    &composed,
                    bank_reach(images, &bank_staged),
                )
                .expect("the batch's deposit with the bank")
            }
            None => deposit_of(&self.theta, &self.refinement, &composed)
                .expect("the batch's deposit"),
        };
        let passive = self.theta.amplitude().expect("the amplitude reads");
        let (mut next, reading) = self.theta.deposited(&deposit).expect("the deposit");
        self.tally.deposit_ms += depositing.elapsed().as_millis();
        // The medium's per-tick growth and, through a pumped ring, the span factor at the
        // refinement's span (`hnn::constitution`, "The pumped medium's reach"): the deposit's own
        // reading when its steps read the reach, the medium's otherwise; one on a passive medium.
        let (amplitude, factor) = match passive {
            Some(amplitude) => (amplitude, Rat::from_integer(1.into())),
            None => {
                let span = self.refinement.last_epoch() as u64;
                let factor = reading.pumped.as_ref().map_or_else(
                    || {
                        self.theta
                            .medium_reach(span)
                            .expect("the medium's reach")
                            .factor(span)
                            .expect("the span's factor")
                            .clone()
                    },
                    |pumped| pumped.factor.clone(),
                );
                let amplitude = self
                    .theta
                    .contrast_amplitude()
                    .expect("the contrast ports' growth");
                (amplitude, factor)
            }
        };
        if let Some(pumped) = &reading.pumped {
            self.tally.pumped_deposits += 1;
            self.tally.pumped_held += pumped.held.len() as u64;
            self.tally.pumped_factor = Some(pumped.factor.clone());
            self.tally.pumped_rings = pumped
                .rings
                .iter()
                .map(|ring| {
                    let class = match &ring.reading {
                        FloquetReading::Passive { .. } => "passive".to_string(),
                        FloquetReading::Edge { on_circle, .. } => {
                            format!("the edge ({on_circle} multipliers on the unit circle)")
                        }
                        FloquetReading::Growing { lower, .. } => {
                            format!("growing (spectral radius at least {lower})")
                        }
                    };
                    format!(
                        "ring {}: {class}, decided growth ρ₀ = {}; {} certified bounds read; reach over the spans 0..={}: {}; the bound the longest span read: ρ = {}, σ² = {}, γ_lo = {}, γ_hi = {}",
                        ring.ring,
                        ring.reading.certificate().growth(),
                        ring.bounds.len(),
                        pumped.span,
                        ring.reach
                            .iter()
                            .map(ToString::to_string)
                            .collect::<Vec<_>>()
                            .join(", "),
                        ring.bounds
                            .iter()
                            .min_by(|a, b| a.reach(pumped.span).cmp(&b.reach(pumped.span)))
                            .map_or_else(|| "none".to_string(), |bound| bound.growth.to_string()),
                        ring.bounds
                            .iter()
                            .min_by(|a, b| a.reach(pumped.span).cmp(&b.reach(pumped.span)))
                            .map_or_else(|| "none".to_string(), |bound| bound.tick.to_string()),
                        ring.bounds
                            .iter()
                            .min_by(|a, b| a.reach(pumped.span).cmp(&b.reach(pumped.span)))
                            .map_or_else(|| "none".to_string(), |bound| bound.low.to_string()),
                        ring.bounds
                            .iter()
                            .min_by(|a, b| a.reach(pumped.span).cmp(&b.reach(pumped.span)))
                            .map_or_else(|| "none".to_string(), |bound| bound.high.to_string()),
                    )
                })
                .collect();
            self.tally.pumped_steps += reading.steps.len() as u64;
        }
        // The standing's fold: the lobe held the standings in their lobes; where the lock chart's
        // steps turn a sheet, the lock compares the batch's code at both sheets exactly and takes
        // the half-turn only where the turned sheets are strictly better.
        if let Some(lobe) = &reading.lobe {
            self.tally.lobe_deposits += 1;
            self.tally.lobe_offered += lobe.offered.len() as u64;
            for (_, step) in &lobe.held {
                match step {
                    Some(_) => self.tally.lobe_halved += 1,
                    None => self.tally.lobe_dropped += 1,
                }
            }
        }
        if let Some(proposal) = &reading.lock {
            let locking = Instant::now();
            let (turned, _) = next.locked(proposal).expect("the lock's proposal at its commit");
            let held_code =
                batch_code(&self.field, &next, &self.refinement, &windows, &mut self.charts);
            let turned_code =
                batch_code(&self.field, &turned, &self.refinement, &windows, &mut self.charts);
            self.tally.lock_proposals += 1;
            self.tally.lock_proposed += proposal.crossings().len() as u64;
            let taken = strictly_better(&held_code, &turned_code);
            self.tally.lock_ms += locking.elapsed().as_millis();
            // The flip read on the held-out probe (the learning pin): the same comparison's code
            // at both sheets on requests no run trains on. A reading only: it decides nothing.
            if !self.probe.is_empty() {
                let probing = Instant::now();
                let probe = std::mem::take(&mut self.probe);
                let held_probe =
                    batch_code(&self.field, &next, &self.refinement, &probe, &mut self.charts);
                let turned_probe =
                    batch_code(&self.field, &turned, &self.refinement, &probe, &mut self.charts);
                self.probe = probe;
                let tally = if taken {
                    &mut self.learning_tally.flips_taken
                } else {
                    &mut self.learning_tally.flips_refused
                };
                if strictly_better(&held_probe, &turned_probe) {
                    tally.0 += 1;
                } else if strictly_better(&turned_probe, &held_probe) {
                    tally.1 += 1;
                } else {
                    tally.2 += 1;
                }
                self.learning_tally.probe_ms += probing.elapsed().as_millis();
            }
            if taken {
                self.tally.lock_taken += 1;
                self.tally.lock_turned += proposal.crossings().len() as u64;
                next = turned;
            }
        }
        for (_, step) in reading.steps.iter().filter(|(_, step)| step.bank.is_positive()) {
            let t = &mut self.learning_tally;
            let range = t
                .curvature
                .get_or_insert((step.bank.clone(), step.bank.clone()));
            if step.bank < range.0 {
                range.0 = step.bank.clone();
            }
            if step.bank > range.1 {
                range.1 = step.bank.clone();
            }
            let exponent = step.step.exponent;
            let steps = t.steps.get_or_insert((exponent, exponent));
            steps.0 = steps.0.min(exponent);
            steps.1 = steps.1.max(exponent);
            let certificate = (
                step.step.alignment.clone(),
                step.step.curvature.clone(),
                step.bank.clone(),
                step.step.covector.clone(),
                exponent,
            );
            if t.certificates.len() < 2 {
                t.certificates.push(certificate);
            } else {
                t.certificates[1] = certificate;
            }
        }
        for (locus, step) in &reading.steps {
            let entry = self
                .tally
                .exponents
                .entry(format!("{locus:?} {:?}", step.family))
                .or_insert((step.step.exponent, step.step.exponent));
            entry.0 = entry.0.min(step.step.exponent);
            entry.1 = entry.1.max(step.step.exponent);
        }
        self.tally.storage_product = Some(reading.storage_product.clone());
        let largest = |matrix: &holonics::ratio::linear::ExactRatMatrix| {
            matrix
                .entries()
                .iter()
                .map(|x| x.abs())
                .max()
                .unwrap_or_else(Rat::zero)
        };
        let mut maps: Vec<(String, Rat)> = Vec::new();
        for g in 0..self.field.rings().len() {
            if let Some(port) = next.source_port(g) {
                maps.push((format!("E{g}"), largest(port)));
            }
            if let Some(map) = next.receiving_map(g) {
                maps.push((format!("R{g}"), largest(map)));
            }
            maps.push((format!("Wc{g}"), largest(next.contrast_port(g))));
            maps.push((format!("f{g}"), largest(next.passive_factor(g))));
            let slices = next
                .slices(g)
                .iter()
                .flat_map(|(u, v)| u.iter().chain(v))
                .map(|x| x.abs())
                .max()
                .unwrap_or_else(Rat::zero);
            maps.push((format!("slices{g}"), slices));
            let standing = next
                .standing(g)
                .iter()
                .map(|x| x.abs())
                .max()
                .unwrap_or_else(Rat::zero);
            maps.push((format!("q{g}"), standing));
        }
        for a in 0..self.field.contacts().len() {
            maps.push((format!("c{a}"), largest(next.contact_storage(a))));
            maps.push((format!("b{a}"), largest(next.contact_stiffness(a))));
            maps.push((format!("F{a}"), largest(next.contact_dissipation(a))));
        }
        let growth = self.tally.growths.get_or_insert((
            reading.storage_growth.clone(),
            reading.storage_growth.clone(),
        ));
        if reading.storage_growth < growth.0 {
            growth.0 = reading.storage_growth.clone();
        }
        if reading.storage_growth > growth.1 {
            growth.1 = reading.storage_growth.clone();
        }
        for (name, value) in &maps {
            let kept = self
                .tally
                .entries
                .entry(name.clone())
                .or_insert_with(Rat::zero);
            if value > kept {
                *kept = value.clone();
            }
        }
        if self.tally.trajectory.len() < 8 {
            self.tally.trajectory.push(maps);
        }
        let (loci, unchanged) = unreached_unchanged(
            &self.field,
            &self.theta,
            &next,
            &self.refinement.diamond(&self.field),
        );
        self.tally.unreached_checks += 1;
        self.tally.unreached_loci += loci as u64;
        self.tally.unreached_unchanged += u64::from(unchanged);
        for (current, end, mut balance) in balances {
            let before = PowerForm::read(&self.field, &self.theta, &current).expect("a form");
            let after = PowerForm::read(&self.field, &next, &current).expect("a form");
            balance
                .commit(&before, &after, &end)
                .expect("the commit's work");
            self.tally.commits += u64::from(balance.closes());
            let bound = balance
                .energy_bound(
                    &self.refinement,
                    &amplitude,
                    &reading.storage_growth,
                    self.field.word_lattice(),
                )
                .expect("the committed energy bound");
            self.tally.energy_checks += 1;
            // Through a pumped ring every span within the refinement's is carried by at most its
            // factor (Lean `Holon/Deposition.pumped_span_factor`); on a passive medium it is one.
            self.tally.energy_holds += u64::from(bound.committed <= &bound.bound * &factor);
        }
        for ((name, before), (_, after)) in families(&self.field, &self.theta)
            .into_iter()
            .zip(families(&self.field, &next))
        {
            let count = self.tally.moved.entry(name).or_insert(0);
            *count += u64::from(before != after);
        }
        self.tally.deposits += 1;
        self.theta = next;
        if self.tally.deposits.is_multiple_of(16) {
            eprintln!(
                "  progress: deposits {}, stage {} ms, deposit {} ms, peak bits {}, released {} held {}",
                self.tally.deposits,
                self.tally.stage_ms,
                self.tally.deposit_ms,
                self.tally.peak_bits,
                self.tally.released,
                self.tally.held
            );
        }
    }

    /// **A generated section**: refined at rest and released at width zero, or held (a plural
    /// section is a typed refusal, never retried).
    fn generate(&mut self, request: &[usize]) -> (Vec<usize>, bool) {
        let (current, moment) = ingest(&self.field, request);
        let release = if self.order {
            let generated = generate(
                &self.field,
                &self.theta,
                &current,
                &moment,
                &self.refinement,
                &mut self.charts,
            )
            .expect("a generated section");
            self.generation_refinements += generated.refinements as u64;
            self.generation_balances += generated.balances_closed as u64;
            generated.release
        } else {
            let section = Section::refine(
                &self.field,
                &self.theta,
                &current,
                &[&moment],
                &self.refinement,
                &mut self.charts,
            )
            .expect("a refined section");
            self.generation_refinements += 1;
            self.generation_balances += u64::from(section.balance().closes());
            section.release().expect("the section's release")
        };
        if release.released() {
            (release.classes, true)
        } else {
            (Vec::new(), false)
        }
    }

    fn report(&self, label: &str) {
        let t = &self.tally;
        println!(
            "  {label}: refinements {}, balances closed {} of {}, pairings exact {} of {}, commits closed {} of {}, deposits {}, unreached checks {} ({} loci in all, every one unchanged in {} of {}), released at width zero {} and held {}, peak state bits {}",
            t.refinements,
            t.balances,
            t.refinements,
            t.pairings_held,
            t.pairings,
            t.commits,
            t.refinements,
            t.deposits,
            t.unreached_checks,
            t.unreached_loci,
            t.unreached_unchanged,
            t.unreached_checks,
            t.released,
            t.held,
            t.peak_bits
        );
        if let Some(code) = &t.code {
            println!(
                "  the training sections' code, Σ_j −log₂ p̂_j(t_j): {}",
                reading_of(code, 16)
            );
        }
        println!(
            "  the committed energy bound held at {} of {} refinements' commits; the certified storage growth's product since the founding {}",
            t.energy_holds,
            t.energy_checks,
            t.storage_product
                .as_ref()
                .map_or_else(|| "none".to_string(), ToString::to_string)
        );
        if let Some((least, largest)) = &t.growths {
            println!(
                "  the certified storage growth ε_k of one deposit: from {least} to {largest}"
            );
        }
        for (locus, (least, largest)) in &t.exponents {
            println!("  certified steps at {locus}: 2^k for k from {least} to {largest}");
        }
        println!(
            "  the standing's fold: the lock chart offered crossings at {} of {} deposits ({} slices in all); the lobe halved {} standing steps and dropped {}; the lock's proposals {} ({} half-turns), taken by the exact comparison {} ({} half-turns); the lock's comparisons {} ms",
            t.lobe_deposits,
            t.deposits,
            t.lobe_offered,
            t.lobe_halved,
            t.lobe_dropped,
            t.lock_proposals,
            t.lock_proposed,
            t.lock_taken,
            t.lock_turned,
            t.lock_ms
        );
        if t.pumped_deposits > 0 {
            println!(
                "  the pumped medium: {} deposits certified through it and taken, {} certified steps, {} own gain families held; the span factor at the refinement's span at the last deposit {}",
                t.pumped_deposits,
                t.pumped_steps,
                t.pumped_held,
                t.pumped_factor
                    .as_ref()
                    .map_or_else(|| "none".to_string(), ToString::to_string)
            );
            for ring in &t.pumped_rings {
                println!("  {ring}");
            }
        }
        let factor = |name: &str| !["E", "R", "Wc"].iter().any(|linear| {
            name.strip_prefix(linear)
                .is_some_and(|ring| ring.chars().all(|c| c.is_ascii_digit()))
        });
        let (mut factors, mut factors_moved) = (0, 0);
        for (name, count) in &t.moved {
            println!("  deposits that moved {name}: {count} of {}", t.deposits);
            if factor(name) {
                factors += 1;
                factors_moved += usize::from(*count > 0);
            }
        }
        println!(
            "  factor families whose entries moved (a lattice coordinate changed) over the run: {factors_moved} of {factors}"
        );
        for (name, value) in &t.entries {
            println!("  the largest absolute entry of {name} over the run: {value}");
        }
        for (deposit, maps) in t.trajectory.iter().enumerate() {
            println!(
                "  after deposit {}: {}",
                deposit + 1,
                maps.iter()
                    .map(|(name, value)| format!("{name} {value}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
    }
}

/// **Every learned family's entries**, by name: the source port `E`, the receiving map `R`, each
/// contrast port `Wc`, and the factor families (each ring's passive factor `f`, slices and standing
/// `q`; each contact's storage `c`, stiffness `b` and dissipation `F`).
fn families(field: &Field, theta: &Constitution) -> Vec<(String, Vec<Rat>)> {
    let mut families = Vec::new();
    for g in 0..field.rings().len() {
        if let Some(port) = theta.source_port(g) {
            families.push((format!("E{g}"), port.entries().to_vec()));
        }
        if let Some(map) = theta.receiving_map(g) {
            families.push((format!("R{g}"), map.entries().to_vec()));
        }
        families.push((format!("Wc{g}"), theta.contrast_port(g).entries().to_vec()));
        families.push((format!("f{g}"), theta.passive_factor(g).entries().to_vec()));
        families.push((
            format!("slices{g}"),
            theta
                .slices(g)
                .iter()
                .flat_map(|(u, v)| u.iter().chain(v))
                .cloned()
                .collect(),
        ));
        families.push((format!("q{g}"), theta.standing(g).to_vec()));
    }
    for a in 0..field.contacts().len() {
        families.push((format!("c{a}"), theta.contact_storage(a).entries().to_vec()));
        families.push((format!("b{a}"), theta.contact_stiffness(a).entries().to_vec()));
        families.push((format!("F{a}"), theta.contact_dissipation(a).entries().to_vec()));
    }
    families
}

/// The resident set at its peak against the cap, and the deadline.
fn guarded(clock: &Instant) -> bool {
    guarded_within(clock, DEADLINE_MS)
}

/// The resident set at its peak against the cap, and a run's own training deadline.
fn guarded_within(clock: &Instant, deadline: u128) -> bool {
    let within_time = clock.elapsed().as_millis() < deadline;
    let within_memory = resident_set().is_none_or(|(_, peak)| peak < RESIDENT_CAP);
    within_time && within_memory
}

/// [agent-inferred, the learning pin] **The learning path's training stop**: the bank's comparison
/// and the flips' probe beside the readout's training, projected from the development reads (the
/// pin's §4); the other modes keep `DEADLINE_MS`.
const LEARNING_DEADLINE_MS: u128 = 1_200_000;

fn resident() -> String {
    resident_set().map_or_else(|| "unread".to_string(), |(now, peak)| format!("{now} now, {peak} peak"))
}

