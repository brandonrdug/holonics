/// The connected components of the menu's edge graph over its ports.
fn components(ports: &[usize], edges: &[(usize, usize)], width: usize) -> Vec<Vec<usize>> {
    let mut of: Vec<Option<usize>> = vec![None; width];
    let mut found: Vec<Vec<usize>> = Vec::new();
    for &start in ports {
        if of[start].is_some() {
            continue;
        }
        let index = found.len();
        let mut members = vec![start];
        of[start] = Some(index);
        let mut cursor = 0;
        while cursor < members.len() {
            let port = members[cursor];
            cursor += 1;
            for &(a, b) in edges {
                for (here, there) in [(a, b), (b, a)] {
                    if here == port && of[there].is_none() {
                        of[there] = Some(index);
                        members.push(there);
                    }
                }
            }
        }
        found.push(members);
    }
    found
}

/// **A crib's menu at key 0, charted for the search**: the menu ports, each edge as the pair of its
/// ports' indices with its stage's images at key 0, the period, and the components. The rotor gauge
/// `(k, S) ↦ (k + 1, S − 1)` carries every stage covariantly (`Machine.stage_succ`), so a plugboard
/// satisfying an edge set under key `k` maps to one satisfying it under key 0: the search runs at
/// key 0, and [`Closure::key_invariant`] checks the best by propagation under every key.
struct Charted {
    ports: usize,
    period: usize,
    edges: Vec<(usize, usize, Vec<usize>)>,
    components: usize,
}

/// A charted menu with every key's stage images per edge, its menu ports and its edges' ports.
type ChartedMenu = (Charted, Vec<Vec<Vec<usize>>>, Vec<usize>, Vec<(usize, usize)>);

fn chart_menu(field: &Field, ring: usize, crib: &[usize], offset: usize, configurations: &[u64]) -> ChartedMenu {
    let menu = keys::crib_menu(field, ring, crib, offset, configurations).expect("the crib's menu");
    let candidates = keys::candidate_keys(field, ring).expect("the ring's keys");
    let d = field.ring(ring).period() as usize;
    let ports = menu.menu_ports();
    let edges: Vec<(usize, usize)> = menu.edges().iter().map(|edge| (edge.from(), edge.to())).collect();
    let tables: Vec<Vec<Vec<usize>>> = candidates
        .iter()
        .map(|key| {
            menu.edges()
                .iter()
                .map(|edge| edge.stage(key).expect("a stage").images().to_vec())
                .collect()
        })
        .collect();
    let index_of: BTreeMap<usize, usize> = ports.iter().enumerate().map(|(i, &port)| (port, i)).collect();
    let charted = Charted {
        ports: ports.len(),
        period: d,
        edges: edges
            .iter()
            .zip(&tables[0])
            .map(|(&(a, b), table)| (index_of[&a], index_of[&b], table.clone()))
            .collect(),
        components: components(&ports, &edges, d).len(),
    };
    (charted, tables, ports, edges)
}

/// The edges an injective plugboard `images` (menu port index → image) satisfies at key 0.
fn satisfied(charted: &Charted, images: &[usize]) -> usize {
    charted
        .edges
        .iter()
        .filter(|(a, b, table)| images[*b] == table[images[*a]])
        .count()
}

/// **The exhaustive best** over every injective plugboard of the menu ports (`d!/(d − P)!` of them).
fn exhaustive_best(charted: &Charted) -> usize {
    fn descend(charted: &Charted, images: &mut Vec<usize>, used: &mut [bool], best: &mut usize) {
        if images.len() == charted.ports {
            *best = (*best).max(satisfied(charted, images));
            return;
        }
        for value in 0..charted.period {
            if !used[value] {
                used[value] = true;
                images.push(value);
                descend(charted, images, used, best);
                images.pop();
                used[value] = false;
            }
        }
    }
    let mut best = 0;
    descend(charted, &mut Vec::with_capacity(charted.ports), &mut vec![false; charted.period], &mut best);
    best
}

/// **The best found by local search** over injective plugboards: `SEARCH_STARTS` random injective
/// starts, each improved by the best single move (a port to an unused image, or two ports' images
/// swapped) until none improves.
fn searched_best(charted: &Charted, draw: &mut Draw) -> usize {
    let (p, d) = (charted.ports, charted.period);
    let mut best = 0;
    for _ in 0..SEARCH_STARTS {
        let mut images: Vec<usize> = draw.permutation(d)[..p].to_vec();
        let mut score = satisfied(charted, &images);
        loop {
            let mut improved: Option<(usize, Vec<usize>)> = None;
            for port in 0..p {
                for value in 0..d {
                    if value == images[port] {
                        continue;
                    }
                    let mut next = images.clone();
                    if let Some(other) = images.iter().position(|&image| image == value) {
                        next.swap(port, other);
                    } else {
                        next[port] = value;
                    }
                    let candidate = satisfied(charted, &next);
                    if candidate > improved.as_ref().map_or(score, |(s, _)| *s) {
                        improved = Some((candidate, next));
                    }
                }
            }
            match improved {
                Some((candidate, next)) => {
                    score = candidate;
                    images = next;
                }
                None => break,
            }
        }
        best = best.max(score);
    }
    best
}

/// **The crib's partial closure for one ring** at the configurations it is located under
/// (`keys::crib_menu`, the port's own menu), over injective plugboards: the best satisfied edges
/// (exhaustive for `d ≤ 7`, else by local search), and the best a propagation from every root and
/// seed image reaches under each key (the port's own forced assignment, kept only when injective),
/// equal under every key by the gauge.
fn closure(field: &Field, ring: usize, crib: &[usize], offset: usize, configurations: &[u64], draw: &mut Draw) -> Closure {
    let (charted, tables, ports, edges) = chart_menu(field, ring, crib, offset, configurations);
    let d = charted.period;
    let comps = components(&ports, &edges, d);
    let mut adjacency: Vec<Vec<(usize, usize)>> = vec![Vec::new(); d];
    for (index, &(a, b)) in edges.iter().enumerate() {
        adjacency[a].push((b, index));
        if a != b {
            adjacency[b].push((a, index));
        }
    }
    let mut per_key = Vec::with_capacity(tables.len());
    for table in &tables {
        let mut total = 0usize;
        for comp in &comps {
            let inside: Vec<usize> = (0..edges.len()).filter(|&e| comp.contains(&edges[e].0)).collect();
            let mut best = 0usize;
            for &root in comp {
                for seed in 0..d {
                    let mut image: Vec<Option<usize>> = vec![None; d];
                    image[root] = Some(seed);
                    let mut queue = vec![root];
                    let mut cursor = 0;
                    while cursor < queue.len() {
                        let here = queue[cursor];
                        cursor += 1;
                        let value = image[here].expect("reached");
                        for &(there, edge) in &adjacency[here] {
                            if image[there].is_none() {
                                image[there] = Some(table[edge][value]);
                                queue.push(there);
                            }
                        }
                    }
                    let assigned: Vec<usize> = comp.iter().map(|&port| image[port].expect("reached")).collect();
                    let distinct: BTreeSet<usize> = assigned.iter().copied().collect();
                    if distinct.len() != assigned.len() {
                        continue;
                    }
                    let count = inside
                        .iter()
                        .filter(|&&e| {
                            let (a, b) = edges[e];
                            image[b] == Some(table[e][image[a].expect("reached")])
                        })
                        .count();
                    best = best.max(count);
                }
            }
            total += best;
        }
        per_key.push(total);
    }
    let propagated = per_key.iter().copied().max().unwrap_or(0);
    let exhaustive = (d <= 7).then(|| exhaustive_best(&charted));
    Closure {
        ports: charted.ports,
        edges: charted.edges.len(),
        components: charted.components,
        propagated,
        key_invariant: per_key.iter().all(|&value| value == propagated),
        searched: searched_best(&charted, draw),
        exhaustive,
    }
}

/// The null: the crib's own cells in `NULL_SHUFFLES` orders.
fn null_closures(field: &Field, ring: usize, crib: &[usize], offset: usize, configurations: &[u64], seed: u64) -> Vec<Closure> {
    let mut draw = Draw(seed);
    (0..NULL_SHUFFLES)
        .map(|_| {
            let order = draw.permutation(crib.len());
            let shuffled: Vec<usize> = order.iter().map(|&i| crib[i]).collect();
            closure(field, ring, &shuffled, offset, configurations, &mut draw)
        })
        .collect()
}

/// **A synthetic crib generated by the declared ring with a true key and plugboard** (ring
/// `ring`'s own relation only): `S(port(x_(k+1))) = W_(key + steps(k)) S(port(x_k))`, each next cell
/// a byte of the forced port class drawn uniformly. The earlier rings run at phase 0.
struct SyntheticTrial {
    in_fibre: bool,
    fibre: usize,
    orbits: usize,
    published: bool,
    gauge_fixed: bool,
    truth_itself: bool,
    earlier_fell_back: bool,
    closing_carried: bool,
    closes_every_edge: bool,
}

fn synthetic_trial(field: &Field, ring: usize, length: usize, draw: &mut Draw) -> SyntheticTrial {
    let geometry = field.ring(ring);
    let d = geometry.period() as usize;
    let machine = geometry.machine().expect("the ring's machine");
    let clocks = keys::candidate_keys(field, ring).expect("keys");
    let key = draw.below(d);
    let plug = draw.permutation(d);
    let mut inverse = vec![0usize; d];
    for (port, &image) in plug.iter().enumerate() {
        inverse[image] = port;
    }
    let mut configurations = vec![0u64; field.rings().len()];
    configurations[ring] = key as u64;
    let opening: Vec<BigInt> = configurations.iter().map(|c| BigInt::from(*c)).collect();
    let mut lift = opening.clone();
    let mut cells = vec![draw.below(field.alphabet())];
    let mut steps = 0u64;
    for k in 0..length - 1 {
        let position = machine.position(&clocks[key], &BigUint::from(steps));
        let stage = machine.stage(&position).expect("a stage");
        let port = geometry.port(cells[k]);
        let next = inverse[stage.apply(plug[port]).expect("a port")];
        steps += u64::from(field.selective_step(&mut lift, cells[k]).expect("a cell").ticks[ring]);
        let representatives = (field.alphabet() - 1 - next) / d + 1;
        cells.push(next + d * draw.below(representatives));
    }
    field.selective_step(&mut lift, cells[length - 1]).expect("a cell");
    let location = keys::locate_keys(field, &Current::at(field, opening).expect("a lift"), &cells, 1).expect("location");
    let located = &location.rings[ring];
    let in_fibre = located.fibre.iter().any(|candidate| {
        (candidate.key.ticks() % BigUint::from(d)).to_usize() == Some(key)
            && located.menu_ports.iter().all(|&port| candidate.images.image(port) == Some(plug[port]))
    });
    let fixed = (key + plug[located.menu_ports[0]]) % d;
    let closing = keys::locate_closing(field, &Current::at(field, lift).expect("a lift"), &cells, 1).expect("closing location");
    let ticks = keys::crib_ticks(field, ring, &cells, &closing.configurations()).expect("ticks");
    let measured = closure(field, ring, &cells, 1, &location.configurations(), draw);
    SyntheticTrial {
        in_fibre,
        fibre: located.fibre.len(),
        orbits: located.orbits,
        published: located.published.is_some(),
        gauge_fixed: located.published == Some(fixed as u64),
        truth_itself: located.published == Some(key as u64),
        earlier_fell_back: location.rings[..ring].iter().all(|r| r.fell_back),
        closing_carried: closing.rings[ring].carried == Some((fixed as u64 + ticks) % d as u64),
        closes_every_edge: measured.exhaustive.unwrap_or(measured.searched) == measured.edges,
    }
}

