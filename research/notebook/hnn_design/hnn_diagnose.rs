/// **The face of a real logit vector at the grain**, the machine's own ([`Face::of_read`]), its
/// imaginary parts zero (the phase part does not enter a code length).
fn face_of(real: &[Rat], grain: u64) -> Face {
    let logits: Vec<Rat> = real.iter().flat_map(|value| [value.clone(), Rat::zero()]).collect();
    let read = ReceivingRead {
        cells: real.iter().map(|value| GrainCell::of(value, grain)).collect(),
        phases: vec![Rat::zero(); real.len()],
        logits,
    };
    Face::of_read(&read, grain).expect("a face")
}

/// The code length of a target under `f = s · y` at the grain: the machine's face when `|s|` is
/// within the ceiling; otherwise the enclosure `[m, m + log₂|A|]`, `m = max_c (f_c − f_t)`.
fn scaled_code(scale: &Rat, y: &[Rat], target: usize, grain: u64) -> (ExactInterval, bool) {
    if scale.abs() <= int(SCALE_CEILING) {
        let real: Vec<Rat> = y.iter().map(|value| scale * value).collect();
        (face_of(&real, grain).code_length(target).expect("a code length"), false)
    } else {
        let at = scale * &y[target];
        let top = y.iter().map(|value| scale * value - &at).max().expect("classes").max(Rat::zero());
        let width = log2_enclosure(&count(y.len())).expect("log2 |A|");
        (ExactInterval::new(top.clone(), top + width.upper).expect("ordered"), true)
    }
}

/// The exact determinant of a square rational matrix by Gaussian elimination over ℚ.
fn determinant(mut rows: Vec<Vec<Rat>>) -> Rat {
    let n = rows.len();
    let mut det = Rat::one();
    for column in 0..n {
        let Some(pivot) = (column..n).find(|&row| !rows[row][column].is_zero()) else {
            return Rat::zero();
        };
        if pivot != column {
            rows.swap(pivot, column);
            det = -det;
        }
        let head = rows[column][column].clone();
        det *= &head;
        let pivot_row = rows[column].clone();
        for row in rows.iter_mut().skip(column + 1) {
            if row[column].is_zero() {
                continue;
            }
            let factor = &row[column] / &head;
            for (entry, top) in row.iter_mut().zip(&pivot_row).skip(column) {
                *entry -= &factor * top;
            }
        }
    }
    det
}

/// Euclid's greatest common divisor of two integers.
fn gcd(a: &BigInt, b: &BigInt) -> BigInt {
    let (mut a, mut b) = (a.abs(), b.abs());
    while !b.is_zero() {
        let r = &a % &b;
        a = b;
        b = r;
    }
    a
}

/// The exact least-squares solution `w` of `wᵀ z_j = 1` over a population of features (a particular
/// solution of `G w = b`, `G = Σ z zᵀ`, `b = Σ z`), with the Gram's rank and the reach
/// `bᵀw / N = 1 − residual/N`. The sums are formed over integers on the features' common
/// denominator (they lie on the word's dyadic lattice) and each entry normalized once.
fn constant_fit(features: &[Vec<Rat>]) -> (Vec<Rat>, usize, Rat) {
    let n = features.first().map_or(0, Vec::len);
    let mut denominator = BigInt::one();
    for feature in features {
        for value in feature {
            let d = value.denom();
            if !(&denominator % d).is_zero() {
                denominator = &denominator / gcd(&denominator, d) * d;
            }
        }
    }
    let scale = Rat::from_integer(denominator.clone());
    let mut g_int = vec![vec![BigInt::zero(); n]; n];
    let mut b_int = vec![BigInt::zero(); n];
    for feature in features {
        let integers: Vec<BigInt> = feature.iter().map(|value| (value * &scale).to_integer()).collect();
        for i in 0..n {
            if integers[i].is_zero() {
                continue;
            }
            b_int[i] += &integers[i];
            for j in i..n {
                g_int[i][j] += &integers[i] * &integers[j];
            }
        }
    }
    let square = &denominator * &denominator;
    let mut gram = vec![vec![Rat::zero(); n]; n];
    let b: Vec<Rat> = b_int.iter().map(|value| Rat::new(value.clone(), denominator.clone())).collect();
    for i in 0..n {
        for j in i..n {
            let value = Rat::new(g_int[i][j].clone(), square.clone());
            gram[i][j] = value.clone();
            gram[j][i] = value;
        }
    }
    let matrix = ExactRatMatrix::new(gram).expect("a square Gram");
    let rank = matrix.rank().expect("a rank");
    let w = matrix
        .preimage_fibre(&b)
        .expect("a fibre")
        .map(|(particular, _)| particular)
        .expect("b lies in the Gram's image");
    let reach = dot(&b, &w) / count(features.len().max(1));
    (w, rank, reach)
}

