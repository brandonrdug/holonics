/// One locus's update at one deposit, from the carry's accounting.
#[derive(Clone, Default)]
struct LocusUpdate {
    exact_l1: Rat,
    applied_l1: Rat,
    carried_l1: Rat,
    released_l1: Rat,
    exact_max: Rat,
    applied_max: Rat,
    exact_entries: u64,
    applied_entries: u64,
}

impl LocusUpdate {
    /// The update of one map: `W' − W`, `r' − r` and the released tails `e` per entry.
    fn of(before: &ExactRatMatrix, after: &ExactRatMatrix, rem_before: &ExactRatMatrix, rem_after: &ExactRatMatrix, released: &BTreeMap<usize, Rat>) -> Self {
        let mut update = Self::default();
        for (index, ((w0, w1), (r0, r1))) in before
            .entries()
            .iter()
            .zip(after.entries())
            .zip(rem_before.entries().iter().zip(rem_after.entries()))
            .enumerate()
        {
            let applied = w1 - w0;
            let carried = r1 - r0;
            let tail = released.get(&index).cloned().unwrap_or_else(Rat::zero);
            let exact = &applied + &carried + &tail;
            if !applied.is_zero() {
                update.applied_entries += 1;
                update.applied_l1 += applied.abs();
                if applied.abs() > update.applied_max {
                    update.applied_max = applied.abs();
                }
            }
            if !exact.is_zero() {
                update.exact_entries += 1;
                update.exact_l1 += exact.abs();
                if exact.abs() > update.exact_max {
                    update.exact_max = exact.abs();
                }
            }
            update.carried_l1 += carried.abs();
            update.released_l1 += tail.abs();
        }
        update
    }
}

