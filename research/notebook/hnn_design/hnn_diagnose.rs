/// Running sums of the logits' real parts over one population of reads.
struct LogitSums {
    sum: Vec<Rat>,
    squares: Rat,
    centred_squares: Rat,
    reads: usize,
}

impl LogitSums {
    fn new(classes: usize) -> Self {
        Self {
            sum: vec![Rat::zero(); classes],
            squares: Rat::zero(),
            centred_squares: Rat::zero(),
            reads: 0,
        }
    }

    fn add(&mut self, real: &[Rat]) {
        let mut total = Rat::zero();
        let mut squares = Rat::zero();
        for (entry, value) in self.sum.iter_mut().zip(real) {
            *entry += value;
            total += value;
            squares += value * value;
        }
        let centred = &squares - &total * &total / count(real.len());
        self.squares += squares;
        self.centred_squares += centred;
        self.reads += 1;
    }

    fn mean(&self) -> Vec<Rat> {
        let n = count(self.reads.max(1));
        self.sum.iter().map(|value| value / &n).collect()
    }
}

