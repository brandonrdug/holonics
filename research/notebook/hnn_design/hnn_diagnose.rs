fn phase_of(field: &Field, lift: &[BigInt]) -> Vec<u64> {
    field
        .rings()
        .iter()
        .zip(lift)
        .map(|(ring, tau)| {
            let d = BigInt::from(ring.period());
            let mut phase = tau % &d;
            if phase.is_negative() {
                phase += &d;
            }
            phase.to_u64().expect("a phase")
        })
        .collect()
}

fn released_map(released: &[(Locus, Carrier, usize, Rat)], locus: Locus) -> BTreeMap<usize, Rat> {
    let mut map = BTreeMap::new();
    for (at, carrier, entry, residual) in released {
        if *at == locus && *carrier == Carrier::Map {
            *map.entry(*entry).or_insert_with(Rat::zero) += residual;
        }
    }
    map
}

fn expose(field: &Field, cut: &Cut, deadline: Option<u64>) -> Run {
    let clock = Instant::now();
    let port = Reference::campaign_one();
    let mut resident = port.mount(field, &Current::at_rest(field)).expect("the mount");
    let phases = resident.admitted()[0].clone();
    let family = resident.admitted().to_vec();
    let receiving = phases.ring();
    let source = field.sources()[0];
    let aperture = phases.aperture();
    let alphabet = field.alphabet();
    let crib = field.crib();
    let cells = &cut.cells;
    let held = |position: usize| cut.held_out.iter().any(|range| range.contains(&position));
    let (moment, _) = port.ingest(&mut resident, None, &[]).expect("open the moment");
    let mut reads = Vec::new();
    let mut deposits = Vec::new();
    let mut locations = Vec::new();
    let mut aeon_cells = Vec::new();
    let mut training = LogitSums::new(alphabet);
    let mut held_sums = LogitSums::new(alphabet);
    let mut recency = Vec::new();
    let mut covector_energy = [Enclosed::default(), Enclosed::default(), Enclosed::default(), Enclosed::default()];
    let mut order_zero = vec![0u64; alphabet];
    let mut seen = 0u64;
    let (mut windows, mut open_windows, mut compares) = (0u64, 0u64, 0u64);
    let mut published = 0usize;
    let mut aeon = 0usize;
    let mut aeon_start = 0usize;
    // The source ring's phase class and the cells since it last moved (the recency reading).
    let mut run_length = 0u64;
    let mut last_phase: Option<u64> = None;
    let mut complete = true;
    let mut position = 0usize;
    while position < cells.len() {
        let end = (position + aperture).min(cells.len());
        let window = &cells[position..end];
        if window.len() == aperture && deadline.is_some_and(|limit| compares >= limit) {
            complete = false;
            break;
        }
        if window.len() == aperture {
            let lift = resident.current().lift().to_vec();
            let config = phase_of(field, &lift);
            let open_moment = resident.moment(&moment).expect("the moment");
            let bin: u64 = open_moment
                .phase_counts(source, config[source] as usize)
                .expect("the source ring's bin")
                .iter()
                .sum();
            recency.push((run_length, bin));
            let (pending, refined) = port.refine(&mut resident, &moment, &phases).expect("refine");
            windows += 1;
            let open = match &refined.receipt.detail {
                ReceiptDetail::Refine { path, .. } => path.open,
                _ => false,
            };
            open_windows += u64::from(open);
            let (staged, compared) = port.compare(&mut resident, pending, &one_hot(window)).expect("compare");
            compares += 1;
            let deposit = compared.deposit.present().cloned().expect("a compare stages its deposit");
            let holon = compared.forward.into_present().expect("a compare returns its ratio");
            let receiving_samples = deposit
                .linear()
                .iter()
                .find(|step| step.locus == LinearLocus::Receiving(receiving))
                .map(|step| step.samples.clone())
                .expect("the receiving map's samples");
            let windowed = (0..window.len()).any(|offset| held(position + offset));
            // The decoder's readings are the wave's `R z`: the count face's grain logits (Decision
            // 27; the masses the compare read, at the window's region) are taken out of the face.
            let count = phases
                .count_face(resident.constitution(), resident.moment(&moment).expect("the moment"))
                .expect("the count face");
            let stored: Vec<Rat> = count.logits().into_iter().step_by(2).collect();
            for (offset, (phase, &code)) in holon.phases().iter().zip(window).enumerate() {
                let logits = &holon.faces().logits[offset];
                let real: Vec<Rat> = logits
                    .iter()
                    .step_by(2)
                    .zip(&stored)
                    .map(|(face, count)| face - count)
                    .collect();
                let spread = real.iter().max().expect("classes") - real.iter().min().expect("classes");
                let is_held = held(position + offset);
                if is_held {
                    held_sums.add(&real);
                } else {
                    training.add(&real);
                }
                let zero = kt(order_zero[code], seen, alphabet);
                order_zero[code] += 1;
                seen += 1;
                reads.push(Read {
                    cell: position + offset,
                    target: code,
                    held_out: is_held,
                    aeon,
                    config: config.clone(),
                    open,
                    model: phase.code_length.clone(),
                    order_zero: zero,
                    feature: receiving_samples[offset].feature.clone(),
                    spread,
                });
            }
            if windowed {
                port.discard(&mut resident, Handle::Staged(staged)).expect("discard");
            } else {
                // The covector's magnitude (Re f) and phase (Im f) parts, at the face and pulled
                // back through Rᵀ to the receiving anchor (the rotation keeps norms), where every
                // other locus's covector starts.
                let map = resident.constitution().receiving_map(receiving).expect("R");
                let columns = map.columns();
                for sample in &receiving_samples {
                    // Within one sample the entries share the face's normalizer, so its sums stay
                    // small; across samples the normalizers differ, so the run's sums are carried
                    // as dyadic enclosures (an exact sum's denominator would be their lcm).
                    let mut pulled = [vec![Rat::zero(); columns], vec![Rat::zero(); columns]];
                    let mut energy = [Rat::zero(), Rat::zero()];
                    for (row, value) in sample.covector.iter().enumerate() {
                        if value.is_zero() {
                            continue;
                        }
                        let part = row % 2;
                        energy[part] += value * value;
                        for (k, entry) in map.entries()[row * columns..(row + 1) * columns].iter().enumerate() {
                            if !entry.is_zero() {
                                pulled[part][k] += entry * value;
                            }
                        }
                    }
                    covector_energy[0].add(&energy[0]);
                    covector_energy[1].add(&energy[1]);
                    covector_energy[2].add(&dot(&pulled[0], &pulled[0]));
                    covector_energy[3].add(&dot(&pulled[1], &pulled[1]));
                }
                let theta = resident.constitution();
                let r_before = theta.receiving_map(receiving).expect("R").clone();
                let r_rem_before = theta.receiving_law(receiving).expect("R's law").map_remainder();
                let e_before = theta.source_port(source).expect("E").clone();
                let e_rem_before = theta.source_law(source).expect("E's law").map_remainder();
                let returned = port.deposit(&mut resident, staged).expect("deposit (no budget stop on this cut)");
                let reading = returned.deposit.present().cloned().expect("a deposit's reading");
                let theta = resident.constitution();
                let r_after = theta.receiving_map(receiving).expect("R").clone();
                let r_law = theta.receiving_law(receiving).expect("R's law");
                let solved = r_law.solved();
                let r_update = LocusUpdate::of(
                    &r_before,
                    &r_after,
                    &r_rem_before,
                    &r_law.map_remainder(),
                    &released_map(&reading.released, Locus::ReceivingMap(receiving)),
                );
                let e_update = LocusUpdate::of(
                    &e_before,
                    theta.source_port(source).expect("E"),
                    &e_rem_before,
                    &theta.source_law(source).expect("E's law").map_remainder(),
                    &released_map(&reading.released, Locus::SourcePort(source)),
                );
                let applied = r_after.subtract(&r_before).expect("one shape");
                let mut leverage = Vec::new();
                let mut moved = Rat::zero();
                let mut covector = Rat::zero();
                for sample in &receiving_samples {
                    let reach = solved.apply(&sample.feature).expect("one width");
                    leverage.push(dot(&sample.feature, &reach));
                    let change = applied.apply(&sample.feature).expect("one width");
                    moved = moved.max(max_abs(&change));
                    covector = covector.max(max_abs(&sample.covector));
                }
                deposits.push(DepositRecord {
                    aeon,
                    leverage,
                    moved,
                    covector,
                    receiving: r_update,
                    source: e_update,
                    stepped: reading.stepped,
                    released_bits: reading.released_bits,
                });
            }
        } else {
            for &code in window {
                order_zero[code] += 1;
                seen += 1;
            }
        }
        let mut fed = 0;
        while fed < window.len() {
            let (_, ingested) = port.ingest(&mut resident, Some(&moment), &one_hot(&window[fed..])).expect("ingest");
            let ingested = ingested.forward.into_present().expect("ingest returns");
            // The recency reading: the source ring's phase after each cell fed.
            let fed_now = ingested.cells;
            let phase = phase_of(field, resident.current().lift())[source];
            // Ingest stops at a carry-out, so the phase read after a batch is the phase of its last
            // cell; within a two-cell window a move at the first cell and none at the second is
            // read as a move (the run restarts at the batch's cells).
            if last_phase == Some(phase) {
                run_length += fed_now as u64;
            } else {
                run_length = fed_now as u64;
                last_phase = Some(phase);
            }
            fed += fed_now;
            if ingested.carry_out {
                let _boundary = port.close_aeon(&mut resident, &family).expect("close the aeon");
                let at = position + fed;
                aeon_cells.push(at - aeon_start);
                aeon += 1;
                let span = cut.closing_crib(aeon_start, at, crib.window);
                if span.len() > crib.offset {
                    let crib_codes: Vec<usize> = cells[span.clone()].to_vec();
                    let located = port.locate_keys(&mut resident, &one_hot(&crib_codes), crib.offset).expect("locate keys");
                    let (fibres, orbits, fell_back, failing) = match &located.receipt.detail {
                        ReceiptDetail::Keys { fibres, orbits, fell_back, failing_loops, .. } => (
                            fibres.clone(),
                            orbits.clone(),
                            fell_back.clone(),
                            failing_loops.iter().map(|walk| walk.as_ref().map(Vec::len)).collect::<Vec<_>>(),
                        ),
                        _ => unreachable!("a key location's receipt"),
                    };
                    let location: KeyLocation = located.forward.into_present().expect("a key location");
                    published += location.rings.iter().filter(|ring| ring.published.is_some()).count();
                    let configurations = location.configurations();
                    let rings = (0..field.rings().len())
                        .map(|g| RingLocation {
                            ring: g,
                            fibre: fibres[g],
                            orbits: orbits[g],
                            fell_back: fell_back[g],
                            failing: failing[g],
                            closure: closure(field, g, &crib_codes, crib.offset, &configurations, &mut Draw(0x5EA2_0000 + (at as u64) * 16 + g as u64)),
                            null: null_closures(field, g, &crib_codes, crib.offset, &configurations, 0x5EED_0000 + (at as u64) * 16 + g as u64),
                        })
                        .collect();
                    locations.push(LocationRecord { cell: at, crib: span, rings });
                }
                aeon_start = at;
            }
        }
        position = end;
    }
    let gram = resident
        .constitution()
        .receiving_law(receiving)
        .expect("R's law")
        .gram()
        .to_rows();
    Run {
        reads,
        deposits,
        locations,
        aeon_cells,
        training,
        held: held_sums,
        recency,
        covector_energy,
        gram_determinant: determinant(gram),
        receiving_map: resident.constitution().receiving_map(receiving).expect("R").clone(),
        moment: resident.moment(&moment).expect("the moment").clone(),
        windows,
        open: open_windows,
        published,
        complete,
        wall_ms: clock.elapsed().as_millis(),
    }
}

