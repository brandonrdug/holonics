struct StagePart {
    ticks: [u64; 2],
    copies: u64,
    staged: [ExactInterval; 2],
    inner: [ExactInterval; 2],
    stage: ExactInterval,
    conditioned: ExactInterval,
}

/// A code on one population: the later passage's less the earlier's, or the development's alone.
fn since(now: &PassageCode, then: Option<&PassageCode>) -> ExactInterval {
    match then {
        Some(then) => minus(&bits(now), &bits(then)),
        None => bits(now),
    }
}

impl StagePart {
    fn of(now: &StageReadout, before: Option<&StageReadout>) -> Self {
        Self {
            ticks: [0, 1].map(|at| now.ticks[at] - before.map_or(0, |b| b.ticks[at])),
            copies: now.copies - before.map_or(0, |b| b.copies),
            staged: [0, 1].map(|at| since(&now.staged[at], before.map(|b| &b.staged[at]))),
            inner: [0, 1].map(|at| since(&now.inner[at], before.map(|b| &b.inner[at]))),
            stage: since(&now.stage, before.map(|b| &b.stage)),
            conditioned: since(&now.conditioned, before.map(|b| &b.conditioned)),
        }
    }
}

/// A relation's pointer on one population: its reading parts, those held, and its code.
fn pointer_part(
    now: &PointerReadout,
    before: Option<&PointerReadout>,
) -> (u64, u64, ExactInterval) {
    (
        now.parts - before.map_or(0, |b| b.parts),
        now.held - before.map_or(0, |b| b.held),
        since(&now.code, before.map(|b| &b.code)),
    )
}

/// **The admitted receivers on one population** (module header): the request's copy stage against
/// the boundary egg on the same ticks, its pointer and the net, and the later human's receipt.
/// Returns the request's pointer code, charged to the curated stream.
fn receivers(now: &AdmittedReadout, before: Option<&AdmittedReadout>) -> ExactInterval {
    let grain = super::GRAIN;
    let stage = |index: usize| StagePart::of(&now.stages[index], before.map(|b| &b.stages[index]));
    let pointer = |kind: RelationKind| {
        pointer_part(
            &now.pointers[kind.index()],
            before.map(|b| &b.pointers[kind.index()]),
        )
    };
    let law = now.stages[0].law;
    println!(
        "  the admitted receivers (the copy stage: least {}, {} length classes, {} odds classes a side):",
        law.least, law.lengths, law.odds
    );
    let request = stage(0);
    let (parts, held, code) = pointer(RelationKind::Request);
    println!(
        "    the request→response receiver: {} agent bytes and {} closes read against their request ({} copies)",
        request.ticks[0], request.ticks[1], request.copies
    );
    ordering(
        "on those agent bytes, the receiver against the boundary egg (the request's port unheld)",
        &request.staged[0],
        &request.inner[0],
        request.ticks[0],
    );
    ordering(
        "at those closes, the receiver against the boundary egg",
        &request.staged[1],
        &request.inner[1],
        request.ticks[1],
    );
    println!(
        "      the chain rule: the stage's faces {}, the conditioned faces {}",
        reading_of(&request.stage, grain),
        reading_of(&request.conditioned, grain)
    );
    println!(
        "    the incidence's code, the request's pointer at {parts} agent letters ({held} held): {}",
        reading_of(&code, grain)
    );
    let value = minus(
        &sum(&request.staged[0], &request.staged[1]),
        &sum(&request.inner[0], &request.inner[1]),
    );
    println!(
        "    the receiver's value, its pointer paid (the staged code less the unheld, plus the pointer): {}",
        reading_of(&sum(&value, &code), grain)
    );
    let later = stage(1);
    let (parts, held, later_code) = pointer(RelationKind::LaterHuman);
    println!(
        "    the response→later-human receipt (an observation, never in the face): {} human bytes and {} closes read against the response they follow ({} copies)",
        later.ticks[0], later.ticks[1], later.copies
    );
    ordering(
        "on those human bytes, conditioned on the response against unconditioned (the boundary egg)",
        &later.staged[0],
        &later.inner[0],
        later.ticks[0],
    );
    ordering(
        "at those closes, conditioned against unconditioned",
        &later.staged[1],
        &later.inner[1],
        later.ticks[1],
    );
    println!(
        "      the chain rule: the stage's faces {}, the conditioned faces {}; its pointer at {parts} human letters ({held} held) {}",
        reading_of(&later.stage, grain),
        reading_of(&later.conditioned, grain),
        reading_of(&later_code, grain)
    );
    println!(
        "    retention: {} spans held ({} cells) at the passage's end, at most {} cells held at once",
        now.retained, now.retained_cells, now.widest_cells
    );
    code
}

/// The population's readings on one population against the flat tree's, beside the recorded
/// readings; returns the whole curated stream against the flat stream.
#[allow(clippy::too_many_arguments)]
fn readings(
    part: usize,
    readings: &[PartReading],
    flat: &[[PassageCode; 3]; 2],
    counts: &[[u64; 4]; 2],
    charge: &ExactInterval,
    flat_charge: u64,
    egg: usize,
    pointer: &ExactInterval,
) -> ExactInterval {
    let grain = super::GRAIN;
    let at = |slot: usize| &readings[part * SLOTS.len() + slot];
    println!(
        "  the population against the flat tree (D = {FLAT_DEPTH}) on identical bytes, uncharged:"
    );
    let mut population_bytes = point(0);
    for (slot, name) in SLOTS.iter().enumerate().take(LETTERS) {
        if counts[part][slot] == 0 {
            println!("    {name}: no cells");
            continue;
        }
        let (population, tree) = (&at(slot).population, bits(&flat[part][slot]));
        population_bytes = sum(&population_bytes, population);
        println!(
            "    {name} ({} cells): population {} (a cell {}), flat {} (a cell {}); the admitted egg alone {}",
            counts[part][slot],
            reading_of(population, grain),
            per(population, counts[part][slot], grain),
            reading_of(&tree, grain),
            per(&tree, counts[part][slot], grain),
            at(slot).families[egg]
                .as_ref()
                .map_or("-".to_string(), |code| reading_of(code, grain))
        );
        ordering(
            &format!("{name}, population against flat"),
            population,
            &tree,
            counts[part][slot],
        );
        if slot == 1 {
            println!(
                "      without the admitted receivers (the population of commit 40ab94cf): {}",
                RECORDED_AGENT[part]
            );
        }
    }
    let bytes: u64 = counts[part][..LETTERS].iter().sum();
    let flat_bytes = joined(&flat[part]);
    ordering(
        &format!("every byte ({bytes}), population against flat"),
        &population_bytes,
        &flat_bytes,
        bytes,
    );
    let letters = &at(LETTERS).population;
    println!(
        "    the section letters ({}): population {} (a letter {})",
        counts[part][LETTERS],
        reading_of(letters, grain),
        per(letters, counts[part][LETTERS], grain)
    );
    let whole = sum(&sum(&sum(&population_bytes, letters), charge), pointer);
    let flat_whole = sum(&flat_bytes, &point(flat_charge));
    println!(
        "  the whole curated stream (bytes, sections and the request's pointer {}) charged {} bits: {}",
        reading_of(pointer, grain),
        reading_of(charge, grain),
        enclosure(&whole, grain)
    );
    println!(
        "  the flat stream (bytes alone) charged {flat_charge} bits: {}",
        enclosure(&flat_whole, grain)
    );
    ordering(
        "the whole curated stream against the flat stream, a byte",
        &whole,
        &flat_whole,
        bytes,
    );
    let delta = ExactInterval {
        lower: &whole.lower - &flat_whole.upper,
        upper: &whole.upper - &flat_whole.lower,
    };
    println!(
        "    beside, recorded on the same cells (the whole curated stream against the flat stream):"
    );
    for (label, cells) in &RECORDED_WHOLE {
        let (carry, phase) = cells[part];
        println!(
            "      {label}: {carry} + {phase}/{grain} + ε; this passage lies {} it",
            against(&delta, &grain_cell(cells[part]))
        );
    }
    delta
}

#[allow(clippy::too_many_lines)]
/// How far the harness reads: the merges' learning alone, the development cells, or the whole cut.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Reach {
    Merges,
    Development,
    Whole,
}

pub fn harness(curated_path: &str, flat_path: &str, reach: Reach) {
    let clock = Instant::now();
    let chart = SectionChart::curated();
    let cut = read_curated(curated_path, &chart);
    let (flat_bytes, flat_count, flat_held) = read_cut(flat_path);
    let bytes_of: Vec<usize> = cut
        .codes
        .iter()
        .copied()
        .filter(|&code| chart.section(code).is_none())
        .collect();
    let identical = bytes_of.len() == flat_count
        && bytes_of
            .iter()
            .zip(&flat_bytes)
            .all(|(&a, &b)| a == usize::from(b));
    assert!(identical, "the flat cut is the curated cut's bytes");
    let development = cut.held.start;
    let flat_development = cut.codes[..development]
        .iter()
        .filter(|&&code| chart.section(code).is_none())
        .count();
    assert_eq!(
        flat_held.start, flat_development,
        "identical held-out cells"
    );
    let field = Field::declare(FieldDeclaration::campaign_one(cut.population))
        .expect("campaign 1's declared field at the population");
    let grain = receiver_grain(&field);
    assert_eq!(grain, super::GRAIN, "the receiver's grain");

    // Each cell's part: its population and its slot (the channel of its part, or a letter).
    let mut open = None;
    let mut counts = [[0u64; 4]; 2];
    let parts: Vec<usize> = cut
        .codes
        .iter()
        .enumerate()
        .map(|(position, &code)| {
            let slot = match chart.section(code) {
                Some(section) => {
                    open = Some(section.channel);
                    LETTERS
                }
                None => open.expect("the cut opens at a section letter"),
            };
            let population = usize::from(position >= development);
            counts[population][slot] += 1;
            population * SLOTS.len() + slot
        })
        .collect();
    println!(
        "hnn_population curated: the curated source through the egg population against the flat stream of the same bytes (campaign 5; #73, #148)"
    );
    println!(
        "0. the cut: {} curated cells (|A| = {}), {flat_count} flat cells, identical bytes: {identical}; n* = {}, L_R = {grain}",
        cut.codes.len(),
        chart.alphabet(),
        cut.population
    );
    for (part, name) in PARTS.iter().enumerate() {
        println!(
            "  {name}: human {}, agent {}, tool {}, section letters {}",
            counts[part][0], counts[part][1], counts[part][2], counts[part][LETTERS]
        );
    }

    // 1. The merges, decided on the development cells only.
    let learning = Instant::now();
    let (partition, learning_receipt) =
        learn_hazard_partition(chart, &cut.codes[..development]).expect("the learned partition");
    println!(
        "1. the merges, decided on the development cells only (the held-out cells are not read): {} ms",
        learning.elapsed().as_millis()
    );
    learned(&learning_receipt, &partition);
    if reach == Reach::Merges {
        println!("wall time in all: {} ms", clock.elapsed().as_millis());
        return;
    }
    let classes_only = HazardPartition::learned(
        partition.classes().to_vec(),
        std::collections::BTreeMap::new(),
    )
    .expect("the learned classes");
    // The comparisons read on the same cells: the declared partition, and the other of the second
    // stage's two outcomes (the shares when refused, the classes alone when adopted).
    let other = if learning_receipt.shares_adopted {
        ("learned classes without shares", classes_only)
    } else {
        (
            "learned classes with the refused shares",
            learning_receipt.shared.clone(),
        )
    };
    println!();

    // 2. The declarations.
    let cells = |depth| {
        declaration(
            chart.alphabet(),
            depth,
            cut.population,
            grain,
            LetterFamily::cells(),
        )
    };
    let slots = || Sections::new(chart, SectionSlots::Channel).expect("the channel slot");
    let typed = |depth| {
        declaration(
            chart.alphabet(),
            depth,
            cut.population,
            grain,
            slots().family().clone(),
        )
    };
    let cell_deepest = deepest(&cells(CELL_DEPTHS[CELL_DEPTHS.len() - 1]));
    let typed_deepest = deepest(&typed(TYPED_DEPTHS[TYPED_DEPTHS.len() - 1]));
    let letter_declaration = declaration(
        chart.letters(),
        LETTER_DEPTH,
        cut.population,
        grain,
        BoundaryEgg::letter_family(cut.population).expect("the letter family"),
    );
    let families = CELL_DEPTHS.len() + 1 + TYPED_DEPTHS.len() + 1;
    let naming = ceil_log2(families as u64);
    let mut declared: Vec<Box<dyn Family>> = Vec::new();
    for depth in CELL_DEPTHS.iter().copied().chain([cell_deepest]) {
        declared.push(Box::new(
            TreeFamily::new(cells(depth), naming).expect("a cell tree"),
        ));
    }
    for &depth in &TYPED_DEPTHS {
        declared.push(Box::new(
            TreeFamily::sectioned(typed(depth), naming, slots()).expect("a typed tree"),
        ));
    }
    let egg_index = declared.len();
    let relations = read_incidence(curated_path);
    let law = CopyLaw::new(COPY_LAW.0, COPY_LAW.1, COPY_LAW.2).expect("the copy stage's law");
    let declared_relations = |kind: RelationKind, part: usize| {
        relations
            .iter()
            .filter(|relation| {
                relation.kind == kind && usize::from(relation.letter >= development as u64) == part
            })
            .count()
    };
    let inner = BoundaryEgg::new(
        format!(
            "boundary egg (part clock ⊳ typed tree D = {typed_deepest}, letter tree D_L = {LETTER_DEPTH}; the learned hazard partition)"
        ),
        naming,
        TreeFamily::sectioned(typed(typed_deepest), naming, slots()).expect("the byte tree"),
        chart,
        letter_declaration,
    )
    .expect("the boundary egg")
    .with_hazard(partition.clone())
    .expect("the learned hazard")
    .compared_with("declared".to_string(), HazardPartition::declared())
    .expect("the declared hazard")
    .compared_with(other.0.to_string(), other.1)
    .expect("the second stage's other outcome");
    declared.push(Box::new(
        AdmittedEgg::new(
            format!(
                "admitted receivers (request ⊳ boundary egg: part clock ⊳ typed tree D = {typed_deepest}, letter tree D_L = {LETTER_DEPTH}; the learned hazard partition)"
            ),
            naming,
            inner,
            chart,
            relations.clone(),
            law,
        )
        .expect("the admitted receivers")
        .with_receipt(RelationKind::LaterHuman, law),
    ));
    let swept: u64 = PROBED.iter().map(|&count| ceil_log2(count)).sum();
    let charge = sum(&point(swept), &learning_receipt.description);
    let flat_charge = ceil_log2(FLAT_SWEEP);
    println!(
        "2. the population: {families} families, each named by ⌈log₂ {families}⌉ = {naming} bits (M = {families}/{}): the cell tree at D = {:?}, the typed tree (channel slot) at D = {TYPED_DEPTHS:?}, the admitted receivers over the boundary egg on the typed tree at D = {typed_deepest} with the learned hazard partition; the development sweep charged {swept} bits and the learned partition's description {}, the flat tree's {flat_charge}",
        1u64 << naming,
        CELL_DEPTHS
            .iter()
            .copied()
            .chain([cell_deepest])
            .collect::<Vec<_>>(),
        reading_of(&learning_receipt.description, grain),
    );
    println!(
        "  the declared relations: requests {} development, {} held out; later human returns {} and {}",
        declared_relations(RelationKind::Request, 0),
        declared_relations(RelationKind::Request, 1),
        declared_relations(RelationKind::LaterHuman, 0),
        declared_relations(RelationKind::LaterHuman, 1)
    );
    let mut population = Population::new(declared).expect("the population");
    println!("  setup: {} ms", clock.elapsed().as_millis());
    println!();

    // 3. One passage: the development cells, then the held-out cells.
    let passage = Instant::now();
    let (_, mut reading) = population
        .receive_partitioned(
            &cut.codes[..development],
            &parts[..development],
            2 * SLOTS.len(),
        )
        .expect("the development cells");
    let development_ms = passage.elapsed().as_millis();
    let development_receipt = population.receipt().expect("a receipt");
    let Some(Readout::Admitted(development_admitted)) = population.readout(egg_index) else {
        panic!("the admitted receivers' readout")
    };
    let development_stages = &development_admitted.inner;
    if reach == Reach::Development {
        println!(
            "3. the development cells only (the held-out cells are not read): {development_ms} ms; resident set (now, peak) {:?} bytes",
            resident_set()
        );
        println!();
        println!(
            "4. development, the population alone (the flat tree's recorded development code 1800742 + 1/16 + ε):"
        );
        let letters = &reading[LETTERS].population;
        let bytes: Vec<&ExactInterval> =
            (0..LETTERS).map(|slot| &reading[slot].population).collect();
        let bytes = Stages::total(&bytes);
        println!(
            "  bytes {} (agent {}), section letters {}",
            reading_of(&bytes, grain),
            reading_of(&reading[1].population, grain),
            reading_of(letters, grain),
        );
        selection(&development_receipt);
        stages(
            &Stages::of(development_stages, None),
            &["human", "agent", "tool"],
            counts[0][LETTERS],
        );
        let pointer = receivers(&development_admitted, None);
        println!(
            "  the whole charged {} bits, the request's pointer paid: {}",
            reading_of(&charge, grain),
            reading_of(&sum(&sum(&sum(&bytes, letters), &charge), &pointer), grain)
        );
        println!("wall time in all: {} ms", clock.elapsed().as_millis());
        return;
    }
    let (_, held) = population
        .receive_partitioned(
            &cut.codes[development..],
            &parts[development..],
            2 * SLOTS.len(),
        )
        .expect("the held-out cells");
    for (index, part) in held.into_iter().enumerate() {
        if index >= SLOTS.len() {
            reading[index] = part;
        }
    }
    let receipt = population.receipt().expect("a receipt");
    let Some(Readout::Admitted(whole_admitted)) = population.readout(egg_index) else {
        panic!("the admitted receivers' readout")
    };
    let whole_stages = &whole_admitted.inner;
    let resident = resident_set();
    println!(
        "3. one passage of the population over the whole cut: development {development_ms} ms, in all {} ms; resident set (now, peak) {resident:?} bytes",
        passage.elapsed().as_millis()
    );
    drop(population);

    // The flat tree over the flat twin, once.
    let flat_clock = Instant::now();
    let mut flat_tree = TreeFamily::new(
        declaration(
            256,
            FLAT_DEPTH,
            cut.population,
            grain,
            LetterFamily::cells(),
        ),
        0,
    )
    .expect("the flat tree");
    let mut flat = [[PassageCode::new(); 3]; 2];
    let byte_slots: Vec<usize> = parts
        .iter()
        .filter(|&&part| part % SLOTS.len() != LETTERS)
        .map(|&part| part % SLOTS.len())
        .collect();
    for (position, &byte) in flat_bytes.iter().enumerate() {
        let face = flat_tree
            .receive(usize::from(byte))
            .expect("a byte of the flat chart");
        flat[usize::from(position >= flat_held.start)][byte_slots[position]]
            .face(&face)
            .expect("a positive face");
    }
    println!(
        "  the flat tree at D = {FLAT_DEPTH}, one passage over the flat twin: {} ms",
        flat_clock.elapsed().as_millis()
    );
    println!();

    // 4. The readings; development's choice is read from the development readings alone.
    let channels = ["human", "agent", "tool"];
    let mut adopted = false;
    for (part, name) in PARTS.iter().enumerate() {
        println!(
            "{}. {name} ({} bytes, {} section letters), bits at L_R = {grain}:",
            4 + part,
            counts[part][..LETTERS].iter().sum::<u64>(),
            counts[part][LETTERS]
        );
        let (admitted, before) = if part == 0 {
            (&development_admitted, None)
        } else {
            (&whole_admitted, Some(&*development_admitted))
        };
        let pointer = since(
            &admitted.pointers[RelationKind::Request.index()].code,
            before.map(|b| &b.pointers[RelationKind::Request.index()].code),
        );
        let whole = readings(
            part,
            &reading,
            &flat,
            &counts,
            &charge,
            flat_charge,
            egg_index,
            &pointer,
        );
        let recorded = grain_cell(RECORDED_WHOLE[0].1[part]);
        if part == 0 {
            adopted = whole.upper < recorded.lower;
            println!(
                "  development's choice (the learned partition in the admitted egg, its description charged, against the declared partition's recorded reading on the same cells): {}",
                if adopted {
                    "the learned partition adopted"
                } else {
                    "the declared partition kept (the learned one is not below it)"
                }
            );
        } else {
            println!(
                "  held out, read once after development's choice and choosing nothing: the {} partition's admitted egg {} the declared partition's recorded reading",
                if adopted {
                    "adopted learned"
                } else {
                    "disclosed (not adopted) learned"
                },
                against(&whole, &recorded)
            );
        }
        println!("  each family's code on this population:");
        let family_receipt = if part == 0 {
            &development_receipt
        } else {
            &receipt
        };
        for (index, family) in family_receipt.families.iter().enumerate() {
            let code = (0..SLOTS.len())
                .map(|slot| reading[part * SLOTS.len() + slot].families[index].clone())
                .collect::<Option<Vec<ExactInterval>>>()
                .map(|codes| Stages::total(&codes.iter().collect::<Vec<_>>()));
            println!(
                "    [{index}] {}: {}",
                family.label,
                code.map_or("dead".to_string(), |code| reading_of(&code, grain))
            );
        }
        println!("  the posterior after the {name} cells:",);
        selection(family_receipt);
        let egg_stages = if part == 0 {
            Stages::of(development_stages, None)
        } else {
            Stages::of(whole_stages, Some(development_stages))
        };
        stages(&egg_stages, &channels, counts[part][LETTERS]);
        receivers(admitted, before);
        if part == 0 {
            println!(
                "    the retired per-port reader's closes on the development cells: human {}, agent {}; its section navigator's letters {RETIRED_LETTERS}",
                RETIRED_CLOSES[0], RETIRED_CLOSES[1]
            );
        }
        println!();
    }
    println!(
        "the population's code over the whole cut: {}",
        enclosure(&receipt.code, grain)
    );
    println!("wall time in all: {} ms", clock.elapsed().as_millis());
}
