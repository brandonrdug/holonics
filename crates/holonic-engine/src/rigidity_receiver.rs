//! **The rigidity receiver: the constraint Jacobian and its two null spaces.**
//!
//! [definition] The physical ontology of
//! `research/records/2026-08-21_THE_FOLD_IS_A_CONSTRAINT_ECOLOGY_THE_ACTIVE_SITE_IS_A_CATALYTIC_RECEIVER_AND_THE_CODEC_RECOVERS_ARCHETYPES.md`
//! §5 represents a physical structure at one grain as
//!
//! ```text
//! P_eta = ( V, C_eta, q, F_eta, J_eta, G, E_eta, R_eta, Gamma_eta )
//! ```
//!
//! with `F_eta(q) = 0` the constraint system, `J_eta = D F_eta(q)` its rigidity Jacobian,
//! `ker J_eta` the infinitesimal motions and `ker J_eta^T` the self-stresses or constraint
//! reactions. This module owns that object exactly. It is the receiver **R4** of
//! `docs/plans/THE_RECEIVER_ATLAS_SEPARATES_WHAT_ONE_FACE_CANNOT.md` and the rigidity half of
//! **B7** in `docs/plans/THE_BIOLOGICAL_ECOLOGY_INSTANTIATES_THE_CARRIER.md`.
//!
//! # What the Jacobian is, and why it is exact
//!
//! [proved-derived; implemented-exact] One distance constraint between occurrences `i` and `j` is
//! `F_c(q) = |q_i − q_j|² − ℓ_c²`. Its differential is read off an exact algebraic expansion and
//! needs no analysis at all:
//!
//! ```text
//! F_c(q + t v) = F_c(q) + t · 2 ⟨q_i − q_j, v_i − v_j⟩ + t² · |v_i − v_j|²
//! ```
//!
//! so the row of `J = D F(q)` at `c` carries `2(q_i − q_j)` in block `i`, `−2(q_i − q_j)` in
//! block `j`, and zero elsewhere. Over exact rational coordinates every entry, every rank, every
//! kernel basis vector and every cluster verdict below is exact. **No float enters any of them.**
//! `ExactConfiguration::from_presented` refuses a presented position whose coordinate box has
//! width, by name, rather than choosing a representative inside it: an interval position is a
//! precision question and it is not a configuration.
//!
//! # The two null spaces
//!
//! [proved-standard] `ker J` is the infinitesimal motion space and `ker Jᵀ` is the self-stress —
//! equivalently constraint-reaction — space. Both come from
//! [`holonics::exact_linear::ExactRatMatrix`]: `kernel_basis` at `exact_linear.rs:770` and
//! `cokernel_annihilator` at `:814`, with `rank` at `:761`. Nothing here reimplements them.
//!
//! # The trivial motions are measured, never assumed
//!
//! [proved-derived; implemented-exact] A `d`-dimensional rigid body is usually said to have
//! `d(d+1)/2` trivial motions — `6` in three dimensions. **That number is a property of the
//! configuration, not of the dimension**, and this module never assumes it. The trivial space is
//! the span of `d` translation generators and `d(d−1)/2` rotation generators *linearized about the
//! given configuration `q`*: the rotation generated by the antisymmetric `Ω = E_ab − E_ba` assigns
//! occurrence `i` the velocity `Ω q_i`, which is a function of `q`. Its dimension is measured as
//! the exact rank of the generator matrix and is independently checked against the closed form
//!
//! ```text
//! dim T(q) = d + d(d−1)/2 − (d−k)(d−k−1)/2,    k = dim span{ q_i − q_0 }
//! ```
//!
//! derived from the kernel of `(t, Ω) ↦ (t + Ω q_i)_i`: that kernel is `{Ω ∈ so(d) : Ω|_W = 0}`
//! for `W` the linear span of the differences, and an antisymmetric map killing `W` is an
//! antisymmetric map of `W^⊥`. In three dimensions this is `6` for a spanning **or coplanar**
//! configuration, `5` for a collinear one, and `3` for a coincident one.
//! [`ConfigurationDegeneracy`] names which case the configuration is in, exactly, and
//! [`RigidityError::TrivialDimensionDisagrees`] refuses if the measured rank and the closed form
//! ever part company.
//!
//! [proved-derived; implemented-exact] That the trivial motions really are motions is **proved,
//! not asserted**: every generator is applied to `J` and the product is required to vanish
//! entry by entry, refusing with [`RigidityError::TrivialMotionOutsideKernel`] naming the
//! generator and the constraint. The mathematics behind it is one line —
//! `v_i − v_j = Ω(q_i − q_j)` and `⟨x, Ω x⟩ = 0` for antisymmetric `Ω` — and it is the Lean
//! theorem `rigid_motion_mem_ker`.
//!
//! # The Maxwell relation and where it is only a bound
//!
//! [proved-standard] Two identities hold unconditionally and are checked at every reading:
//!
//! ```text
//! rank J + dim ker J = d·n          (rank–nullity on the configuration space)
//! dim ker Jᵀ = m − rank J           (rank–nullity on the constraint space)
//! ```
//!
//! Subtracting gives the exact Maxwell relation `dim ker J − dim ker Jᵀ = d·n − m`. The *count*
//! `d·n − m` therefore equals `dim ker J` **only when there is no self-stress**, and is otherwise
//! a strict lower bound. [`MaxwellCount::count_is_a_bound_only`] says which case holds on the
//! actual data.
//!
//! [definition] A count is a necessary condition and never a sufficient one, and this module
//! claims **infinitesimal** rigidity at the given configuration and nothing else. Generic
//! rigidity is a statement about almost every configuration of a combinatorial structure; a
//! degenerate or redundant configuration breaks the passage from one to the other in both
//! directions, and [`RigidityReading::is_infinitesimally_rigid`] is named so that it cannot be
//! read as either generic or finite rigidity.
//!
//! # Rigid clusters and contact-removal sensitivity
//!
//! [proved-derived; implemented-exact] A pair `(i,j)` is **implied** when its separation is
//! first-order constant under every admitted infinitesimal motion, i.e. when its constraint row
//! `r_ij` annihilates `ker J` — equivalently when `r_ij` lies in the row space of `J`, since over
//! `ℚ` with the standard pairing `(ker J)^⊥ = row J`. A **rigid cluster** is a maximal set of
//! occurrences all of whose pairs are implied; every infinitesimal motion then restricts to a
//! rigid motion of that sub-configuration, and [`rigid_clusters`] verifies exactly that for every
//! returned cluster against every kernel basis vector. Clusters **overlap**: two rigid bodies
//! sharing a hinge are two clusters sharing an occurrence, and that is the phenomenon, not a
//! defect. Enumeration is bounded explicitly and refuses with
//! [`RigidityError::ClusterPopulationTooWide`] rather than exhausting the machine.
//!
//! [proved-derived; implemented-exact] Removing one constraint changes `dim ker J` **exactly
//! when that constraint carries no self-stress.** If some `w ∈ ker Jᵀ` has `w_c ≠ 0` then
//! `row_c = −w_c^{-1} Σ_{k≠c} w_k row_k` lies in the span of the others and the rank is unmoved;
//! conversely a dependent row yields such a `w` with `w_c = 1`. So the sensitivity question of
//! item 4 is answered by the self-stress space of item 2, with no second computation —
//! [`removal_sensitivity`] reads it off the cokernel basis, and
//! [`verify_removal_sensitivity`] re-derives a bounded sample by actually deleting the row and
//! recomputing the exact rank.
//! The law is formal-checked over this owner's own `selfStresses` and `rigidityMatrix` as
//! `Transport/EditRigidity.lean::dependent_iff_droppingLosesNothing`, with
//! `Transport/EditRigidity.lean::entanglement_is_self_stress_support` its edit-side reading.
//!
//! # The open family
//!
//! [definition] `crate::physical_constraint_grading` returns a **family** of complexes because an
//! `Open` contact is a 1-cell that may or may not exist, and different resolutions give different
//! homology. A constraint that may or may not exist makes the constraint *system* plural in the
//! same way, so the rigidity reading is a family too, indexed identically:
//! [`rigidity_family`] returns the `refusing` and `admitting` bounds of that indexing with their
//! open set retained, and never promotes or demotes an open contact. Admitting more constraints
//! can only shrink the motion space, so the two bounds bracket `dim ker J`; when they differ, the
//! open class is a **rigidity** question and not bookkeeping, and
//! [`RigidityFamily::bounds_differ_in_motion_dimension`] says so on the actual data.
//!
//! # Formal owner
//!
//! `formal/elementary-holonics/ElementaryHolonics/Foundation/RigidityReceiver.lean`, namespace
//! `Soma.Holonics.Foundation.RigidityReceiver`. The correspondence, both directions:
//!
//! | Rust | Lean |
//! |---|---|
//! | [`ExactConfiguration`], [`DistanceConstraint`] | `ConstraintSystem` (`left`, `right`, `place`) |
//! | [`DistanceConstraint::squared_length`] read from the configuration | `constraintMap`, `constraintMap_place` |
//! | the row law `2(q_i − q_j)` with opposite sign in the two blocks | `rigidityMatrix`, `bump`, `sum_bump`, `rigidityMatrix_mulVec` |
//! | `J = D F(q)` with no analysis, from the exact expansion | `constraint_expansion`, `jacobian_is_the_differential` |
//! | [`RigidityJacobian::matrix`] | `rigidityLin` |
//! | [`RigidityReading::motions`] = `ker J` | `infinitesimalMotions`, `mem_infinitesimalMotions_iff` |
//! | [`RigidityReading::self_stresses`] = `ker Jᵀ` | `selfStresses`, `self_stress_pairing` |
//! | `rank J + dim ker J = d·n`, checked at every reading | `rank_nullity`, `finrank_flat` |
//! | `dim ker Jᵀ = m − rank J`, checked at every reading | `self_stress_dimension` |
//! | [`MaxwellCount`] and [`MaxwellCount::count_is_a_bound_only`] | `maxwell_relation`, `motion_dimension_eq_count_of_no_self_stress` |
//! | [`TrivialMotionReading::generators`] linearized about `q` | `rigidMotion`, `IsSkew`, `delta_rigidMotion` |
