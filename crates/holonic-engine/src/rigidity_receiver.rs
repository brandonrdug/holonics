/// The pairs whose separation is first-order constant under every admitted infinitesimal motion.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RigidPairReading {
    pub schema: String,
    /// Block ordinal pairs `(i,j)`, `i < j`, with `r_ij ⟂ ker J`.
    pub implied_pairs: Vec<(usize, usize)>,
    /// Implied pairs that carry no constraint of their own: the constraint the structure holds
    /// without being told to.
    pub implied_without_constraint: Vec<(usize, usize)>,
    /// Implied pairs whose two occurrences are coincident. Their row is zero, so the criterion
    /// holds by degeneracy and not by rigidity; they are named so the distinction is not lost.
    pub coincident_pairs: Vec<(usize, usize)>,
}

/// Maximal sets of occurrences that move together.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RigidClusterReading {
    pub schema: String,
    /// Maximal sets of pairwise-implied occurrences, each ascending, the whole family ordered.
    /// **Clusters may overlap**: a hinge is exactly two clusters sharing an occurrence.
    pub clusters: Vec<Vec<usize>>,
    pub pairs: RigidPairReading,
    /// The enumeration ceiling this reading was taken under.
    pub bound: usize,
}

/// **Which occurrences move together under every admissible infinitesimal motion.**
///
/// Every returned cluster is verified: each kernel basis vector, restricted to the cluster, is
/// checked to lie in the trivial motion space of that sub-configuration, exactly.
pub fn rigid_clusters(
    jacobian: &RigidityJacobian,
    reading: &RigidityReading,
    bound: usize,
) -> Result<RigidClusterReading, RigidityError> {
    jacobian.validated()?;
    let dimension = jacobian.dimension();
    let places = jacobian.configuration.ordered_places();
    let occurrences = places.len();
    if reading.motions.iter().any(|motion| motion.len() != dimension * occurrences) {
        return Err(RigidityError::MotionWidthDisagrees {
            expected: dimension * occurrences,
        });
    }

    let constrained: BTreeSet<(usize, usize)> = jacobian
        .constraints
        .iter()
        .map(|constraint| {
            let (low, high) = (constraint.lower_block, constraint.upper_block);
            if low <= high { (low, high) } else { (high, low) }
        })
        .collect();

    let mut implied_pairs = Vec::new();
    let mut implied_without_constraint = Vec::new();
    let mut coincident_pairs = Vec::new();
    let mut adjacency = vec![BTreeSet::<usize>::new(); occurrences];
    for left in 0..occurrences {
        for right in (left + 1)..occurrences {
            let difference = (0..dimension)
                .map(|axis| &places[left][axis] - &places[right][axis])
                .collect::<Vec<_>>();
            let coincident = difference.iter().all(Zero::is_zero);
            let implied = reading.motions.iter().all(|motion| {
                let pairing = (0..dimension).fold(Rat::zero(), |sum, axis| {
                    let relative = &motion[left * dimension + axis]
                        - &motion[right * dimension + axis];
                    sum + &difference[axis] * &relative
                });
                pairing.is_zero()
            });
            if implied {
                implied_pairs.push((left, right));
                if !constrained.contains(&(left, right)) {
                    implied_without_constraint.push((left, right));
                }
                if coincident {
                    coincident_pairs.push((left, right));
                }
                adjacency[left].insert(right);
                adjacency[right].insert(left);
            }
        }
    }

    let mut clusters = Vec::new();
    let mut retained = Vec::new();
    bron_kerbosch(
        &adjacency,
        &mut retained,
        (0..occurrences).collect(),
        BTreeSet::new(),
        bound,
        &mut clusters,
    )?;
    clusters.sort();

    for (ordinal, cluster) in clusters.iter().enumerate() {
        if cluster.len() < 2 {
            continue;
        }
        let cluster_places = cluster
            .iter()
            .map(|block| places[*block].clone())
            .collect::<Vec<_>>();
        let generators = trivial_generators(dimension, &cluster_places)?;
        let width = dimension * cluster.len();
        let span = column_matrix(width, &generators)?;
        let span_rank = span.rank()?;
        for (motion_at, motion) in reading.motions.iter().enumerate() {
            let restricted = cluster
                .iter()
                .flat_map(|block| {
                    (0..dimension).map(move |axis| motion[block * dimension + axis].clone())
                })
                .collect::<Vec<_>>();
            let mut extended = generators.clone();
            extended.push(restricted);
            let widened = column_matrix(width, &extended)?;
            if widened.rank()? != span_rank {
                return Err(RigidityError::ClusterNotRigid {
                    cluster: ordinal,
                    motion: motion_at,
                });
            }
        }
    }

    Ok(RigidClusterReading {
        schema: RIGID_CLUSTER_SCHEMA.to_owned(),
        clusters,
        pairs: RigidPairReading {
            schema: RIGID_PAIR_SCHEMA.to_owned(),
            implied_pairs,
            implied_without_constraint,
            coincident_pairs,
        },
        bound,
    })
}

fn bron_kerbosch(
    adjacency: &[BTreeSet<usize>],
    retained: &mut Vec<usize>,
    mut candidates: BTreeSet<usize>,
    mut excluded: BTreeSet<usize>,
    bound: usize,
    clusters: &mut Vec<Vec<usize>>,
) -> Result<(), RigidityError> {
    if candidates.is_empty() && excluded.is_empty() {
        if clusters.len() >= bound {
            return Err(RigidityError::ClusterPopulationTooWide { bound });
        }
        let mut cluster = retained.clone();
        cluster.sort_unstable();
        clusters.push(cluster);
        return Ok(());
    }
    let pivot = candidates
        .union(&excluded)
        .copied()
        .max_by_key(|occurrence| adjacency[*occurrence].intersection(&candidates).count());
    let walk: Vec<usize> = match pivot {
        Some(chosen) => candidates
            .iter()
            .copied()
            .filter(|occurrence| !adjacency[chosen].contains(occurrence))
            .collect(),
        None => candidates.iter().copied().collect(),
    };
    for occurrence in walk {
        let next_candidates = candidates
            .intersection(&adjacency[occurrence])
            .copied()
            .collect();
        let next_excluded = excluded
            .intersection(&adjacency[occurrence])
            .copied()
            .collect();
        retained.push(occurrence);
        bron_kerbosch(
            adjacency,
            retained,
            next_candidates,
            next_excluded,
            bound,
            clusters,
        )?;
        retained.pop();
        candidates.remove(&occurrence);
        excluded.insert(occurrence);
    }
    Ok(())
}

