/// What removing one constraint does to the motion space.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ConstraintSensitivity {
    pub edge: ConstraintEdge,
    pub provenance: EdgeProvenance,
    /// Some self-stress has a nonzero coefficient here, so this row is dependent on the others
    /// and its removal leaves `rank J` — hence `dim ker J` — unchanged.
    pub carries_self_stress: bool,
    /// `dim ker J` after deleting this one constraint: `motion_dimension + 1` exactly when the
    /// constraint carries no self-stress, and `motion_dimension` otherwise.
    pub motion_dimension_after_removal: usize,
}

/// **Which single contact's removal changes `dim ker J`.**
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RemovalSensitivity {
    pub schema: String,
    pub motion_dimension: usize,
    pub constraints: Vec<ConstraintSensitivity>,
    /// Constraints whose removal raises the motion dimension by exactly one.
    pub load_bearing: Vec<ConstraintEdge>,
    /// Constraints whose removal moves nothing.
    pub redundant: Vec<ConstraintEdge>,
}

/// Read the sensitivity off the self-stress space. No rank is recomputed: a row is dependent on
/// the others **iff** some element of `ker Jᵀ` is supported at it.
pub fn removal_sensitivity(
    jacobian: &RigidityJacobian,
    reading: &RigidityReading,
) -> Result<RemovalSensitivity, RigidityError> {
    jacobian.validated()?;
    if reading.constraint_count != jacobian.constraint_count() {
        return Err(RigidityError::ReadingDisagreesWithJacobian {
            reading: reading.constraint_count,
            jacobian: jacobian.constraint_count(),
        });
    }
    if reading
        .self_stresses
        .iter()
        .any(|stress| stress.len() != reading.constraint_count)
    {
        return Err(RigidityError::SelfStressWidthDisagrees {
            expected: reading.constraint_count,
        });
    }
    let mut constraints = Vec::with_capacity(jacobian.constraints.len());
    let mut load_bearing = Vec::new();
    let mut redundant = Vec::new();
    for (at, constraint) in jacobian.constraints.iter().enumerate() {
        let carries_self_stress = reading
            .self_stresses
            .iter()
            .any(|stress| !stress[at].is_zero());
        let motion_dimension_after_removal = if carries_self_stress {
            redundant.push(constraint.edge);
            reading.motion_dimension
        } else {
            load_bearing.push(constraint.edge);
            reading.motion_dimension + 1
        };
        constraints.push(ConstraintSensitivity {
            edge: constraint.edge,
            provenance: constraint.provenance,
            carries_self_stress,
            motion_dimension_after_removal,
        });
    }
    Ok(RemovalSensitivity {
        schema: REMOVAL_SENSITIVITY_SCHEMA.to_owned(),
        motion_dimension: reading.motion_dimension,
        constraints,
        load_bearing,
        redundant,
    })
}

/// Re-derive a bounded prefix of the sensitivity by **actually deleting the row** and recomputing
/// the exact rank. The self-stress criterion is a theorem, so this cannot fire while the
/// elimination is correct; that is what it is for.
pub fn verify_removal_sensitivity(
    jacobian: &RigidityJacobian,
    sensitivity: &RemovalSensitivity,
    bound: usize,
) -> Result<usize, RigidityError> {
    jacobian.validated()?;
    if sensitivity.constraints.len() != jacobian.constraint_count() {
        return Err(RigidityError::ReadingDisagreesWithJacobian {
            reading: sensitivity.constraints.len(),
            jacobian: jacobian.constraint_count(),
        });
    }
    let width = jacobian.coordinate_freedoms();
    let rows = jacobian.matrix.to_rows();
    let checked = bound.min(rows.len());
    for (at, claimed) in sensitivity.constraints.iter().take(checked).enumerate() {
        let mut reduced = rows.clone();
        reduced.remove(at);
        let removed = ExactRatMatrix::shaped(reduced.len(), width, reduced)?;
        let measured = width - removed.rank()?;
        if measured != claimed.motion_dimension_after_removal {
            return Err(RigidityError::RemovalSensitivityDisagrees {
                constraint: at,
                predicted: claimed.motion_dimension_after_removal,
                measured,
            });
        }
    }
    Ok(checked)
}

