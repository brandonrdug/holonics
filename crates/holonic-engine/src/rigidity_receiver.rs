/// One distance constraint `|q_i − q_j|² − ℓ² = 0`, addressed by the canonical 1-cell it comes
/// from.
///
/// `ℓ²` is **read from the configuration**, never supplied: the presented configuration satisfies
/// `F(q) = 0` by construction, and the receiver's question is the differential there, not whether
/// some exterior target length is met.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct DistanceConstraint {
    pub edge: ConstraintEdge,
    pub provenance: EdgeProvenance,
    /// Block ordinal of `edge.lower` in the configuration's address order.
    pub lower_block: usize,
    /// Block ordinal of `edge.upper`.
    pub upper_block: usize,
    /// `|q_lower − q_upper|²`, exact.
    pub squared_length: Rat,
}

/// **`J_eta = D F_eta(q)`: the exact rational constraint Jacobian**, `m × (d·n)`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RigidityJacobian {
    pub schema: String,
    pub presentation_lineage: String,
    /// The configuration the differential is taken at. `J` is meaningless without it, so it
    /// travels with it.
    pub configuration: ExactConfiguration,
    /// The constraint population in canonical edge order; row `c` of `matrix` is constraint `c`.
    pub constraints: Vec<DistanceConstraint>,
    pub matrix: ExactRatMatrix,
    /// Constraints whose two occurrences are **coincident**. Their gradient row is identically
    /// zero, so they are not first-order restrictions at all. Named rather than dropped.
    pub coincident_constraints: Vec<ConstraintEdge>,
}

impl RigidityJacobian {
    /// The Jacobian of a declared constraint set at a declared configuration.
    pub fn found(
        presentation_lineage: impl Into<String>,
        configuration: &ExactConfiguration,
        constraints: &BTreeMap<ConstraintEdge, EdgeProvenance>,
    ) -> Result<Self, RigidityError> {
        configuration.validated()?;
        let dimension = configuration.dimension;
        let occurrences = configuration.occurrence_count();
        let blocks = configuration.blocks();
        let width = dimension
            .checked_mul(occurrences)
            .ok_or(ExactLinearError::ExtentOverflow)?;
        let coefficient = two();

        let mut rows = Vec::with_capacity(constraints.len());
        let mut population = Vec::with_capacity(constraints.len());
        let mut coincident = Vec::new();
        for (edge, provenance) in constraints {
            let lower_block = *blocks
                .get(&edge.lower)
                .ok_or(RigidityError::OccurrenceAbsent(edge.lower))?;
            let upper_block = *blocks
                .get(&edge.upper)
                .ok_or(RigidityError::OccurrenceAbsent(edge.upper))?;
            let lower_place = configuration.place(edge.lower)?;
            let upper_place = configuration.place(edge.upper)?;

            let mut row = vec![Rat::zero(); width];
            let mut squared_length = Rat::zero();
            let mut vanishes = true;
            for axis in 0..dimension {
                let difference = &lower_place[axis] - &upper_place[axis];
                squared_length += &difference * &difference;
                if !difference.is_zero() {
                    vanishes = false;
                }
                let entry = &coefficient * &difference;
                row[lower_block * dimension + axis] = entry.clone();
                row[upper_block * dimension + axis] = -entry;
            }
            // A constraint from an occurrence to itself writes `+2δ` and then `−2δ` into the same
            // block, leaving the row zero, which is the correct differential of a constant. The
            // canonical `ConstraintEdge` cannot hold one, but a remounted constraint set is not
            // bound by that, so the row law above is written to be right either way.
            if vanishes {
                coincident.push(*edge);
            }
            rows.push(row);
            population.push(DistanceConstraint {
                edge: *edge,
                provenance: *provenance,
                lower_block,
                upper_block,
                squared_length,
            });
        }

        let matrix = ExactRatMatrix::shaped(population.len(), width, rows)?;
        Ok(Self {
            schema: RIGIDITY_JACOBIAN_SCHEMA.to_owned(),
            presentation_lineage: presentation_lineage.into(),
            configuration: configuration.clone(),
            constraints: population,
            matrix,
            coincident_constraints: coincident,
        })
    }

    /// The Jacobian of one member of the open family: its 1-skeleton **is** its constraint set.
    pub fn from_member(
        member: &GradedConstraintComplex,
        configuration: &ExactConfiguration,
    ) -> Result<Self, RigidityError> {
        let mut constraints = BTreeMap::new();
        for edge in member.edge_cells.keys() {
            let provenance = member
                .edge_provenance
                .get(edge)
                .copied()
                .ok_or(RigidityError::ConstraintProvenanceAbsent(*edge))?;
            constraints.insert(*edge, provenance);
        }
        member.validate_structure()?;
        Self::found(
            member.presentation_lineage.clone(),
            configuration,
            &constraints,
        )
    }

    pub fn dimension(&self) -> usize {
        self.configuration.dimension
    }

    pub fn occurrence_count(&self) -> usize {
        self.configuration.occurrence_count()
    }

    pub fn constraint_count(&self) -> usize {
        self.constraints.len()
    }

    pub fn coordinate_freedoms(&self) -> usize {
        self.dimension().saturating_mul(self.occurrence_count())
    }

    /// The shape invariants a remounted value need not satisfy, checked by name.
    pub fn validated(&self) -> Result<(), RigidityError> {
        self.configuration.validated()?;
        let expected_columns = self.coordinate_freedoms();
        if self.matrix.rows() != self.constraints.len()
            || self.matrix.columns() != expected_columns
        {
            return Err(RigidityError::JacobianShapeDisagrees {
                rows: self.matrix.rows(),
                columns: self.matrix.columns(),
                expected_rows: self.constraints.len(),
                expected_columns,
            });
        }
        let occurrences = self.occurrence_count();
        for constraint in &self.constraints {
            if constraint.lower_block >= occurrences || constraint.upper_block >= occurrences {
                return Err(RigidityError::BlockOutsideConfiguration {
                    edge: constraint.edge,
                });
            }
        }
        Ok(())
    }
}

