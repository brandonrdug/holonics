/// **The rigidity reading of a presentation whose contact set is plural.**
///
/// Indexed exactly as `physical_constraint_grading::ConstraintComplexFamily` is: by the
/// resolutions of the open set, with the two bounds of the 1-cell inclusion order constructed.
/// This is a computed summary receipt, not a remountable source presentation: its serialized
/// bounds retain the reading but not the original physical complex and configuration needed to
/// reproduce them. Consumers that need operative material must retain those source inputs.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RigidityFamily {
    pub schema: String,
    pub presentation_lineage: String,
    /// The exact open set, each contact with the interval and aperture that could not decide it.
    pub open_contacts: Vec<OpenContact>,
    /// Open readings whose 1-cell exists anyway under another aperture. Retained, not dropped.
    pub open_subsumed_by_inside: Vec<ConstraintEdge>,
    /// Every open contact refused: the member whose incidence is the presentation's own.
    pub refusing: RigidityReading,
    /// Every open contact founded.
    pub admitting: RigidityReading,
}

impl RigidityFamily {
    /// The presentation decides its own constraint set: the family is a singleton.
    pub fn is_determinate(&self) -> bool {
        self.open_contacts.is_empty()
    }

    /// `2^n` for `n` open contacts.
    pub fn cardinality(&self) -> BigUint {
        BigUint::from(1_u8) << self.open_contacts.len()
    }

    /// `(admitting, refusing)`: adding constraints can only shrink the motion space, so these
    /// bracket `dim ker J` over the whole family.
    pub fn motion_dimension_bounds(&self) -> (usize, usize) {
        (
            self.admitting.motion_dimension,
            self.refusing.motion_dimension,
        )
    }

    /// **The finding**: the open class is a rigidity question on this presentation.
    pub fn bounds_differ_in_motion_dimension(&self) -> bool {
        self.admitting.motion_dimension != self.refusing.motion_dimension
    }
}

/// The Jacobian of one named member of the open family.
pub fn rigidity_jacobian_member(
    complex: &PhysicalConstraintComplex,
    configuration: &ExactConfiguration,
    law: &OpenContactLaw,
) -> Result<RigidityJacobian, RigidityError> {
    configuration.within_presented(complex)?;
    let member = graded_constraint_member(complex, law)?;
    RigidityJacobian::from_member(&member, configuration)
}

/// The rigidity reading of one named member of the open family.
pub fn rigidity_member(
    complex: &PhysicalConstraintComplex,
    configuration: &ExactConfiguration,
    law: &OpenContactLaw,
) -> Result<RigidityReading, RigidityError> {
    let jacobian = rigidity_jacobian_member(complex, configuration, law)?;
    rigidity_reading(&jacobian)
}

/// **The family, with its open set and its two bounding readings.**
pub fn rigidity_family(
    complex: &PhysicalConstraintComplex,
    configuration: &ExactConfiguration,
) -> Result<RigidityFamily, RigidityError> {
    configuration.within_presented(complex)?;
    let family = graded_constraint_family(complex)?;
    let refusing = rigidity_reading(&RigidityJacobian::from_member(
        &family.refusing,
        configuration,
    )?)?;
    let admitting = rigidity_reading(&RigidityJacobian::from_member(
        &family.admitting,
        configuration,
    )?)?;
    if admitting.motion_dimension > refusing.motion_dimension {
        return Err(RigidityError::MotionDimensionNotAntitone {
            refusing: refusing.motion_dimension,
            admitting: admitting.motion_dimension,
        });
    }
    Ok(RigidityFamily {
        schema: RIGIDITY_FAMILY_SCHEMA.to_owned(),
        presentation_lineage: complex.presentation_lineage.clone(),
        open_contacts: family.open_contacts,
        open_subsumed_by_inside: family.open_subsumed_by_inside,
        refusing,
        admitting,
    })
}

