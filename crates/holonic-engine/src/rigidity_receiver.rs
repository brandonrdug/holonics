/// How the configuration's affine span sits inside the ambient dimension. This is what decides
/// the trivial motion count, so it is measured and named rather than assumed.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub enum ConfigurationDegeneracy {
    /// Every occurrence sits at one place: the span of differences is `{0}`. Every rotation
    /// generator vanishes and only the `d` translations remain.
    Coincident,
    /// The span of differences is a line, and the rotations fixing that line are lost.
    Collinear,
    /// A proper affine span of dimension at least two. In three dimensions this is the coplanar
    /// case, which loses **nothing**: a plane still carries all six rigid motions of space.
    Deficient,
    /// The occurrences affinely span the ambient space.
    Spanning,
}

/// **The trivial motions at this configuration, measured.**
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct TrivialMotionReading {
    pub schema: String,
    pub dimension: usize,
    pub occurrences: usize,
    /// `k = dim span{ q_i − q_0 }`, exact.
    pub affine_span_dimension: usize,
    pub degeneracy: ConfigurationDegeneracy,
    /// `d` translation generators followed by the `d(d−1)/2` rotation generators `E_ab − E_ba`
    /// in ascending `(a,b)` order, each linearized about `q`.
    pub generators: Vec<Vec<Rat>>,
    /// Generators that are identically zero at this configuration.
    pub vanishing_generators: Vec<usize>,
    /// The exact rank of the generator span: the dimension of the trivial motion space.
    pub dimension_of_span: usize,
    /// An independent subfamily spanning it, by pivot order.
    pub basis: Vec<Vec<Rat>>,
    /// `d + d(d−1)/2 − (d−k)(d−k−1)/2`, computed from `k` alone and checked against
    /// `dimension_of_span`.
    pub closed_form: usize,
}

impl TrivialMotionReading {
    /// Measure the trivial space at a Jacobian's configuration **and prove it is in the kernel**.
    pub fn measure(jacobian: &RigidityJacobian) -> Result<Self, RigidityError> {
        jacobian.validated()?;
        let dimension = jacobian.dimension();
        let places = jacobian.configuration.ordered_places();
        let occurrences = places.len();
        let generators = trivial_generators(dimension, &places)?;

        for (ordinal, generator) in generators.iter().enumerate() {
            let image = jacobian.matrix.apply(generator)?;
            if let Some(constraint) = image.iter().position(|entry| !entry.is_zero()) {
                return Err(RigidityError::TrivialMotionOutsideKernel {
                    generator: ordinal,
                    constraint,
                });
            }
        }

        let vanishing_generators = generators
            .iter()
            .enumerate()
            .filter(|(_, generator)| generator.iter().all(Zero::is_zero))
            .map(|(ordinal, _)| ordinal)
            .collect();

        let width = dimension.saturating_mul(occurrences);
        let columns = column_matrix(width, &generators)?;
        let basis = columns.image_basis()?;
        let dimension_of_span = basis.len();

        let affine_span_dimension = affine_span_dimension(dimension, &places)?;
        let free = dimension - affine_span_dimension.min(dimension);
        let closed_form = dimension + dimension * dimension.saturating_sub(1) / 2
            - free * free.saturating_sub(1) / 2;
        if closed_form != dimension_of_span {
            return Err(RigidityError::TrivialDimensionDisagrees {
                measured: dimension_of_span,
                closed_form,
            });
        }

        let degeneracy = if affine_span_dimension == 0 {
            ConfigurationDegeneracy::Coincident
        } else if affine_span_dimension >= dimension {
            ConfigurationDegeneracy::Spanning
        } else if affine_span_dimension == 1 {
            ConfigurationDegeneracy::Collinear
        } else {
            ConfigurationDegeneracy::Deficient
        };

        Ok(Self {
            schema: TRIVIAL_MOTION_SCHEMA.to_owned(),
            dimension,
            occurrences,
            affine_span_dimension,
            degeneracy,
            generators,
            vanishing_generators,
            dimension_of_span,
            basis,
            closed_form,
        })
    }
}

/// The `d + d(d−1)/2` rigid generators of a point family, flattened into the `d·n` configuration
/// space in block order.
fn trivial_generators(
    dimension: usize,
    places: &[Vec<Rat>],
) -> Result<Vec<Vec<Rat>>, RigidityError> {
    let occurrences = places.len();
    let width = dimension
        .checked_mul(occurrences)
        .ok_or(ExactLinearError::ExtentOverflow)?;
    let mut generators = Vec::with_capacity(dimension + dimension * dimension.saturating_sub(1) / 2);
    for axis in 0..dimension {
        let mut generator = vec![Rat::zero(); width];
        for block in 0..occurrences {
            generator[block * dimension + axis] = Rat::one();
        }
        generators.push(generator);
    }
    for first in 0..dimension {
        for second in (first + 1)..dimension {
            // Ω = E_{first,second} − E_{second,first}: (Ω q)_first = q_second,
            // (Ω q)_second = −q_first, every other component zero.
            let mut generator = vec![Rat::zero(); width];
            for (block, place) in places.iter().enumerate() {
                generator[block * dimension + first] = place[second].clone();
                generator[block * dimension + second] = -place[first].clone();
            }
            generators.push(generator);
        }
    }
    Ok(generators)
}

/// `dim span{ q_i − q_0 }`, exact.
fn affine_span_dimension(
    dimension: usize,
    places: &[Vec<Rat>],
) -> Result<usize, RigidityError> {
    let Some((first, rest)) = places.split_first() else {
        return Ok(0);
    };
    let rows = rest
        .iter()
        .map(|place| {
            place
                .iter()
                .zip(first)
                .map(|(entry, origin)| entry - origin)
                .collect::<Vec<_>>()
        })
        .collect::<Vec<_>>();
    let differences = ExactRatMatrix::shaped(rows.len(), dimension, rows)?;
    Ok(differences.rank()?)
}

/// The vectors as **columns** of a `width × count` matrix, so `image_basis` returns an
/// independent subfamily of the vectors themselves.
fn column_matrix(width: usize, vectors: &[Vec<Rat>]) -> Result<ExactRatMatrix, RigidityError> {
    let rows = (0..width)
        .map(|row| {
            vectors
                .iter()
                .map(|vector| vector[row].clone())
                .collect::<Vec<_>>()
        })
        .collect::<Vec<_>>();
    Ok(ExactRatMatrix::shaped(width, vectors.len(), rows)?)
}

