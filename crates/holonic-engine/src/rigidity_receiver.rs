pub const RIGIDITY_JACOBIAN_SCHEMA: &str = "holonic-engine.rigidity-jacobian.v1";
pub const RIGIDITY_READING_SCHEMA: &str = "holonic-engine.rigidity-reading.v1";
pub const TRIVIAL_MOTION_SCHEMA: &str = "holonic-engine.rigidity-trivial-motions.v1";
