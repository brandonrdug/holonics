/// The Maxwell counting relation, and the exact identity behind it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct MaxwellCount {
    /// `d·n`.
    pub coordinate_freedoms: usize,
    /// `m`.
    pub constraints: usize,
    pub rank: usize,
    pub motion_dimension: usize,
    pub self_stress_dimension: usize,
    /// `d·n − m`. Equal to `dim ker J` exactly when there is no self-stress, and a strict lower
    /// bound otherwise.
    pub counted_freedom: i64,
    /// True when a self-stress exists, so the count alone under-reports the motion space and no
    /// rigidity verdict may be read from it.
    pub count_is_a_bound_only: bool,
}

/// **The complete rigidity reading of one constraint system at one configuration.**
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RigidityReading {
    pub schema: String,
    pub presentation_lineage: String,
    pub dimension: usize,
    pub occurrences: usize,
    pub constraint_count: usize,
    pub rank: usize,
    /// A basis of `ker J`: the infinitesimal motions, exhibited rather than counted.
    pub motions: Vec<Vec<Rat>>,
    pub motion_dimension: usize,
    /// A basis of `ker Jᵀ`: the self-stresses, equivalently the constraint reactions.
    pub self_stresses: Vec<Vec<Rat>>,
    pub self_stress_dimension: usize,
    pub trivial: TrivialMotionReading,
    /// `dim ker J − dim T(q)`: the motions that are not rigid motions of the whole configuration.
    pub internal_motion_dimension: usize,
    pub maxwell: MaxwellCount,
}

impl RigidityReading {
    /// **Infinitesimal** rigidity at this configuration: every infinitesimal motion is a rigid
    /// motion of the whole configuration.
    ///
    /// This is not generic rigidity — that is a statement about almost every configuration of a
    /// combinatorial structure — and it is not finite rigidity. A degenerate configuration can be
    /// infinitesimally flexible while its combinatorics are generically rigid, and the converse
    /// direction fails only through the degenerate locus.
    pub fn is_infinitesimally_rigid(&self) -> bool {
        self.internal_motion_dimension == 0
    }

    /// True when some constraint is dependent on the others.
    pub fn is_redundant(&self) -> bool {
        self.self_stress_dimension > 0
    }
}

/// The reading of one Jacobian: `rank J`, `ker J`, `ker Jᵀ`, the trivial space and the counts.
pub fn rigidity_reading(jacobian: &RigidityJacobian) -> Result<RigidityReading, RigidityError> {
    jacobian.validated()?;
    let dimension = jacobian.dimension();
    let occurrences = jacobian.occurrence_count();
    let constraint_count = jacobian.constraint_count();
    let coordinate_freedoms = jacobian.coordinate_freedoms();

    // One reading, not two: above the prime-image crossover `rank` and `kernel_basis` each decide
    // charts, lift and verify their own certificate over this same matrix.
    let (rank, motions) = jacobian.matrix.rank_and_kernel()?;
    let motion_dimension = motions.len();
    if rank + motion_dimension != coordinate_freedoms {
        return Err(RigidityError::RankNullityFails {
            rank,
            nullity: motion_dimension,
            coordinate_freedoms,
        });
    }
    let self_stresses = jacobian.matrix.cokernel_annihilator()?;
    let self_stress_dimension = self_stresses.len();
    if rank + self_stress_dimension != constraint_count {
        return Err(RigidityError::CokernelCountFails {
            rank,
            self_stress: self_stress_dimension,
            constraints: constraint_count,
        });
    }

    let trivial = TrivialMotionReading::measure(jacobian)?;
    if trivial.dimension_of_span > motion_dimension {
        return Err(RigidityError::TrivialExceedsKernel {
            trivial: trivial.dimension_of_span,
            kernel: motion_dimension,
        });
    }
    let internal_motion_dimension = motion_dimension - trivial.dimension_of_span;

    let counted_freedom = i64::try_from(coordinate_freedoms).unwrap_or(i64::MAX)
        - i64::try_from(constraint_count).unwrap_or(i64::MAX);
    let identity = i64::try_from(motion_dimension).unwrap_or(i64::MAX)
        - i64::try_from(self_stress_dimension).unwrap_or(i64::MAX);
    if identity != counted_freedom {
        return Err(RigidityError::MaxwellIdentityFails {
            motion: motion_dimension,
            self_stress: self_stress_dimension,
            counted: counted_freedom,
        });
    }

    Ok(RigidityReading {
        schema: RIGIDITY_READING_SCHEMA.to_owned(),
        presentation_lineage: jacobian.presentation_lineage.clone(),
        dimension,
        occurrences,
        constraint_count,
        rank,
        motions,
        motion_dimension,
        self_stresses,
        self_stress_dimension,
        trivial,
        internal_motion_dimension,
        maxwell: MaxwellCount {
            coordinate_freedoms,
            constraints: constraint_count,
            rank,
            motion_dimension,
            self_stress_dimension,
            counted_freedom,
            count_is_a_bound_only: self_stress_dimension > 0,
        },
    })
}

