//! | [`RigidityError::TrivialExceedsKernel`] cannot fire | `rigidMotionSpace`, `rigidMotionSpace_le_motions` |
//! | [`RigidityReading::is_infinitesimally_rigid`] | `InfinitesimallyRigid`, `infinitesimallyRigid_iff_eq` |
//! | [`ConfigurationDegeneracy::Coincident`] keeps the rotations but loses their independence | `rotation_is_a_translation_of_coincident` |
