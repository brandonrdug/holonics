/// **An exact rational configuration: one point per addressed occurrence.**
///
/// The fields are private because the invariant — every place carries exactly `dimension`
/// coordinates, and there is at least one occurrence — is not expressible in the wire format.
/// A remounted value is re-checked by [`Self::validated`], which every public consumer calls
/// before it reads anything.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExactConfiguration {
    dimension: usize,
    places: BTreeMap<ConstraintVertexId, Vec<Rat>>,
}

impl ExactConfiguration {
    /// A declared configuration. The block order of the Jacobian is the ascending address order
    /// of this map, so it is determined by the addresses and never by insertion order.
    pub fn declared(
        dimension: usize,
        places: impl IntoIterator<Item = (ConstraintVertexId, Vec<Rat>)>,
    ) -> Result<Self, RigidityError> {
        let configuration = Self {
            dimension,
            places: places.into_iter().collect(),
        };
        configuration.validated()?;
        Ok(configuration)
    }

    /// The configuration a presented complex already carries — **when it carries one.**
    ///
    /// A presented position is a [`crate::physical_constraint_complex::CoordinateBox3`], and a box
    /// with width is not a point. A Jacobian entry built from an interval would be an interval,
    /// and then no rank, kernel or cluster verdict below would be exact. So a box with width is
    /// refused by name with its occurrence and axis rather than collapsed to a midpoint, an
    /// endpoint or a float.
    pub fn from_presented(complex: &PhysicalConstraintComplex) -> Result<Self, RigidityError> {
        let mut places = BTreeMap::new();
        for (id, vertex) in &complex.vertices {
            let axes = [
                &vertex.position.x,
                &vertex.position.y,
                &vertex.position.z,
            ];
            let mut place = Vec::with_capacity(3);
            for (axis, interval) in axes.into_iter().enumerate() {
                if !interval.is_point() {
                    return Err(RigidityError::ConfigurationIsNotAPoint {
                        occurrence: *id,
                        axis,
                    });
                }
                place.push(interval.lower.clone());
            }
            places.insert(*id, place);
        }
        Self::declared(3, places)
    }

    pub fn validated(&self) -> Result<(), RigidityError> {
        if self.dimension == 0 {
            return Err(RigidityError::ZeroDimension);
        }
        if self.places.is_empty() {
            return Err(RigidityError::EmptyConfiguration);
        }
        for (id, place) in &self.places {
            if place.len() != self.dimension {
                return Err(RigidityError::RaggedConfiguration {
                    occurrence: *id,
                    declared: self.dimension,
                    supplied: place.len(),
                });
            }
        }
        Ok(())
    }

    /// Every presented occurrence carries a declared place, and that place lies inside the
    /// presented coordinate box.
    ///
    /// This is the only thing that ties a declared configuration to a presentation whose boxes
    /// have width. Without it a caller could read a rigidity family off a presentation while
    /// supplying coordinates from somewhere else entirely.
    pub fn within_presented(
        &self,
        complex: &PhysicalConstraintComplex,
    ) -> Result<(), RigidityError> {
        self.validated()?;
        if self.dimension != 3 {
            return Err(RigidityError::PresentationDimensionDisagrees {
                supplied: self.dimension,
            });
        }
        for (id, vertex) in &complex.vertices {
            let place = self
                .places
                .get(id)
                .ok_or(RigidityError::OccurrenceAbsent(*id))?;
            let axes = [
                &vertex.position.x,
                &vertex.position.y,
                &vertex.position.z,
            ];
            for (axis, interval) in axes.into_iter().enumerate() {
                if place[axis] < interval.lower || place[axis] > interval.upper {
                    return Err(RigidityError::ConfigurationOutsideBox {
                        occurrence: *id,
                        axis,
                    });
                }
            }
        }
        Ok(())
    }

    pub fn dimension(&self) -> usize {
        self.dimension
    }

    pub fn occurrence_count(&self) -> usize {
        self.places.len()
    }

    /// The block order: ascending addresses.
    pub fn addresses(&self) -> Vec<ConstraintVertexId> {
        self.places.keys().copied().collect()
    }

    pub fn place(&self, occurrence: ConstraintVertexId) -> Result<&[Rat], RigidityError> {
        self.places
            .get(&occurrence)
            .map(Vec::as_slice)
            .ok_or(RigidityError::OccurrenceAbsent(occurrence))
    }

    /// The places in block order.
    pub fn ordered_places(&self) -> Vec<Vec<Rat>> {
        self.places.values().cloned().collect()
    }

    fn blocks(&self) -> BTreeMap<ConstraintVertexId, usize> {
        self.places
            .keys()
            .enumerate()
            .map(|(at, id)| (*id, at))
            .collect()
    }
}

