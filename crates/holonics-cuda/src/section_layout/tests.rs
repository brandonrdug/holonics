/// A coefficient table lawful in its width and everywhere canonical **except one named index**.
/// Built through the generic [`LocalOperator::dense`], which carries no representation clause — that
/// is the point: the representation clause lives at the device boundary, and this fixture is what
/// the boundary is held against.
fn operator_with_one_non_canonical_entry(width: usize, at: usize, word: u64) -> LocalOperator<u64> {
    let mut entries = symmetric_operator(width).entries().to_vec();
    entries[at] = word;
    LocalOperator::dense(width, entries).expect("the width clause is untouched")
}

/// An **independent** exact reference for `Z/(2^61 - 1)`: a plain 128-bit remainder sharing no code
/// with `soma_abi::section_layout_cuda`.
///
/// `ModularWords::DEVICE` dispatches *into* the very code the card runs, which is exactly what makes
/// it the right reference for a transcription question and the wrong one for an arithmetic
/// question: a fold that is wrong on both sides agrees with itself. This ring is the second
/// witness, and the device assertions below compare against it.
#[derive(Debug, Clone, Copy)]
struct IndependentModulus;

impl ExactRing for IndependentModulus {
    type Value = u64;

    fn zero(&self) -> u64 {
        0
    }

    fn add(&self, left: u64, right: u64) -> Option<u64> {
        Some((((left as u128) + (right as u128)) % (section_cuda::MODULUS as u128)) as u64)
    }

    fn mul(&self, left: u64, right: u64) -> Option<u64> {
        Some((((left as u128) * (right as u128)) % (section_cuda::MODULUS as u128)) as u64)
    }

    fn law(&self) -> AccumulationLaw {
        AccumulationLaw::ModularAdd {
            modulus: section_cuda::MODULUS,
        }
    }
}

#[test]
fn a_non_canonical_coefficient_is_refused_at_the_staging_boundary_naming_its_first_index() {
    let layout = SectionLayout::generate(chain_1d(6, 4, 2), accumulated()).expect("generated");
    let width = layout.tile().max_width();
    let ring = ModularWords::DEVICE;

    // A lawful declaration passes every mouth of the boundary.
    let lawful = symmetric_operator(width);
    lawful.verify_canonical(&ring).expect("a canonical operator is admitted");
    LocalOperator::dense_canonical(width, lawful.entries().to_vec(), &ring)
        .expect("a canonical operator is admitted at construction");
    ring.verify_canonical(&field(layout.global_extent()), "global field")
        .expect("a canonical field is admitted");

    // `p` itself is the first non-canonical word and `u64::MAX` the widest; the refusal names the
    // offending index and the offending word, and it is raised through all three mouths.
    for (at, word) in [
        (0usize, section_cuda::MODULUS),
        (9, section_cuda::MODULUS + 1),
        (width * width - 1, u64::MAX),
    ] {
        let operator = operator_with_one_non_canonical_entry(width, at, word);
        let refusal = operator.verify_canonical(&ring).expect_err("refused");
        assert_eq!(refusal.clause, SectionClause::CanonicalWord);
        assert!(
            refusal.detail.contains(&format!("entry {at} is {word}")),
            "{}",
            refusal.detail
        );

        let constructed = LocalOperator::dense_canonical(width, operator.entries().to_vec(), &ring)
            .expect_err("refused at construction");
        assert_eq!(constructed.clause, SectionClause::CanonicalWord);

        // And through `stage`, which raises it **before any driver call**: this assertion runs on a
        // host with no CUDA context created and no device touched.
        let error = match SectionDeviceTables::stage(&layout, &operator, None) {
            Ok(_) => panic!("the staging boundary admitted a non-canonical coefficient"),
            Err(error) => error,
        };
        assert_eq!(error.context, SectionClause::CanonicalWord.name());
        assert!(
            error.message.contains(&format!("entry {at} is {word}")),
            "{}",
            error.message
        );
    }

    // Two offending entries: the refusal names the **first**, so the caller is pointed at a place
    // rather than told that a place exists.
    let mut entries = symmetric_operator(width).entries().to_vec();
    entries[3] = section_cuda::MODULUS + 17;
    entries[11] = u64::MAX;
    let operator = LocalOperator::dense(width, entries).expect("the width clause is untouched");
    let refusal = operator.verify_canonical(&ring).expect_err("refused");
    assert!(
        refusal.detail.contains("entry 3 is 2305843009213693968"),
        "{}",
        refusal.detail
    );

    // The same clause holds the global-field mouth, which is the other host table that crosses.
    let mut x = field(layout.global_extent());
    x[2] = section_cuda::MODULUS;
    let refusal = ring.verify_canonical(&x, "global field").expect_err("refused");
    assert_eq!(refusal.clause, SectionClause::CanonicalWord);
    assert!(
        refusal.detail.contains("global field entry 2 is"),
        "{}",
        refusal.detail
    );

    // The clause is the declaration's, not the arithmetic's: the arithmetic is total regardless,
    // and this is the assertion that says so on the host path the card shares.
    assert_eq!(
        ring.mul(17_678_129_737_304_986_966, 2_305_843_009_213_693_949),
        Some(1_537_228_672_809_129_284)
    );
    assert_eq!(ring.add(u64::MAX, u64::MAX), IndependentModulus.add(u64::MAX, u64::MAX));
}

#[test]
fn the_device_ring_agrees_with_an_independent_reference_over_non_canonical_words() {
    // `the_device_ring_agrees_with_the_general_modular_path_over_the_same_modulus` reduces every
    // probe first, so it can say nothing about a word outside `[0, p)`. This one does not reduce.
    let device = ModularWords::DEVICE;
    let probes: [u64; 12] = [
        0,
        1,
        section_cuda::MODULUS - 1,
        section_cuda::MODULUS,
        section_cuda::MODULUS + 1,
        1 << 61,
        (1 << 61) + 1,
        1 << 62,
        1 << 63,
        u64::MAX,
        17_678_129_737_304_986_966,
        2_305_843_009_213_693_949,
    ];
    for left in probes {
        assert_eq!(
            device.canonical(left),
            ((left as u128) % (section_cuda::MODULUS as u128)) as u64,
            "canonical({left})"
        );
        for right in probes {
            assert_eq!(
                device.add(left, right),
                IndependentModulus.add(left, right),
                "{left} + {right}"
            );
            assert_eq!(
                device.mul(left, right),
                IndependentModulus.mul(left, right),
                "{left} * {right}"
            );
        }
    }
}

/// Stage the device tables **around** the canonicality clause, so the four entries can be driven
/// with coefficients no public mouth would let through. Reachable only from this test module —
/// `SectionDeviceTables`' fields are private, and `stage` stays the only public way to fill them.
fn stage_around_the_canonicality_clause<'a>(
    layout: &'a SectionLayout,
    operator: &'a LocalOperator<u64>,
    colouring: Option<&'a RegionColouring>,
) -> crate::Result<SectionDeviceTables<'a>> {
    let index = crate::DeviceBuffer::<u32>::alloc(layout.slots())?;
    index.copy_from_slice(layout.gather_index())?;
    let offsets = crate::DeviceBuffer::<u32>::alloc(layout.regions() + 1)?;
    offsets.copy_from_slice(layout.device_offsets())?;
    let coefficients = crate::DeviceBuffer::<u64>::alloc(operator.entries().len())?;
    coefficients.copy_from_slice(operator.entries())?;
    let mut colour_regions = Vec::new();
    if let Some(colouring) = colouring {
        for colour in 0..colouring.colour_count() {
            let class = colouring.class(colour).expect("colour below the count");
            let buffer = crate::DeviceBuffer::<u32>::alloc(class.len())?;
            buffer.copy_from_slice(class)?;
            colour_regions.push(buffer);
        }
    }
    Ok(SectionDeviceTables {
        index,
        offsets,
        coefficients,
        colour_regions,
        provenance: SectionTableProvenance {
            layout,
            _operator: operator,
            colouring,
        },
    })
}

/// **The canonicality boundary and the total arithmetic, on the card.**
///
/// Three things are asserted, in the order the law holds them:
///
/// 1. a non-canonical coefficient and a non-canonical global field are refused at the host mouths,
///    naming the first offending index, with the card present and nothing staged;
/// 2. what those mouths admit is exact against the **independent** 128-bit reference, not merely
///    against `ModularWords::DEVICE`, which is the same code the card runs;
/// 3. driven *around* the refusal — the only way to reach it — the four entries run `mul` and `add`
///    on words outside `[0, p)`, including an accumulation target seeded non-canonical, and still
///    produce the exact residue. That is the arithmetic being total rather than guarded, and it is
///    the assertion the narrowing fold fails.
#[test]
#[ignore = "requires a CUDA device visible to the test process"]
fn the_device_boundary_refuses_non_canonical_declarations_and_its_arithmetic_is_total() -> crate::Result<()> {
    crate::cuda::init()?;
    let device = crate::Device::get(0)?;
    let context = crate::Context::create(&device)?;
    let module = crate::cuda::Module::load_ptx(crate::SOMA_PTX)?;
    let apparatus = SectionApparatus::resolve(&module)?;
    let stream = crate::Stream::create()?;

    let layout = SectionLayout::generate(chain_1d(48, 6, 2), accumulated())?;
    let width = layout.tile().max_width();
    let colouring = layout.colouring(1 << 20)?;
    colouring.verify_proper(&layout)?;
    let ring = ModularWords::DEVICE;
    let x = field(layout.global_extent());

    // --- (1) the two host mouths refuse -----------------------------------------------------
    let hostile = operator_with_one_non_canonical_entry(width, 7, section_cuda::MODULUS + 3);
    let error = match SectionDeviceTables::stage(&layout, &hostile, Some(&colouring)) {
        Ok(_) => panic!("a non-canonical coefficient reached the card"),
        Err(error) => error,
    };
    assert_eq!(error.context, SectionClause::CanonicalWord.name());
    assert!(error.message.contains("entry 7 is"), "{}", error.message);

    let lawful = LocalOperator::dense_canonical(
        width,
        symmetric_operator(width).entries().to_vec(),
        &ring,
    )?;
    let tables = SectionDeviceTables::stage(&layout, &lawful, Some(&colouring))?;

    let mut hostile_field = x.clone();
    hostile_field[5] = u64::MAX;
    let error = apparatus
        .apply_once(
            &device,
            &context,
            &stream,
            &layout,
            &tables,
            Some(&colouring),
            &hostile_field,
        )
        .expect_err("a non-canonical global field does not reach the card");
    assert_eq!(error.context, SectionClause::CanonicalWord.name());
    assert!(
        error.message.contains("global field entry 5 is"),
        "{}",
        error.message
    );

    // --- (2) what is admitted is exact against the independent reference ---------------------
    let (produced, receipts) = apparatus.apply_once(
        &device,
        &context,
        &stream,
        &layout,
        &tables,
        Some(&colouring),
        &x,
    )?;
    assert_eq!(
        produced,
        layout.apply_reference(&IndependentModulus, &lawful, &x)?,
        "the admitted declaration disagrees with the independent 128-bit reference"
    );
    assert_eq!(produced, layout.apply_reference(&ring, &lawful, &x)?);
    assert!(receipts.gather.receipt().is_fully_proved());

    // --- (3) the arithmetic itself is total --------------------------------------------------
    let mut entries = lawful.entries().to_vec();
    entries[0] = u64::MAX;
    entries[width + 1] = section_cuda::MODULUS + 11;
    entries[width * width - 1] = 17_678_129_737_304_986_966;
    let non_canonical = LocalOperator::dense(width, entries)?;
    non_canonical
        .verify_canonical(&ring)
        .expect_err("the fixture is genuinely non-canonical");
    let hostile_tables =
        stage_around_the_canonicality_clause(&layout, &non_canonical, Some(&colouring))?;

    // The accumulating target starts non-canonical too: `section_scatter_add` folds whatever the
    // global field already holds, which is the second place `add` met a word it was not promised.
    let seed: Vec<u64> = (0..layout.global_extent())
        .map(|at| {
            if at % 3 == 0 {
                u64::MAX - at as u64
            } else {
                section_cuda::MODULUS + at as u64
            }
        })
        .collect();
    let source = crate::DeviceBuffer::<u64>::alloc(x.len())?;
    source.copy_from_slice(&x)?;
    let mut local = crate::DeviceBuffer::<u64>::alloc_zeroed(layout.slots())?;
    let mut target = crate::DeviceBuffer::<u64>::alloc(layout.global_extent())?;
    target.copy_from_slice(&seed)?;
    apparatus.kernels().enact(
        &device,
        &stream,
        &layout,
        &hostile_tables,
        Some(&colouring),
        &source,
        &mut local,
        &mut target,
    )?;
    context.synchronize()?;
    let mut produced = vec![0u64; layout.global_extent()];
    target.copy_to_slice(&mut produced)?;

    let mut touched = vec![false; layout.global_extent()];
    for address in layout.incidence().addresses() {
        touched[*address as usize] = true;
    }
    let mut expected = layout.apply_reference(&IndependentModulus, &non_canonical, &x)?;
    for (at, word) in expected.iter_mut().enumerate() {
        *word = if touched[at] {
            IndependentModulus.add(*word, seed[at]).expect("total")
        } else {
            // An address no region names keeps exactly what the caller seeded, verbatim.
            seed[at]
        };
    }
    assert_eq!(
        produced, expected,
        "the device arithmetic is not total over words outside [0, p)"
    );
    // And the one-mouth property survives it: the host reference that *is* the device's own code
    // lands on the same field.
    let mut host = layout.apply_reference(&ring, &non_canonical, &x)?;
    for (at, word) in host.iter_mut().enumerate() {
        *word = if touched[at] {
            ring.add(*word, seed[at]).expect("total")
        } else {
            seed[at]
        };
    }
    assert_eq!(produced, host);

    eprintln!(
        "canonicality boundary: regions={} slots={} extent={} tile={} colours={} \
         · staging refusal EXACT · field refusal EXACT · total arithmetic EXACT",
        layout.regions(),
        layout.slots(),
        layout.global_extent(),
        width,
        colouring.colour_count(),
    );

    drop(tables);
    drop(hostile_tables);
    drop(source);
    context.destroy()?;
    Ok(())
}
