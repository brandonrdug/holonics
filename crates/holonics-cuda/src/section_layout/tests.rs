/// Synthetic device limits, `cfg(test)` only, so no production path can author a device bound.
fn synthetic_limits(warp: u32, block_cap: u32, shared: u32) -> LaunchLimits {
    LaunchLimits::synthetic(
        block_cap,
        Some(block_cap),
        Some(Dim3 {
            x: 2_147_483_647,
            y: 65_535,
            z: 65_535,
        }),
        Some(Dim3 {
            x: block_cap,
            y: block_cap,
            z: 64,
        }),
        Some(shared),
        Some(warp),
    )
}

#[test]
fn the_apply_requirement_generates_its_block_and_shared_extent_from_the_tile_and_the_card() {
    let layout = SectionLayout::generate(grid_2d(6, 5), accumulated()).expect("generated");
    let limits = synthetic_limits(32, 1024, 49_152);
    let requirement = layout
        .apply_requirement(&limits, layout.tile().max_width())
        .expect("a generated requirement");
    // Tile width 5, rounded up to one 32-lane warp; shared is five exact words.
    assert_eq!(requirement.block.exact, Some(Dim3::x(32)));
    assert!(requirement.block.warp_multiple);
    assert_eq!(requirement.shared.per_block_bytes, 40);
    assert_eq!(requirement.shared.per_thread_bytes, 0);
    assert_eq!(requirement.extent, layout.regions() as u64 * 32);
    assert!(matches!(requirement.coverage, Coverage::Exact));

    // The derived shape is submitted to the same proof any caller-authored shape faces.
    let shape = requirement.cover_with(&limits).expect("a derived shape");
    assert_eq!(shape.grid, Dim3::x(layout.regions() as u32));
    assert_eq!(shape.block, Dim3::x(32));
    assert_eq!(shape.shared_bytes, 40);
}

