/// **Case (a): a 1D chain of overlapping tiles.**  Region `r` covers `width` consecutive addresses
/// beginning at `r * (width - overlap)`, so consecutive regions share `overlap` addresses.
fn chain_1d(regions: usize, width: usize, overlap: usize) -> IncidenceDeclaration {
    assert!(regions > 0 && width > overlap, "a chain overlaps by less than its width");
    let stride = width - overlap;
    let global_extent = (regions - 1) * stride + width;
    let mut addresses = Vec::with_capacity(regions * width);
    for region in 0..regions {
        for slot in 0..width {
            addresses.push((region * stride + slot) as u32);
        }
    }
    IncidenceDeclaration::uniform(global_extent, width, addresses).expect("a lawful chain")
}

/// **Case (b): a 2D grid with 4-neighbour overlap.**  One region per interior cell, incident to the
/// cell and its four neighbours; adjacent regions therefore share addresses.
fn grid_2d(rows: usize, columns: usize) -> IncidenceDeclaration {
    assert!(rows > 2 && columns > 2, "a 4-neighbour stencil needs an interior");
    let global_extent = rows * columns;
    let mut addresses = Vec::new();
    for row in 1..(rows - 1) {
        for column in 1..(columns - 1) {
            let at = row * columns + column;
            addresses.push(at as u32);
            addresses.push((at - columns) as u32);
            addresses.push((at + columns) as u32);
            addresses.push((at - 1) as u32);
            addresses.push((at + 1) as u32);
        }
    }
    IncidenceDeclaration::uniform(global_extent, 5, addresses).expect("a lawful grid")
}

/// **Case (c): an irregular contact incidence**, structurally equivalent to a contact complex's
/// cell-to-vertex incidence: ragged widths between 2 and 6, addresses not in ascending order inside
/// a region, and an uneven address multiplicity so that some addresses are reached by one region
/// and others by five.  Generated by an exact integer recurrence, so it is reproducible and carries
/// no float.
fn irregular_contact(regions: usize, global_extent: usize) -> IncidenceDeclaration {
    assert!(regions > 0 && global_extent >= 8);
    let mut offsets = Vec::with_capacity(regions + 1);
    let mut addresses: Vec<u32> = Vec::new();
    // An exact linear congruential walk over the address space: deterministic, integral, and with
    // no arithmetic that could leave its wire (every operand is below 2^32 and the modulus is
    // applied before the next step).
    let mut state: u64 = 0x9E37_79B9;
    offsets.push(0usize);
    for region in 0..regions {
        let width = 2 + (region % 5);
        for _ in 0..width {
            state = (state.wrapping_mul(6_364_136_223_846_793_005).wrapping_add(1_442_695_040_888_963_407))
                >> 1;
            addresses.push((state % global_extent as u64) as u32);
        }
        offsets.push(addresses.len());
    }
    IncidenceDeclaration::new(global_extent, offsets, addresses).expect("a lawful irregular table")
}

/// A symmetric dense local operator over the device's own ring: `L[j][k] = 1 + j + k + j·k`,
/// canonical in `Z/(2^61 - 1)`.  Symmetric by construction, so
/// `SectionLayout.Incidence.assembled_symm` applies.
fn symmetric_operator(width: usize) -> LocalOperator<u64> {
    let ring = ModularWords::DEVICE;
    let mut entries = Vec::with_capacity(width * width);
    for row in 0..width {
        for column in 0..width {
            let value = 1 + row as u64 + column as u64 + (row as u64) * (column as u64);
            entries.push(ring.canonical(value));
        }
    }
    LocalOperator::dense(width, entries).expect("a lawful dense operator")
}

/// A deterministic exact global field.
fn field(extent: usize) -> Vec<u64> {
    let ring = ModularWords::DEVICE;
    (0..extent)
        .map(|at| ring.canonical(3 + 7 * at as u64 + (at as u64) * (at as u64)))
        .collect()
}

fn accumulated() -> ScatterRequest {
    ScatterRequest::Accumulated(AccumulationLaw::ModularAdd {
        modulus: section_cuda::MODULUS,
    })
}

