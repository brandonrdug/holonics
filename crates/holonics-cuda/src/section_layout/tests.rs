#[test]
fn a_uniform_declaration_generates_its_tile_extents_and_a_uniform_gather_partition() {
    let layout = SectionLayout::generate(chain_1d(6, 4, 2), accumulated()).expect("generated");
    let tile = layout.tile();
    assert_eq!(tile.regions(), 6);
    assert_eq!(tile.slots(), 24);
    assert_eq!(tile.max_width(), 4);
    assert_eq!(tile.uniform_width(), Some(4));
    // Generated, not authored: four exact 64-bit words.
    assert_eq!(tile.tile_bytes(), 32);

    let partition = layout.gather_partition().expect("a generated partition");
    assert_eq!(partition.regions(), 6);
    assert_eq!(partition.elements(), 24);
    assert_eq!(partition.region(0), Some(0..4));
    assert_eq!(partition.region(5), Some(20..24));
    partition
        .verify_pairwise_disjoint()
        .expect("the generated gather partition is disjoint");
}

#[test]
fn a_ragged_declaration_generates_an_offsets_gather_partition() {
    let layout = SectionLayout::generate(irregular_contact(9, 32), accumulated()).expect("generated");
    assert_eq!(layout.tile().uniform_width(), None);
    let partition = layout.gather_partition().expect("a generated partition");
    assert_eq!(partition.regions(), layout.regions());
    assert_eq!(partition.elements(), layout.slots());
    partition
        .verify_pairwise_disjoint()
        .expect("the generated gather partition is disjoint");
    // Every region's partition region is exactly its declared slot span.
    for region in 0..layout.regions() {
        let span = partition.region(region).expect("a region");
        assert_eq!(span.start, layout.incidence().offsets()[region]);
        assert_eq!(span.end, layout.incidence().offsets()[region + 1]);
    }
}

#[test]
fn the_generated_transpose_is_the_transpose_of_the_generated_gather() {
    let layout = SectionLayout::generate(grid_2d(5, 5), accumulated()).expect("generated");
    let transpose = layout.transpose();
    // Every (address, slot) of the gather table appears exactly once in the transpose.
    let mut seen = 0usize;
    for at in 0..transpose.touched().len() {
        let address = transpose.touched()[at];
        for slot in transpose.fibre(at).expect("a fibre") {
            assert_eq!(layout.gather_index()[*slot as usize], address);
            seen += 1;
        }
    }
    assert_eq!(seen, layout.slots());
    assert!(transpose.max_multiplicity() > 1, "the grid overlaps");
}

