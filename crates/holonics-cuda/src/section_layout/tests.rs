#[test]
fn colouring_refuses_an_incidence_past_the_declared_work_ceiling_before_it_colours() {
    // Every slot on one address: the conflict work is quadratic in the slot population, and the
    // ceiling refuses it *before* the colouring loop runs.
    let slots = 64usize;
    let incidence =
        IncidenceDeclaration::uniform(4, 1, vec![0u32; slots]).expect("a lawful hostile table");
    let layout = SectionLayout::generate(incidence, accumulated()).expect("generated");
    let refusal = layout.colouring(16).expect_err("the ceiling refuses it");
    assert_eq!(refusal.clause, SectionClause::WorkCeiling);
    // With a ceiling that admits the work, the same declaration colours and is proper.
    let colouring = layout.colouring(slots * slots).expect("a colouring");
    colouring.verify_proper(&layout).expect("proper");
    assert_eq!(colouring.colour_count(), slots, "every region conflicts with every other");
    assert_eq!(colouring.conflict_work(), slots * slots);
}

