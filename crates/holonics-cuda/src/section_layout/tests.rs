#[test]
fn the_generated_colouring_is_proper_on_every_declared_case() {
    for layout in [
        SectionLayout::generate(chain_1d(9, 4, 2), accumulated()).expect("generated"),
        SectionLayout::generate(grid_2d(7, 6), accumulated()).expect("generated"),
        SectionLayout::generate(irregular_contact(17, 24), accumulated()).expect("generated"),
    ] {
        let colouring = layout.colouring(1 << 20).expect("a colouring");
        colouring
            .verify_proper(&layout)
            .expect("the greedy colouring is proper");
        assert!(colouring.colour_count() >= 1);
        // Every region carries exactly one colour and every colour class is non-empty.
        let mut counted = 0usize;
        for colour in 0..colouring.colour_count() {
            let class = colouring.class(colour).expect("a class");
            assert!(!class.is_empty());
            counted += class.len();
            for region in class {
                assert_eq!(colouring.colour_of(*region as usize), Some(colour as u32));
            }
        }
        assert_eq!(counted, layout.regions());
    }
}

