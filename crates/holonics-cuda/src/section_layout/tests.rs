/// The three declared cases plus an injective control, each enacted on the card and compared
/// **bit for bit** against the exact cpu reference, with the four clocks reported separately.
///
/// Named clocks, all host `Instant` wall time:
///
/// * **setup** — context, module load, entry resolution, colouring, table staging and the source
///   upload: everything before the first section launch.
/// * **resident execution** — `SectionKernels::enact`, which is the three arms and, for an
///   accumulating scatter, one scatter launch per colour class.  Each arm's
///   `PartitionedWrite::scope` synchronizes the stream before returning, so this clock includes the
///   device work and the per-arm synchronization, and excludes the readback.
/// * **readout** — the device-to-host copy of the global field.
/// * **end to end** — the whole of the above, one clock across all of it.
#[test]
#[ignore = "requires a CUDA device visible to the test process"]
fn the_generated_triple_matches_the_exact_reference_on_the_card() -> crate::Result<()> {
    use std::time::Instant;

    crate::cuda::init()?;
    let device = crate::Device::get(0)?;
    let context = crate::Context::create(&device)?;
    let ring = ModularWords::DEVICE;

    let cases: Vec<(&str, IncidenceDeclaration, ScatterRequest)> = vec![
        ("1d-chain-of-overlapping-tiles", chain_1d(512, 16, 6), accumulated()),
        ("2d-grid-4-neighbour-overlap", grid_2d(64, 64), accumulated()),
        ("irregular-contact-incidence", irregular_contact(1024, 4096), accumulated()),
        (
            "injective-control",
            IncidenceDeclaration::uniform(4096, 8, (0..4096u32).collect()).expect("lawful"),
            ScatterRequest::Injective,
        ),
    ];

    for (name, incidence, request) in cases {
        let whole = Instant::now();
        let setup = Instant::now();
        let module = crate::cuda::Module::load_ptx(crate::SOMA_PTX)?;
        let apparatus = SectionApparatus::resolve(&module)?;
        let stream = crate::Stream::create()?;

        let layout = SectionLayout::generate(incidence, request)?;
        let operator = symmetric_operator(layout.tile().max_width());
        let colouring = match layout.receipt() {
            ScatterReceipt::Accumulated(_) => {
                let colouring = layout.colouring(1 << 24)?;
                colouring.verify_proper(&layout)?;
                Some(colouring)
            }
            ScatterReceipt::Injective => None,
        };
        let tables = SectionDeviceTables::stage(&layout, &operator, colouring.as_ref())?;
        let x = field(layout.global_extent());
        let source = crate::DeviceBuffer::<u64>::alloc(x.len())?;
        source.copy_from_slice(&x)?;
        let mut local = crate::DeviceBuffer::<u64>::alloc_zeroed(layout.slots())?;
        let mut target = crate::DeviceBuffer::<u64>::alloc_zeroed(layout.global_extent())?;
        context.synchronize()?;
        let setup = setup.elapsed();

        let resident = Instant::now();
        let receipts = apparatus.kernels().enact(
            &device,
            &stream,
            &layout,
            &tables,
            colouring.as_ref(),
            &source,
            &mut local,
            &mut target,
        )?;
        let resident = resident.elapsed();

        let readout = Instant::now();
        let mut produced = vec![0u64; layout.global_extent()];
        target.copy_to_slice(&mut produced)?;
        let readout = readout.elapsed();
        let end_to_end = whole.elapsed();

        // Every receipt is completely proved: `LaunchEvidence::Device` defers nothing.
        assert!(receipts.gather.receipt().is_fully_proved());
        assert!(receipts.apply.receipt().is_fully_proved());
        assert!(receipts.apply.receipt().proves(LaunchClause::BlockWarpMultiple));
        assert!(receipts.apply.receipt().proves(LaunchClause::SharedWithinDevice));
        assert!(receipts.apply.receipt().proves(LaunchClause::BlockDimensionWithinDevice));
        for scatter in &receipts.scatter {
            assert!(scatter.receipt().is_fully_proved());
        }
        assert_eq!(
            receipts.scatter.len(),
            colouring.as_ref().map_or(1, RegionColouring::colour_count)
        );

        let expected = layout.apply_reference(&ring, &operator, &x)?;
        assert_eq!(
            produced, expected,
            "{name}: the device result and the exact cpu reference disagree"
        );
        // And the reference is itself held against the directly assembled matrix wherever the
        // dense assembly fits; the big cases are covered by the cpu test above.
        if layout.global_extent() <= 512 {
            let matrix = layout.assemble_dense(&ring, &operator, 1 << 20)?;
            assert_eq!(produced, layout.apply_assembled(&ring, &matrix, &x)?);
        }

        // The convenience mouth is exercised too, on one case, so no public entry point of this
        // owner goes untested: it stages nothing new, allocates its own source/local/target and
        // reads the field back, and must produce the same exact field.
        if name == "injective-control" {
            let (once, once_receipts) = apparatus.apply_once(
                &device,
                &context,
                &stream,
                &layout,
                &tables,
                colouring.as_ref(),
                &x,
            )?;
            assert_eq!(once, expected, "{name}: apply_once left a different field");
            assert!(once_receipts.gather.receipt().is_fully_proved());
        }

        eprintln!(
            "{name}: regions={} slots={} extent={} tile={} shared={}B colours={} \
             setup={:?} resident={:?} readout={:?} end-to-end={:?}",
            layout.regions(),
            layout.slots(),
            layout.global_extent(),
            layout.tile().max_width(),
            layout.tile().tile_bytes(),
            colouring.as_ref().map_or(0, RegionColouring::colour_count),
            setup,
            resident,
            readout,
            end_to_end,
        );
        eprintln!("  gather  {}", receipts.gather.receipt());
        eprintln!("  apply   {}", receipts.apply.receipt());
        eprintln!("  scatter {}", receipts.scatter[0].receipt());

        drop(tables);
        drop(source);
    }

    context.destroy()?;
    Ok(())
}

