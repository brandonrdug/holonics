#[test]
fn a_shared_extent_past_the_card_is_refused_by_the_launch_law_rather_than_clipped() {
    // A 8192-slot tile wants 65_536 shared octets; the card in this fixture has 49_152.
    let width = 8192usize;
    let incidence = IncidenceDeclaration::uniform(
        65_536,
        width,
        (0..(width as u32 * 2)).map(|at| at % 65_536).collect(),
    )
    .expect("lawful");
    let layout = SectionLayout::generate(incidence, accumulated()).expect("generated");
    let limits = synthetic_limits(32, 1024, 49_152);
    let requirement = layout.apply_requirement(&limits, width).expect("a requirement");
    assert_eq!(requirement.shared.per_block_bytes, 65_536);
    let shape = requirement.cover_with(&limits).expect("a derived shape");
    let refusal = crate::launch_law::LawfulLaunch::prove(&requirement, &limits, shape, &[])
        .expect_err("the shared extent exceeds the card");
    assert_eq!(refusal.clause, LaunchClause::SharedWithinDevice);
}

