#[test]
fn the_colour_by_colour_scatter_equals_the_sequential_scatter() {
    // The executable witness of `SectionLayout.Incidence.colour_schedule`: accumulating one colour
    // class at a time into a running field leaves exactly what the whole scatter leaves.
    let ring = ModularWords::DEVICE;
    for layout in [
        SectionLayout::generate(chain_1d(9, 4, 2), accumulated()).expect("generated"),
        SectionLayout::generate(grid_2d(7, 6), accumulated()).expect("generated"),
        SectionLayout::generate(irregular_contact(17, 24), accumulated()).expect("generated"),
    ] {
        let colouring = layout.colouring(1 << 20).expect("a colouring");
        let tile: Vec<u64> = (0..layout.slots())
            .map(|slot| ring.canonical(13 + 17 * slot as u64))
            .collect();
        let mut sequential = vec![0u64; layout.global_extent()];
        layout
            .scatter_reference(&ring, &tile, &mut sequential)
            .expect("the whole scatter");

        let mut running = vec![0u64; layout.global_extent()];
        for colour in 0..colouring.colour_count() {
            for region in colouring.class(colour).expect("a class") {
                let lo = layout.incidence().offsets()[*region as usize];
                let hi = layout.incidence().offsets()[*region as usize + 1];
                for (address, value) in layout.gather_index()[lo..hi].iter().zip(&tile[lo..hi]) {
                    let at = *address as usize;
                    running[at] = ring.add(running[at], *value).expect("exact");
                }
            }
        }
        assert_eq!(running, sequential);
    }
}

