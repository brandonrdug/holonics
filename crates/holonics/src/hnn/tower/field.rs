/// [definition; agent-inferred, November 1] **The field's declared law**: an alphabet of `A`
/// classes (the face's; the encoding carries one more row, the unresolved operand), a face width
/// `D`, `H` heads of `n` complex modes each, `f` pair contacts and `K` ticks of the one
/// constitution; `frames`, the founding's heads, whose ring sets every grown head copies (head `h`
/// is of set `h mod frames`), the first `still` of them still (every mode unframed, reading the
/// word) and the rest turned (every mode on the solenoid's rings, [`ring_periods`]); and `reach`,
/// the most sites a region may span (the terrain's extent, read from the passages the field will
/// meet), which the rings' coarsest closures cover.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FieldDeclaration {
    pub alphabet: usize,
    pub width: usize,
    pub heads: usize,
    pub modes: usize,
    pub still: usize,
    pub contacts: usize,
    pub ticks: usize,
    pub frames: usize,
    pub reach: usize,
    /// The ring sets that are clocks (§15.4): the last `clocks` of the turned sets, framed by each
    /// site's own sweep count instead of its place.
    pub clocks: usize,
}

impl FieldDeclaration {
    /// `M = H n`, the complex modes over every head.
    pub fn complex(&self) -> usize {
        self.heads * self.modes
    }

    /// `⌈log₂ reach⌉`, at least one bit.
    fn reach_bits(&self) -> usize {
        (usize::BITS - self.reach.saturating_sub(1).leading_zeros()).max(1) as usize
    }

    /// [definition; agent-inferred, November 1] **The contact's gain covers the falloff, a mode at a
    /// time** (the dispersing field's §2.5 and §15.2): each mode keeps its own row, scored by its lock
    /// ([`lock`]), whose value at an equal word is half the mode's power, `|ŵ_m|²/2`, which a head's word
    /// at unit power over its `2n` reals holds at `1` on the mean over its `n` modes; an equal word at the
    /// farthest reach pays `⌊log₂ reach⌋` bits of falloff and must still outweigh the rest of its support
    /// together, at most another `⌈log₂ reach⌉` bits. `β` is the largest shift, negative where it must
    /// amplify, with `2^(−β) ≥ 2⌈log₂ reach⌉`: `−5` at reading 8's reach of 2,221 (a mode of mean power
    /// locks its equal at 32 bits; the falloff at the reach is 11). What it bounds is the mean mode's
    /// peak: a louder mode is heard sharper, a silent one is near flat over its support. A turned mode
    /// carries the lock by its skin decay, so its far counterparts are heard more faintly by design
    /// (§12). Why the mode's own row (§15.2): the head's sum over its modes was one number a pair, so one
    /// mode's agreement could not be heard apart from the rest.
    pub fn score_shift(&self) -> i32 {
        let (reals, need) = (self.modes as u128, 2 * self.reach_bits() as u128);
        let mut beta = 0i32;
        if reals >= need {
            while (reals >> (beta + 1)) >= need {
                beta += 1;
            }
        } else {
            while (reals << -beta) < need {
                beta -= 1;
            }
        }
        beta
    }

    /// [definition; agent-inferred, November 1] **The resonance classes' shells** (the dispersing
    /// field's §12): each of a head's first `b` modes is a trit of its unframed word, the sky plate
    /// (`Re > |Im|`, the in-phase part dominates: the mode locks and boosts), the ground plate
    /// (`Re < −|Im|`) or the bridge (`|Re| ≤ |Im|`, the quadrature dominates: it turns), the mode's
    /// light cone `|Re| = |Im|` (the null set of its Lorentz form `Re(w²)`) on the bridge.
    /// `b = min(n, ⌈½ log₃ reach⌉)`, the least `k` with `9^k ≥ reach`, so about `√reach` classes of
    /// about `√reach` sites each at a region of the reach (4 trits, 81 classes, at reading 8's
    /// declaration).
    pub fn class_trits(&self) -> usize {
        let mut k = 0usize;
        while 9u128.pow(k as u32) < self.reach as u128 {
            k += 1;
        }
        self.modes.min(k)
    }

    /// [agent-inferred, November 1] **The contact's return carrier**: the word's return sums
    /// `δs D ŵ` over a support of at most the reach (`D ≤ 2^30`, `ŵ` on 32 bits), so a contact
    /// covector `|δs| < 2^(126 − 30 − 31 − ⌈log₂ reach⌉)` keeps every sum inside 128 bits; one past it
    /// is refused, on the host and the card alike.
    pub fn contact_return_bits(&self) -> u32 {
        (126 - MOVE_BITS - 31).saturating_sub(self.reach_bits() as u32)
    }

    /// [definition; agent-inferred, November 1] **A series row's bound**, read from the declaration's
    /// own bounds (§14.11, §15.2), never chosen: a mode's lock is at most `2^(−β)·n` above zero (half a
    /// head's whole power in one mode, `|ŵ|² ≤ 2n`) and at most `2^(−β)·3n` below it (`|a||b| + |b|²/2`),
    /// and the falloff at the reach below that, so a row's whole bits spread over `2^(−β)·4n +
    /// ⌊log₂ reach⌋ + 2`; a term's face is 62 bits and its multiplier 62 (a far source's weight,
    /// [`WEIGHT_BITS`]) and `⌈log₂ reach⌉` more for a crowd's count; a row holds at most the reach and two
    /// crowds an octave, `⌈log₂⌉` of that; a value is at most a 64-bit carrier summed over the reach. A
    /// realization's carrier is as wide as the exponents a row actually holds and never past this bound;
    /// a row past it is refused. Owed to #410 with the grouped row's equality.
    pub fn row_bits(&self) -> u32 {
        let reach_bits = self.reach_bits() as u32;
        let gain = if self.score_shift() >= 0 { (4 * self.modes as u32) >> self.score_shift() } else { (4 * self.modes as u32) << -self.score_shift() };
        let spread = gain + (usize::BITS - 1 - self.reach.leading_zeros()) + 2;
        let terms = (usize::BITS - (self.reach + 2 * reach_bits as usize).leading_zeros()) as u32;
        62 + WEIGHT_BITS + reach_bits + spread + terms + 64 + reach_bits + 1
    }

    /// The classes a head reads, `3^b`.
    pub fn classes(&self) -> usize {
        3usize.pow(self.class_trits() as u32)
    }

    /// [definition; agent-inferred, November 1] **Where the closure compares** (§19): a head of a
    /// still ring set (it reads words at any distance, so the site that holds a class is met
    /// wherever it stands) at every tick. See [`Field`]'s reverse.
    pub fn closes(&self, _tick: usize, head: usize) -> bool {
        head % self.frames < self.still
    }

    /// [definition; agent-inferred, November 1] **The heads of a ring set**, `H / frames`: the
    /// closure's code at a head is read over its set's heads, `copies` of them, so a set compares
    /// once however many heads growth has copied into it. Why: growth by copies keeps every face
    /// (each copy's contact is its source's), so without it a grown field's closure would count each
    /// set's code `factor` times while the faces' code stays one, and growth alone would move the
    /// comparison toward the closure (the sixth review, November 1).
    pub fn copies(&self) -> usize {
        self.heads / self.frames
    }

    /// The key draws the founding reads, four bytes a draw: the encoding and the strand contacts'
    /// rows of every class (their unresolved rows open at zero), the word chart, the value chart and
    /// both pair drives.
    pub fn founding_draws(&self) -> usize {
        let m2 = 2 * self.complex();
        3 * self.alphabet * self.width + 2 * m2 * self.width + 2 * self.contacts * self.width
    }

    /// The key draws a growth by `factor` reads ([`Field::growth_draws`]).
    pub fn growth_draws(&self, factor: usize) -> usize {
        factor * factor.saturating_sub(1) * self.width * (2 * 2 * self.complex() + 2 * self.contacts)
    }

    /// The declaration grown by `factor`: width, heads and contacts (a head's modes, its ring set,
    /// the ring sets and the reach are kept).
    pub fn grown(&self, factor: usize) -> Result<Self> {
        let grow = |v: usize| v.checked_mul(factor).ok_or(TowerError::Refused("a grown extent outgrew its carrier"));
        Ok(Self { width: grow(self.width)?, heads: grow(self.heads)?, contacts: grow(self.contacts)?, ..*self })
    }

    /// The turned slots: `(frames − still) · n`, slot `l · (frames − still) + (g − still)` the ring
    /// of local mode `l` in every head of turned ring set `g`.
    pub fn turned_slots(&self) -> usize {
        (self.frames - self.still) * self.modes
    }

    /// [definition; agent-inferred, November 1] **The modes that carry a moment** (§15.1): every mode of
    /// a turned ring set that is not a clock, `T = H (frames − still − clocks)/frames · n`, numbered by
    /// head then mode. A still mode has no skin to bound its sum and a clock's place is no strand.
    pub fn moment_modes(&self) -> usize {
        (0..self.heads).filter(|&h| self.carries_moment(h)).count() * self.modes
    }

    /// Whether head `h`'s modes carry a moment: a turned ring set that is not a clock.
    pub fn carries_moment(&self, h: usize) -> bool {
        h % self.frames >= self.still && !self.is_clock(h)
    }

    /// The moment index of head `h`'s first mode.
    pub fn moment_index(&self, h: usize) -> usize {
        (0..h).filter(|&k| self.carries_moment(k)).count() * self.modes
    }

    /// [definition; agent-inferred, November 1] **A clock ring set** (the dispersing field's §15.4): head
    /// `h` is of one where its set is among the last `clocks`. Its modes are turned by each site's own
    /// sweep count since the site was reached (the release's clock; in training §14.6's rung), not by
    /// its place, so sites reached or locked together share phase, their gaps are read as phase like
    /// place is, and the contact reads rhythm beside content. A clock carries no skin: the sweeps are
    /// not a medium a field crosses, and the place's falloff still charges the pair.
    pub fn is_clock(&self, h: usize) -> bool {
        h % self.frames >= self.frames - self.clocks
    }

    fn admit(&self) -> Result<()> {
        if self.clocks > self.frames - self.still.min(self.frames) {
            return refuse("a field's clocks are among its turned ring sets");
        }
        if self.alphabet < 2 || self.width == 0 || self.heads == 0 || self.modes == 0 || self.contacts == 0 || self.ticks == 0 {
            return refuse("a field needs two classes, a nonempty width, heads, modes, contacts and ticks");
        }
        if self.frames == 0 || self.heads % self.frames != 0 || self.still > self.frames || self.reach < 2 {
            return refuse("a field's ring sets divide its heads, no more of them are still than there are, and its reach spans two sites");
        }
        // The score is released `16 + β` bits from its products' grain, and a head's classes are
        // listed on the card in at most `2^12` buckets.
        if (FACE_BITS as i32) + self.score_shift() < 0 || self.class_trits() > MAX_CLASS_TRITS {
            return refuse("a field whose gain passes the face's grain or whose classes pass 3^7 a head");
        }
        Ok(())
    }

    fn to_text(self) -> String {
        format!("hnn-field-v5 {} {} {} {} {} {} {} {} {} {}", self.alphabet, self.width, self.heads, self.modes, self.still, self.contacts, self.ticks, self.frames, self.reach, self.clocks)
    }

    fn from_text(line: &str) -> Result<Self> {
        let words: Vec<&str> = line.split(' ').collect();
        if words.len() != 11 || words[0] != "hnn-field-v5" {
            return refuse("a field's head line that is not hnn-field-v5");
        }
        let n = |w: &str| w.parse::<usize>().map_err(|_| TowerError::Refused("a field's declaration that is not a count"));
        let d = Self { alphabet: n(words[1])?, width: n(words[2])?, heads: n(words[3])?, modes: n(words[4])?, still: n(words[5])?, contacts: n(words[6])?, ticks: n(words[7])?, frames: n(words[8])?, reach: n(words[9])?, clocks: n(words[10])? };
        d.admit()?;
        Ok(d)
    }
}

