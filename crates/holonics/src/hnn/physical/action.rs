/// The largest `k ≥ 0` with `fits(k)`, given that `fits` holds at `0` and then up to some `k` and
/// fails beyond it. Galloping then bisection: only comparisons are made.
fn farthest(fits: impl Fn(&BigInt) -> bool) -> BigInt {
    let one = BigInt::one();
    let mut good = BigInt::zero();
    let mut bad = one.clone();
    while fits(&bad) {
        good = bad.clone();
        bad = &bad + &bad;
    }
    while &bad - &good > one {
        let middle = (&good + &bad) >> 1usize;
        if fits(&middle) {
            good = middle;
        } else {
            bad = middle;
        }
    }
    good
}

/// The integers `z` with `(z − centre)² ≤ radius_sq`, as the inclusive interval `[low, high]`, or
/// `None` when no integer fits. The squares are compared exactly: no root, no float. The set is an
/// interval of consecutive integers, so it is found outward from the nearer integer of the centre.
fn lattice_interval(centre: &Rat, radius_sq: &Rat) -> Option<(BigInt, BigInt)> {
    let fits = |z: &BigInt| {
        let gap = Rat::from_integer(z.clone()) - centre;
        &gap * &gap <= *radius_sq
    };
    let below = centre.floor().to_integer();
    let above = centre.ceil().to_integer();
    let start = if fits(&below) {
        below
    } else if fits(&above) {
        above
    } else {
        return None;
    };
    let high = &start + farthest(|k| fits(&(&start + k)));
    let low = &start - farthest(|k| fits(&(&start - k)));
    Some((low, high))
}

/// [definition; agent-inferred, October 8] **The admitted source waves**: a declared FINITE lattice
/// by physical work, never samples of an infinite control fibre (module header). The controls
/// `u ∈ 2^(−j) ℤ^m` of the preparation whose model preparation work
/// `W(u) = P(m + B u) − P(m)` ([`ProspectiveFeature::preparation_work`], the owner's
/// `PowerForm::ring_power` at the opening's source wave `m`) does not exceed the declared supply
/// `E`, in lexicographic order. `B` must have full column rank: otherwise `W` is not coercive in the
/// controls and a kernel quotient would be needed, which is outside this declaration and refused.
///
/// `W(u) = c(|m + B u|² − |m|²)` with `c = P(e)` the owner's storage power of a unit wave (positive),
/// so with `G = BᵀB ≻ 0`, `b = Bᵀm`, `u* = −G⁻¹ b` and `ρ = E/c + bᵀG⁻¹b`
/// the admitted set is `{ u : (u − u*)ᵀ G (u − u*) ≤ ρ }`, whose coordinate `i` satisfies
/// `(u_i − u*_i)² ≤ ρ (G⁻¹)_ii`; in lattice units `(z_i − 2^j u*_i)² ≤ 4^j ρ (G⁻¹)_ii`, compared as
/// exact squares. The lattice points of the resulting bounding box are enumerated and kept exactly
/// when `W(u) ≤ E`. A set empty because `ρ < 0` (the supply is below the least work) or because no
/// lattice point meets a coordinate's bound is a valid empty declaration.
///
/// The `capacity` is the declared ceiling of the bounding box's lattice points, checked before any
/// point is enumerated: a refusal, never a truncation, and never raised by this owner (lesson 9).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AdmittedWaves {
    exponent: u32,
    supply: Rat,
    controls: Vec<Vec<Rat>>,
    enumerated: usize,
    declared_for: DeclaredFor,
}

/// The producing feature an admitted declaration was read from, by everything that decides the
/// admitted set and the probes it offers: the material commit, the opening tick and the compared
/// station; the preparation's ring and map `B`, the opening's source wave `m` and the work's
/// coefficient `c = P(e)` (so `P(m + Bu) − P(m)` is the same function of `u`); and the native
/// feature map itself, `x(u) = x₀ + J u`. The commit is a local counter, not an identity, so the
/// operands it would stand for are compared directly. A declaration admits only at an equal
/// feature (Epime's review, October 8: an admitted wave is a checked membership, never a caller's
/// precondition).
#[derive(Clone, Debug, PartialEq, Eq)]
struct DeclaredFor {
    producing_commit: u64,
    opened_at: usize,
    station: usize,
    ring: usize,
    map: ExactRatMatrix,
    source_wave: Vec<Rat>,
    unit_power: Rat,
    baseline_feature: Vec<Rat>,
    jacobian: ExactRatMatrix,
}

impl DeclaredFor {
    fn of(feature: &ProspectiveFeature) -> Self {
        let mut unit = vec![Rat::zero(); feature.source_wave().len()];
        if let Some(first) = unit.first_mut() {
            *first = Rat::one();
        }
        Self {
            producing_commit: feature.producing_commit(),
            opened_at: feature.opened_at(),
            station: feature.station(),
            ring: feature.preparation().ring(),
            map: feature.preparation().map().clone(),
            source_wave: feature.source_wave().to_vec(),
            unit_power: feature.storage_power(&unit),
            baseline_feature: feature.baseline_feature().to_vec(),
            jacobian: feature.jacobian().clone(),
        }
    }
}

impl AdmittedWaves {
    /// Declare the lattice `2^(−exponent) ℤ^m` of `feature`'s preparation at the work supply
    /// `supply`, enumerating at most `capacity` points of its bounding box.
    pub fn declare(
        feature: &ProspectiveFeature,
        exponent: u32,
        supply: Rat,
        capacity: usize,
    ) -> Result<Self, HnnError> {
        let declared_for = DeclaredFor::of(feature);
        let preparation = feature.preparation();
        let map = preparation.map();
        let controls = preparation.controls();
        if map.rank()? != controls {
            return Err(HnnError::Unadmitted {
                reason: "the admitted source waves require a full-column-rank preparation: a kernel quotient is outside this declaration",
            });
        }
        if controls == 0 {
            // The one point `u = ()` is still enumerated under the declared capacity.
            if capacity < 1 {
                return Err(HnnError::Unadmitted {
                    reason: "the declared finite lattice's bounding box exceeds its declared enumeration capacity",
                });
            }
            let admitted = feature.preparation_work(&[])? <= supply;
            return Ok(Self {
                exponent,
                declared_for: declared_for.clone(),
                supply,
                controls: if admitted { vec![Vec::new()] } else { Vec::new() },
                enumerated: 1,
            });
        }
        let source = feature.source_wave();
        // c = P(e): the owner's storage power of a unit wave.
        let mut unit = vec![Rat::zero(); source.len()];
        let Some(first) = unit.first_mut() else {
            return Err(HnnError::Unadmitted {
                reason: "a source ring carries a wave to prepare",
            });
        };
        *first = Rat::one();
        let unit_power = feature.storage_power(&unit);
        if !unit_power.is_positive() {
            return Err(HnnError::Unadmitted {
                reason: "the storage power of a unit wave is positive",
            });
        }
        let transpose = map.transpose()?;
        let inverse = transpose.multiply(map)?.inverse()?;
        let moment = transpose.apply(source)?;
        let response = inverse.apply(&moment)?;
        let curvature: Rat = moment.iter().zip(&response).map(|(a, b)| a * b).sum();
        let rho = &supply / &unit_power + curvature;
        if rho.is_negative() {
            return Ok(Self {
                exponent,
                declared_for: declared_for.clone(),
                supply,
                controls: Vec::new(),
                enumerated: 0,
            });
        }
        let scale = Rat::from_integer(BigInt::one() << exponent as usize);
        let mut lows = Vec::with_capacity(controls);
        let mut highs = Vec::with_capacity(controls);
        let mut points = BigInt::one();
        for i in 0..controls {
            let centre = -&response[i] * &scale;
            let radius_sq = &rho * inverse.get(i, i)? * &scale * &scale;
            let Some((low, high)) = lattice_interval(&centre, &radius_sq) else {
                return Ok(Self {
                    exponent,
                    declared_for: declared_for.clone(),
                    supply,
                    controls: Vec::new(),
                    enumerated: 0,
                });
            };
            points *= &high - &low + BigInt::one();
            lows.push(low);
            highs.push(high);
        }
        if points > BigInt::from(capacity) {
            return Err(HnnError::Unadmitted {
                reason: "the declared finite lattice's bounding box exceeds its declared enumeration capacity",
            });
        }
        let enumerated = points.to_usize().ok_or(HnnError::CountOverflow)?;
        let denominator = BigInt::one() << exponent as usize;
        let mut cursor = lows.clone();
        let mut admitted: Vec<Vec<Rat>> = Vec::new();
        'walk: loop {
            let control: Vec<Rat> = cursor
                .iter()
                .map(|z| Rat::new(z.clone(), denominator.clone()))
                .collect();
            if feature.preparation_work(&control)? <= supply {
                admitted.push(control);
            }
            let mut position = controls;
            loop {
                if position == 0 {
                    break 'walk;
                }
                position -= 1;
                if cursor[position] < highs[position] {
                    cursor[position] += BigInt::one();
                    break;
                }
                cursor[position] = lows[position].clone();
            }
        }
        admitted.sort();
        Ok(Self {
            exponent,
            declared_for: declared_for.clone(),
            supply,
            controls: admitted,
            enumerated,
        })
    }

    /// The admitted controls, in lexicographic order.
    pub fn controls(&self) -> &[Vec<Rat>] {
        &self.controls
    }
    /// `j` of the lattice `2^(−j) ℤ^m`.
    pub fn exponent(&self) -> u32 {
        self.exponent
    }
    /// The declared work supply `E`.
    pub fn supply(&self) -> &Rat {
        &self.supply
    }
    pub fn len(&self) -> usize {
        self.controls.len()
    }
    pub fn is_empty(&self) -> bool {
        self.controls.is_empty()
    }
    /// The lattice points of the bounding box that were tested against the supply.
    pub fn enumerated(&self) -> usize {
        self.enumerated
    }
    /// Whether `control` is admitted (exact membership in the declared set).
    pub fn contains(&self, control: &[Rat]) -> bool {
        self.controls
            .binary_search_by(|admitted| admitted.as_slice().cmp(control))
            .is_ok()
    }
    /// Whether this declaration was read from `feature`: the same material commit, opening,
    /// station, preparation and source wave ([`DeclaredFor`]).
    pub fn declared_for(&self, feature: &ProspectiveFeature) -> bool {
        self.declared_for == DeclaredFor::of(feature)
    }
}

/// The refusal of an admitted declaration read from another feature.
fn foreign_declaration() -> HnnError {
    HnnError::Unadmitted {
        reason: "an admitted wave declaration admits only at the feature it was declared from",
    }
}

/// Why a probe holds, as a typed reason beside the release law's `Hold`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ProbeHold {
    /// The receiving law carries no phase statistics (a law that is not a receiving map's).
    NoPhaseStatistics,
    /// The declared finite lattice of waves is empty.
    NoAdmittedWave,
    /// No admitted wave's image meets two outcome blocks: with the statistics' tolerance and the
    /// receiver's grain, the readout does not tell two members of the family apart.
    NoSeparatingWave,
}

/// A prediction of the NATIVE readout only: the feature `x(u) = x0 + J u` of an admitted wave, the
/// retained family's image at it and the outcome blocks that image meets, with two feasible witnesses
/// in distinct blocks when there are two. The actual World's reflected return is not modelled, so
/// the executed World face may fall outside every predicted block.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeReadoutPrediction {
    /// The compared station, an index into the receiving aperture.
    pub station: usize,
    /// The native feature `x(u)` at that station.
    pub feature: Vec<Rat>,
    /// The family's image at the feature: centre, class leverages and tolerance.
    pub image: PhaseImage,
    /// Every outcome block (per-class arc indices) the image meets, in ascending order.
    pub blocks: Vec<Vec<BigInt>>,
    /// Two feasible members' readings in the two least blocks, `None` below two blocks.
    pub witnesses: Option<[(Vec<BigInt>, Vec<Rat>); 2]>,
}

/// The probe's decision: the release law's return, the offered control, its native prediction, how
/// many admitted waves were candidates, and the typed reason when it holds.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ProbeDecision {
    pub release: ReleaseReturn,
    /// The offered control, exactly when `release` is an `Ask`.
    pub control: Option<Vec<Rat>>,
    pub prediction: Option<NativeReadoutPrediction>,
    /// The admitted waves whose image meets at least two outcome blocks.
    pub candidates: usize,
    pub held: Option<ProbeHold>,
}

/// The executed World face against the prediction made before the encounter. `predicted` is the
/// necessary condition: the observed lifted class phases fall in a block that the image meets. A
/// block miss falsifies the native prediction (the image does not contain the observed phases); a
/// hit is not asserted as containment, which `contained` states exactly (`Q(y) ≤ τ`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PhaseDiscrepancy {
    /// `j_c = ⌊L y_c⌋` of the observed lifted class phases `y_c = Im z_c / 2`.
    pub observed_block: Vec<BigInt>,
    /// The observed block is among the prediction's blocks.
    pub predicted: bool,
    /// The observed phases lie in the predicted image exactly.
    pub contained: bool,
}

impl PhaseDiscrepancy {
    /// The native prediction is falsified: the observed block is none the image meets.
    pub fn falsified(&self) -> bool {
        !self.predicted
    }
}

/// An executed probe: the actual communication (the same `ActionCommunication` a request's
/// encounter returns), the native prediction made before it, and the discrepancy of the observed
/// face against that prediction when both exist.
#[derive(Debug)]
pub struct ProbeReception {
    pub reception: ActionCommunication,
    pub prediction: Option<NativeReadoutPrediction>,
    pub discrepancy: Option<PhaseDiscrepancy>,
}

/// The best candidate so far: greatest total leverage, then the lexicographically least control.
struct Candidate {
    control: Vec<Rat>,
    feature: Vec<Rat>,
    image: PhaseImage,
    witnesses: [(Vec<BigInt>, Vec<Rat>); 2],
    leverage: Rat,
}

fn family_refusal() -> HnnError {
    HnnError::Unadmitted {
        reason: "the receiving law's phase family refuses its declared tolerance",
    }
}

fn image_refusal() -> HnnError {
    HnnError::Unadmitted {
        reason: "the receiving law's phase family refuses the native feature's image",
    }
}

fn blocks_refusal() -> HnnError {
    HnnError::Unadmitted {
        reason: "the receiving law's phase family refuses the image's outcome blocks at the receiver's grain",
    }
}

/// The receiving law's declared phase family at `τ = ε_bits · N`, or `None` when the law carries no
/// phase statistics. `ε_bits` is the receiver declaration's per-cell code tolerance as the phases
/// carry it, and `N` the statistics' cumulative compared cells: a declared convention, not a theorem.
/// With no reading yet (`N = 0`) the family is its prior alone, a single member.
fn declared_family(
    constitution: &Constitution,
    phases: &ReceivingPhases,
) -> Result<Option<PhaseFamily>, HnnError> {
    let law = constitution
        .receiving_law(phases.ring())
        .ok_or(HnnError::MissingReceivingMap {
            ring: phases.ring(),
        })?;
    let Some(statistics) = law.phase_statistics() else {
        return Ok(None);
    };
    let tolerance = phases.tolerance() * statistics.cells();
    statistics
        .family(law.prior_scale(), &tolerance)
        .map(Some)
        .map_err(|_| family_refusal())
}

/// The native prediction of one admitted wave at the present material, or `None` without a family.
fn predict_native(
    constitution: &Constitution,
    feature: &ProspectiveFeature,
    control: &[Rat],
) -> Result<Option<NativeReadoutPrediction>, HnnError> {
    let Some(family) = declared_family(constitution, feature.phases())? else {
        return Ok(None);
    };
    let x = feature.feature_at(control)?;
    let grain = feature.phases().grain();
    let image = family.image(&x).map_err(|_| image_refusal())?;
    let blocks = image.blocks(grain).map_err(|_| blocks_refusal())?;
    let witnesses = image.witnesses(grain).map_err(|_| blocks_refusal())?;
    Ok(Some(NativeReadoutPrediction {
        station: feature.station(),
        feature: x,
        image,
        blocks,
        witnesses,
    }))
}

/// **The one decision on the probe.** Its reading is, for a member `V` of the declared family,
/// the tuple of **outcome blocks** over the admitted controls,
/// `R(V) = (block_L(V x(u)/2))_(u ∈ AdmittedWaves)` (each block the tuple of lifted half-open phase
/// arcs at the receiver's grain), in the supremum over the control index of the **discrete metric
/// on blocks**: two distinct blocks are at distance one, whatever their phase separation, as the
/// station decision reads its classes (`hnn::prediction`). One member keeps its identity across the
/// controls, and outcomes of different controls are never pooled (two deterministic controls can
/// meet different blocks while each has zero width). The diameter is one exactly when some single
/// admitted control meets two feasible blocks, attained by that control's two witnesses (each the
/// reading of a family member, by the equality case of `hnn::phase_family`), and zero otherwise. It is not the phases' sup-norm width (Epime's review,
/// October 8: two blocks need not be a unit phase apart, and one block can hold a nonzero image).
/// The existing release law at tolerance zero `Hold`s inside the tolerance and `Ask`s beyond it,
/// only for the probe offered.
fn decide_probe(station: usize, offered: Option<ObservationProbe>) -> Result<ReleaseReturn, HnnError> {
    let (diameter, attaining, read) = if offered.is_some() {
        (Rat::one(), WidthWitness::Pair { left: 0, right: 1 }, 2)
    } else {
        (Rat::zero(), WidthWitness::Point, 1)
    };
    let width = ReceiverWidth::declared(
        format!("the native station {station}'s phase outcome block"),
        "the compared station's native phase readout over the declared family's image at the admitted source waves, read as its outcome block in the discrete metric on blocks (two distinct blocks at distance one)",
        DiameterNorm::Supremum,
        diameter,
        attaining,
        read,
    )?;
    let options = LawfulOptions::assemble(&width, Rat::zero(), offered, false)?;
    let rule = DecisionRule::new(
        "the phase family's probe at tolerance zero",
        WithinTolerance::Hold,
        BeyondTolerance::Ask,
    );
    Ok(release(&rule, &options)?)
}

/// The observed face against the prediction, from the actual encounter's observed slots. Only a
/// face actually received at the compared station is read; a missing slot or prediction reports
/// nothing.
fn discrepancy_of(
    reception: &ActionCommunication,
    station: usize,
    grain: u64,
    prediction: Option<&NativeReadoutPrediction>,
) -> Option<PhaseDiscrepancy> {
    let prediction = prediction?;
    let observed = match reception {
        ActionCommunication::Received(received) => received.encounter.observed(),
        ActionCommunication::Interrupted(interrupted) => interrupted.encounter.partial.observed(),
        ActionCommunication::Held { .. } => return None,
    };
    let face = observed.get(station)?.as_ref()?;
    let observed_block = PhaseImage::block_of(face.phases(), grain);
    let predicted = prediction.blocks.contains(&observed_block);
    let contained = prediction.image.contains(face.phases());
    Some(PhaseDiscrepancy {
        observed_block,
        predicted,
        contained,
    })
}

/// A bound, unrun probe: the native feature of one compared station and the receiver it will meet.
/// Borrowing the receiver bars interleaved material, current and World edits, so the family that
/// chooses a wave is the family the wave meets.
pub struct PreparedPhysicalProbe<'r, 'f> {
    owner: &'r mut PhysicalReceiver<'f>,
    word: Word<'f>,
    feature: ProspectiveFeature,
    section: DamagedSection,
    source_length: usize,
    receiver_index: usize,
    opening: SourceOpeningReceipt,
}

impl PreparedPhysicalProbe<'_, '_> {
    pub fn feature(&self) -> &ProspectiveFeature {
        &self.feature
    }
    pub fn source_chart(&self) -> &Encoded {
        self.section.chart()
    }
    pub fn producing_commit(&self) -> u64 {
        self.feature.producing_commit()
    }
    pub fn current(&self) -> &Current {
        self.feature.current()
    }
    pub fn opened_at(&self) -> usize {
        self.feature.opened_at()
    }
    pub fn receiving_phases(&self) -> &ReceivingPhases {
        self.feature.phases()
    }
    /// The material this probe meets (frozen while the probe is held).
    pub fn constitution(&self) -> &Constitution {
        self.owner.constitution()
    }

    /// The native prediction of one control at the present material: `None` without phase
    /// statistics. The same prediction `encounter` makes before it executes.
    pub fn predict(&self, control: &[Rat]) -> Result<Option<NativeReadoutPrediction>, HnnError> {
        predict_native(self.owner.constitution(), &self.feature, control)
    }

    /// **Ask**: offer the admitted wave whose image of the retained family is the most
    /// distinguishing, or hold (module header). Nothing executes: no World step, deposit or carry.
    /// Candidates are the admitted waves whose image meets at least two outcome blocks; the
    /// offered one has the greatest total leverage, ties broken by the lexicographically least
    /// `u` (declared conventions). The probe is offered to the existing release law, which asks
    /// exactly when it is offered. The admitted waves are a declaration read from this same
    /// feature ([`AdmittedWaves::declared_for`]); another opening's declaration is refused.
    pub fn ask(&self, admitted: &AdmittedWaves) -> Result<ProbeDecision, HnnError> {
        if !admitted.declared_for(&self.feature) {
            return Err(foreign_declaration());
        }
        let feature = &self.feature;
        let phases = feature.phases();
        let station = feature.station();
        let Some(family) = declared_family(self.owner.constitution(), phases)? else {
            return Ok(ProbeDecision {
                release: decide_probe(station, None)?,
                control: None,
                prediction: None,
                candidates: 0,
                held: Some(ProbeHold::NoPhaseStatistics),
            });
        };
        let grain = phases.grain();
        let mut candidates = 0usize;
        let mut best: Option<Candidate> = None;
        for control in admitted.controls() {
            let x = feature.feature_at(control)?;
            let image = family.image(&x).map_err(|_| image_refusal())?;
            let Some(witnesses) = image.witnesses(grain).map_err(|_| blocks_refusal())? else {
                continue;
            };
            candidates += 1;
            let leverage = image.total_leverage();
            let better = best.as_ref().is_none_or(|held| {
                leverage > held.leverage || (leverage == held.leverage && control < &held.control)
            });
            if better {
                best = Some(Candidate {
                    control: control.clone(),
                    feature: x,
                    image,
                    witnesses,
                    leverage,
                });
            }
        }
        let Some(best) = best else {
            let reason = if admitted.is_empty() {
                ProbeHold::NoAdmittedWave
            } else {
                ProbeHold::NoSeparatingWave
            };
            return Ok(ProbeDecision {
                release: decide_probe(station, None)?,
                control: None,
                prediction: None,
                candidates,
                held: Some(reason),
            });
        };
        let blocks = best.image.blocks(grain).map_err(|_| blocks_refusal())?;
        let separation = LeverageSeparation::new(blocks.len(), best.leverage.clone(), Rat::zero())?;
        let control_text = best
            .control
            .iter()
            .map(|u| u.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        let probe = ObservationProbe {
            observation: format!(
                "the native station {station}'s phase readout after the admitted source wave u = [{control_text}]"
            ),
            partition: ProbeSeparation::Leverage(separation),
        };
        let released = decide_probe(station, Some(probe))?;
        let asked = matches!(released, ReleaseReturn::Ask { .. });
        Ok(ProbeDecision {
            release: released,
            control: asked.then(|| best.control.clone()),
            prediction: asked.then(|| NativeReadoutPrediction {
                station,
                feature: best.feature,
                image: best.image,
                blocks,
                witnesses: Some(best.witnesses),
            }),
            candidates,
            held: None,
        })
    }

    /// **Execute the probe at one admitted control**: exactly the actual World encounter, return,
    /// carry publication, receiving comparison and deposit that [`PreparedPhysicalAction::encounter`]
    /// performs (one shared execution), with this control applied by the shared physical
    /// application and no fibre or request. A control of the wrong shape is refused before any
    /// physical work. The native prediction for the control is made first, at the material the
    /// control meets; the executed World face is then read against it ([`PhaseDiscrepancy`]).
    pub fn encounter(
        self,
        admitted: &AdmittedWaves,
        control: &[Rat],
    ) -> Result<ProbeReception, HnnError> {
        Ok(self.encounter_teaching(admitted, control, &[])?.0)
    }

    /// **Execute the probe at one admitted control, carrying material tangents** (the held-carry
    /// record §3): exactly [`Self::encounter`]'s execution, with one [`MaterialTangent`] per declared
    /// direction riding the actual Word and, at the World port, the located World key's charts.
    /// Refused before any physical work unless the World model holds exactly one live key. The
    /// tangents return at the Word's reception carry, for the next Word's credit.
    pub fn encounter_teaching(
        self,
        admitted: &AdmittedWaves,
        control: &[Rat],
        directions: &[MaterialDirection],
    ) -> Result<(ProbeReception, Vec<MaterialTangent>), HnnError> {
        let Self {
            owner,
            word,
            feature,
            section,
            source_length,
            receiver_index,
            opening,
        } = self;
        if control.len() != feature.preparation().controls() {
            return Err(HnnError::Shape {
                what: "the admitted source wave control",
                expected: feature.preparation().controls(),
                found: control.len(),
            });
        }
        // An admitted wave is a checked membership in a declaration read from this same feature,
        // before any physical work (Epime's review, October 8).
        if !admitted.declared_for(&feature) {
            return Err(foreign_declaration());
        }
        if !admitted.contains(control) {
            return Err(HnnError::Unadmitted {
                reason: "the control is not a member of its admitted wave declaration",
            });
        }
        let prediction = predict_native(owner.constitution(), &feature, control)?;
        if owner.resident.held_contact_variation().is_some() {
            return Err(HnnError::Unadmitted {
                reason: "the held HNN-only contact differential has no actual World tangent and finite ray",
            });
        }
        let station = feature.station();
        let grain = feature.phases().grain();
        let (word, preparation, applied) = feature.prepare_control(word, control)?;
        let mut tangents = Vec::with_capacity(directions.len());
        let reception = owner.execute_prepared(
            word,
            preparation,
            applied,
            ActionFrame {
                section,
                source_length,
                receiver_index,
                opening,
            },
            directions,
            &mut tangents,
        )?;
        let discrepancy = discrepancy_of(&reception, station, grain, prediction.as_ref());
        Ok((
            ProbeReception {
                reception,
                prediction,
                discrepancy,
            },
            tangents,
        ))
    }
}
