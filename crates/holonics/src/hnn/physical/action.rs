/// A bound, unrun preparation. Borrowing the receiver bars interleaved material/current edits.
pub struct PreparedPhysicalAction<'r, 'f> {
    owner: &'r mut PhysicalReceiver<'f>,
    word: Word<'f>,
    prospective: ProspectiveControl,
    section: DamagedSection,
    source_length: usize,
    receiver_index: usize,
    opening: SourceOpeningReceipt,
}

impl PreparedPhysicalAction<'_, '_> {
    pub fn prospective(&self) -> &ProspectiveControl {
        &self.prospective
    }
    pub fn source_chart(&self) -> &Encoded {
        self.section.chart()
    }
    pub fn producing_commit(&self) -> u64 {
        self.prospective.producing_commit()
    }
    pub fn current(&self) -> &Current {
        self.prospective.current()
    }
    pub fn opened_at(&self) -> usize {
        self.prospective.opened_at()
    }
    pub fn receiving_phases(&self) -> &ReceivingPhases {
        self.prospective.phases()
    }

    /// **The World model's coupled prospect of this prepared action** (`model`, C1b-2a): per declared
    /// key, its coupled prospect of the controlled Word's passage, or that key's own refusal (a held
    /// or incompatible key, or charts it cannot read), so one key never withholds another's. It
    /// predicts the port waves and the native station features, not the World's observed face. The
    /// prepared Word stays unrun and nothing actual is read or written; a missing model or a plural
    /// or obstructed control refuses the whole read.
    pub fn world_prospect(&self) -> Result<Vec<Result<CoupledProspect, HnnError>>, HnnError> {
        let model = self.owner.world_model().ok_or(HnnError::Unadmitted {
            reason: "a World prospect reads the bound World model",
        })?;
        let word = self.prospective.controlled_word(&self.word)?;
        let ring = self.prospective.preparation().ring();
        Ok((0..model.keys().len())
            .map(|key| {
                model.coupled_prospect(
                    key,
                    &word,
                    ring,
                    self.prospective.phases(),
                    self.prospective.compared(),
                )
            })
            .collect())
    }

    /// Execute against the one actual World retained by this receiver's common Resident.
    /// A plural fibre remains held; no World branch, reset or guessed point is released.
    pub fn encounter(self) -> Result<ActionCommunication, HnnError> {
        let Self {
            owner,
            word,
            prospective,
            section,
            source_length,
            receiver_index,
            opening,
        } = self;
        if prospective.unique_control().is_none() {
            return Ok(ActionCommunication::Held { prospective });
        }
        if owner.resident.held_contact_variation().is_some() {
            return Err(HnnError::Unadmitted {
                reason: "the held HNN-only contact differential has no actual World tangent and finite ray",
            });
        }
        let (word, preparation, applied) = prospective.prepare(word)?;
        // The post-preparation execution is one function for a request's unique control and a
        // probe's admitted control: the same actual World encounter, return, carry publication,
        // receiving comparison and deposit.
        owner.execute_prepared(
            word,
            preparation,
            applied,
            ActionFrame {
                section,
                source_length,
                receiver_index,
                opening,
            },
        )
    }
}

